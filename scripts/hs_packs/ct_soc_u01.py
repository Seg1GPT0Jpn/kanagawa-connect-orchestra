PERMS = [(0, 1, 2), (0, 2, 1), (1, 0, 2), (1, 2, 0), (2, 0, 1), (2, 1, 0)]


def pick_events(r, k, gap=3):
    while True:
        evs = sorted(r.sample(EVENTS, k))
        ys = [e[0] for e in evs]
        if all(b - a >= gap for a, b in zip(ys, ys[1:])) and ys[-1] - ys[0] <= 60:
            return evs


