def wave_svg(n_div, amp, cols=10):
    """オシロスコープの画面（横 cols 目盛り、縦 6 目盛り）。1 回の振動に n_div 目盛り、振幅 amp 目盛り。"""
    import math
    u = 22
    W, H = cols * u, 6 * u
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W + 20} {H + 20}" width="{W + 20}" height="{H + 20}" font-family="serif" font-size="10">',
           f'<rect x="10" y="10" width="{W}" height="{H}" fill="#fff" stroke="#000"/>']
    for i in range(1, cols):
        out.append(f'<line x1="{10 + i * u}" y1="10" x2="{10 + i * u}" y2="{10 + H}" stroke="#ccc" stroke-width="0.6"/>')
    for j in range(1, 6):
        out.append(f'<line x1="10" y1="{10 + j * u}" x2="{10 + W}" y2="{10 + j * u}" stroke="#ccc" stroke-width="0.6"/>')
    pts = []
    for k in range(cols * 20 + 1):
        x = k / 20
        y = amp * math.sin(2 * math.pi * x / n_div)
        pts.append(f"{10 + x * u:.1f},{10 + H / 2 - y * u:.1f}")
    out.append(f'<polyline points="{" ".join(pts)}" fill="none" stroke="#1f4e79" stroke-width="1.6"/>')
    out.append("</svg>")
    return "".join(out)


