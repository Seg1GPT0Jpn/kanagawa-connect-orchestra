def lat_txt(a):
    return "赤道（緯度0度）" if a == 0 else (f"北緯{a}度" if a > 0 else f"南緯{-a}度")


def lon_txt(L):
    if L == 0:
        return "経度0度"
    if abs(L) == 180:
        return "経度180度"
    L = int(L) if float(L).is_integer() else L
    return f"東経{L}度" if L > 0 else f"西経{-L}度"


def jtime(t, date=True):
    """2026年の日時を「1月9日午後7時」の形にする（0時は午前0時、12時は午後0時）。"""
    ap = "午前" if t.hour < 12 else "午後"
    s = f"{ap}{t.hour % 12}時"
    return f"{t.month}月{t.day}日{s}" if date else s


def tz_hours(L):
    """標準時子午線の経度 L（東経を正、西経を負）から、経度0度との時差（時間）を求める。"""
    assert L % 15 == 0
    return L // 15


def local_time(t_tokyo, L):
    """東京（東経135度）の日時 t_tokyo のとき、標準時子午線 L の地点の日時。"""
    return t_tokyo - timedelta(hours=tz_hours(135) - tz_hours(L))


