def great_circle(p, q):
    """球面上の2点 p,q（度）の大圏距離（km、地球の半径 6371 km）と、p から見た方位角（北から時計回り、度）。"""
    f1, l1, f2, l2 = map(math.radians, (p[0], p[1], q[0], q[1]))
    dl = l2 - l1
    a = math.sin((f2 - f1) / 2) ** 2 + math.cos(f1) * math.cos(f2) * math.sin(dl / 2) ** 2
    d = 2 * 6371 * math.asin(math.sqrt(a))
    b = math.degrees(math.atan2(math.sin(dl) * math.cos(f2), math.cos(f1) * math.sin(f2) - math.sin(f1) * math.cos(f2) * math.cos(dl)))
    return d, b % 360


def dir8(b):
    """方位角を8方位にし、8方位の中心からのずれ（度）も返す。"""
    k = int(((b + 22.5) % 360) // 45)
    return DIR8[k], abs(((b - 45 * k + 180) % 360) - 180)


