def kz(x):
    """問題文・選択肢の読点を入試冊子と同じ「，」にそろえる（辞書のキーも同じ変換をする）。"""
    if isinstance(x, str):
        return x.replace("、", "，")
    if isinstance(x, dict):
        return {kz(k): kz(v) for k, v in x.items()}
    if isinstance(x, list):
        return [kz(v) for v in x]
    if isinstance(x, tuple):
        return tuple(kz(v) for v in x)
    return x


def kgen(level, n, ps, rel=None):
    """hs_pack_lib.gen と同じ。生成した問題の表記を kz で入試形式にそろえる。"""
    def deco(fn):
        @functools.wraps(fn)
        def wrapped(r):
            it = fn(r)
            for key in ("s", "c", "e", "why", "ap", "steps", "alt", "pit", "err"):
                if key in it:
                    it[key] = kz(it[key])
            return it
        return _gen(level, n, ps, rel)(wrapped)
    return deco


def mc4(stem, right, wrongs, e, **kw):
    """正答と誤答候補 [(文, 理由, 誤概念)] から、重複を除いて 4 択を作る。
    誤答は文の順にそろえ、同じ組み合わせが別の問題として数えられないようにする。"""
    ch, why = [], {}
    for w, reason, mis in wrongs:
        if w == right or w in why:
            continue
        why[w] = (reason, mis)
        if len(why) == 3:
            break
    assert len(why) == 3, (stem, right, wrongs)
    ch = [right] + sorted(why)
    return mc(stem, ch, e, why=why, **kw)


def combo(stem, heads, opts, correct, bad, e, ask=None, **kw):
    """組み合わせ選択（「あ：…　い：…」）。最初の空欄ほどゆっくり変わる順に並べる。
    opts=[[候補...], ...]、correct=[正しい候補の番号...]、bad[n]={誤った候補: (理由, 誤概念)}。"""
    choices, why, ai = [], {}, 0
    for idx in itertools.product(*[range(len(o)) for o in opts]):
        text = "　".join(f"{h}：{o[k]}" for h, o, k in zip(heads, opts, idx))
        if tuple(idx) == tuple(correct):
            ai = len(choices)
        else:
            rs = [bad[n][opts[n][k]] for n, k in enumerate(idx) if k != correct[n]]
            why[text] = ("".join(x[0] for x in rs), rs[0][1])
        choices.append(text)
    n = len(choices)
    q = ask or f"の組み合わせとして最も適するものを，次の1〜{n}の中から一つ選び，その番号を答えなさい。"
    return mc(f"{stem}{q}", choices, e, why=why, keep=True, ai=ai, **kw)


def seigo(lead, stmts, e, **kw):
    """X・Y（・Z）の正誤の組み合わせ。stmts=[(文, 正しいか, 説明)]。"""
    labs = "XYZ"[:len(stmts)]
    body = "\n".join(f"{labs[i]}　{s[0]}" for i, s in enumerate(stmts))
    choices, why, ai = [], {}, 0
    for pick in itertools.product([True, False], repeat=len(stmts)):
        text = "　".join(f"{labs[i]}：{'正' if v else '誤'}" for i, v in enumerate(pick))
        wrong = [i for i, v in enumerate(pick) if v != stmts[i][1]]
        if not wrong:
            ai = len(choices)
        else:
            why[text] = ("".join(f"{labs[i]}は{'正しい' if stmts[i][1] else '誤り'}。{stmts[i][2]}" for i in wrong), "記述の正誤の判断の誤り")
        choices.append(text)
    n = len(choices)
    return mc(f"{lead}次の文{'・'.join(labs)}の正誤の組み合わせとして最も適するものを，あとの1〜{n}の中から一つ選び，その番号を答えなさい。\n{body}",
              choices, e, why=why, keep=True, ai=ai, **kw)


def pick2(lead, stmts, e, **kw):
    """文a〜dのうち正しいもの2つの組み合わせ（6択）。stmts=[(文, 正しいか, 説明)]。"""
    lab = "abcd"
    assert len(stmts) == 4 and sum(1 for s in stmts if s[1]) == 2, stmts
    body = "\n".join(f"{lab[i]}　{s[0]}" for i, s in enumerate(stmts))
    choices, why, ai = [], {}, 0
    for i, j in itertools.combinations(range(4), 2):
        t = f"{lab[i]}と{lab[j]}"
        if stmts[i][1] and stmts[j][1]:
            ai = len(choices)
        else:
            why[t] = ("".join(f"{lab[k]}は誤り。{stmts[k][2]}" for k in (i, j) if not stmts[k][1]), "資料の読み取りや知識の誤り")
        choices.append(t)
    return mc(f"{lead}次の文a〜dのうち，正しいものの組み合わせとして最も適するものを，あとの1〜6の中から一つ選び，その番号を答えなさい。\n{body}",
              choices, e, why=why, keep=True, ai=ai, **kw)


def order3(lead, items, key_note, e, **kw):
    """Ⅰ〜Ⅲの並べかえ（6択）。items=[(表示する文, 並べる順位)]（順位の小さい方が先）。"""
    roman = "ⅠⅡⅢ"
    body = "\n".join(f"{roman[i]}　{t}" for i, (t, _) in enumerate(items))
    correct = sorted(range(3), key=lambda i: items[i][1])
    right = "→".join(roman[i] for i in correct)
    choices, why, ai = [], {}, 0
    for p in itertools.permutations(range(3)):
        t = "→".join(roman[i] for i in p)
        if list(p) == correct:
            ai = len(choices)
        else:
            why[t] = (f"正しい順は {right} である。{key_note}", "順序の判断の誤り")
        choices.append(t)
    return mc(f"{lead}\n{body}", choices, e, why=why, keep=True, ai=ai, **kw)


