def grid_svg(points):
    """経線・緯線を30度ごとにえがいた略地図（大陸は省略）。points=[(記号, 緯度, 経度)]。"""
    s, ox, oy = 0.85, 34, 14
    X = lambda L: ox + (L + 180) * s  # noqa: E731
    Y = lambda a: oy + (90 - a) * s  # noqa: E731
    W, H = int(X(180) + 30), int(Y(-90) + 30)
    out = [svg_open(W, H), f'<rect x="{X(-180)}" y="{Y(90)}" width="{360 * s}" height="{180 * s}" fill="#f4f8fc" stroke="#000" stroke-width="0.8"/>']
    for L in range(-150, 180, 30):
        w = 1.4 if L == 0 else 0.5
        out.append(f'<line x1="{X(L):.1f}" y1="{Y(90):.1f}" x2="{X(L):.1f}" y2="{Y(-90):.1f}" stroke="#555" stroke-width="{w}"/>')
        out.append(f'<text x="{X(L):.1f}" y="{Y(-90) + 11:.1f}" font-size="8" text-anchor="middle">{abs(L)}</text>')
    for a in range(-60, 90, 30):
        w = 1.4 if a == 0 else 0.5
        out.append(f'<line x1="{X(-180):.1f}" y1="{Y(a):.1f}" x2="{X(180):.1f}" y2="{Y(a):.1f}" stroke="#555" stroke-width="{w}"/>')
        out.append(f'<text x="{X(-180) - 3:.1f}" y="{Y(a) + 3:.1f}" font-size="8" text-anchor="end">{abs(a)}</text>')
    out.append(f'<text x="{X(-180) + 4:.1f}" y="{Y(-90) + 22:.1f}" font-size="9">← 西経</text>')
    out.append(f'<text x="{X(180) - 4:.1f}" y="{Y(-90) + 22:.1f}" font-size="9" text-anchor="end">東経 →</text>')
    out.append(f'<text x="{X(0):.1f}" y="{Y(-90) + 22:.1f}" font-size="8" text-anchor="middle">本初子午線</text>')
    out.append(f'<text x="{X(-180) - 3:.1f}" y="{Y(80):.1f}" font-size="8" text-anchor="end">北緯</text>')
    out.append(f'<text x="{X(-180) - 3:.1f}" y="{Y(-80):.1f}" font-size="8" text-anchor="end">南緯</text>')
    out.append(f'<text x="{X(-175):.1f}" y="{Y(0) - 3:.1f}" font-size="8">赤道</text>')
    for lab, a, L in points:
        out.append(f'<circle cx="{X(L):.1f}" cy="{Y(a):.1f}" r="3" fill="#000"/>')
        out.append(f'<text x="{X(L) + 4:.1f}" y="{Y(a) - 4:.1f}" font-size="11" font-weight="bold">{lab}</text>')
    out.append("</svg>")
    return "".join(out)


def azimuthal_svg(cities):
    """東京を中心とする正距方位図法の模式図（大陸は省略。都市の位置は大圏距離と方位角から計算）。"""
    R, c = 120, 150
    k = R / 20000
    out = [svg_open(2 * c, 2 * c)]
    for d in (5000, 10000, 15000, 20000):
        out.append(f'<circle cx="{c}" cy="{c}" r="{d * k:.1f}" fill="none" stroke="#888" stroke-width="{1.2 if d == 20000 else 0.5}" stroke-dasharray="{"" if d == 20000 else "3 2"}"/>')
        out.append(f'<text x="{c + 2}" y="{c - d * k + 10:.1f}" font-size="8" fill="#555">{d:,}km</text>')
    out.append(f'<line x1="{c}" y1="{c - R - 6}" x2="{c}" y2="{c + R}" stroke="#bbb" stroke-width="0.5"/>')
    out.append(f'<line x1="{c - R}" y1="{c}" x2="{c + R}" y2="{c}" stroke="#bbb" stroke-width="0.5"/>')
    out.append(f'<text x="{c - 4}" y="{c - R - 9}" font-size="10">北</text>')
    out.append(f'<circle cx="{c}" cy="{c}" r="3" fill="#000"/><text x="{c + 4}" y="{c + 12}" font-size="10" font-weight="bold">東京</text>')
    for name in cities:
        d, b = great_circle(TOKYO, CITY_LL[name])
        x = c + d * k * math.sin(math.radians(b))
        y = c - d * k * math.cos(math.radians(b))
        anchor = "end" if x > c + 60 else "start"
        dx = -4 if anchor == "end" else 4
        out.append(f'<circle cx="{x:.1f}" cy="{y:.1f}" r="2.5" fill="#000"/><text x="{x + dx:.1f}" y="{y - 3:.1f}" font-size="9" text-anchor="{anchor}">{name}</text>')
    out.append("</svg>")
    return "".join(out)


