def _samples(r, n_small, n_big, p):
    """標本の大きさが小さい調査と大きい調査それぞれ5回分の該当数（架空）。"""
    small = [max(0, min(n_small, round(n_small * p + r.randint(-3, 3)))) for _ in range(5)]
    big = [max(0, min(n_big, round(n_big * p + r.randint(-4, 4)))) for _ in range(5)]
    return small, big


