    while True:
        a = r.choice([40, 50, 60, 80, 90, 100, 120, 150, 200])
        n = r.choice([30, 40, 45, 50, 60, 70, 80, 90, 100, 120])
        k = r.randint(2, 15)
        if k < n // 3 and (a * n) % k == 0:
            break
    v = a * n // k
    animal, place, how = r.choice([("魚", "池", "網で"), ("コイ", "沼", "網で"), ("ザリガニ", "用水路", "わなで"), ("バッタ", "草原", "虫とり網で")])
