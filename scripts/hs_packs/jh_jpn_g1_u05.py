@gen("thinking_writing", 3, ["application", "condition_check"])
def pair_select(r):
    s = r.choice(S)
    tr = [x for x in s["stmts"] if x[1]]
    fa = [x for x in s["stmts"] if not x[1]]
    stmts = tr + r.sample(fa, 4)
    r.shuffle(stmts)
    lab = "abcdef"
    m = {lab[i]: x for i, x in enumerate(stmts)}
    right = [k for k in lab if m[k][1]]
    ok = f"{right[0]}と{right[1]}"
    pairs = [f"{a}と{b}" for a, b in itertools.combinations(lab, 2)]
    pick = sorted(r.sample([p for p in pairs if p != ok], 7) + [ok], key=pairs.index)
    why = {}
    for c in pick:
        if c == ok:
            continue
        a, b = c.split("と")
        why[c] = ("　".join(f"{k} は誤り。{m[k][2]}" for k in (a, b) if not m[k][1]), "本文の内容との照合の誤り")
    body = "\n".join(f"{k}　{m[k][0]}" for k in lab)
    return mc("本文の内容に合うものを、次の a〜f の中から二つ選んだとき、その組み合わせとして最も適するものを、あとの1〜8の中から一つ選び、その番号を答えなさい。\n" + body,
              pick, f"本文に合うのは {ok}。" + "　".join(f"{k}：{m[k][2]}" for k in lab), ai=pick.index(ok), keep=True, why=why,
              d=4, k=RT, stim=sstim(s), p=6,
              ap="a〜f の一つ一つに、本文と照らし合わせて○×をつけてから組み合わせを選ぶ。",
              steps=["a〜f のそれぞれに関係する部分を本文から見つける。", "人物・時間・行動の細かいちがいまで確かめ、○×をつける。", f"○の二つを組み合わせる：{ok}。"],
              alt=["×をつけた文について、本文のどの言葉とくい違うかを書き出して確かめる。"],
              pc=[("一つ目の正しい文を選んでいる", 3), ("二つ目の正しい文を選んでいる", 3)],
              pit=["前半と後半の場面の出来事を取り違える。", "リード文の内容を読み落とす。"])


