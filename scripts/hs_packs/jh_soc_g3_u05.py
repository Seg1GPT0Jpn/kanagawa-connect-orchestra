def sep_svg(labels):
    """三権分立の模式図。labels={矢印の番号: 記号}。記号のない矢印は内容を書く。"""
    out = ['<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 420 240" width="420" height="240" font-family="sans-serif" font-size="11">',
           '<defs><marker id="ah" markerWidth="8" markerHeight="8" refX="7" refY="4" orient="auto"><path d="M0,0 L8,4 L0,8 z" fill="#333"/></marker></defs>']
    for name, (x, y) in POS.items():
        w = 64 if name != "国民" else 52
        fill = "#eef4fb" if name != "国民" else "#fdf1d8"
        out.append(f'<rect x="{x - w / 2}" y="{y - 14}" width="{w}" height="28" rx="6" fill="{fill}" stroke="#1f4e79"/>')
        out.append(f'<text x="{x}" y="{y + 4}" text-anchor="middle" font-weight="bold">{name}</text>')
    for k, (a, b, txt) in enumerate(ARROWS):
        (x1, y1), (x2, y2) = POS[a], POS[b]
        dx, dy = x2 - x1, y2 - y1
        L = math.hypot(dx, dy)
        ux, uy = dx / L, dy / L
        nx, ny = -uy, ux
        off = 7 if a != "国民" else 0
        sx, sy = x1 + ux * 34 + nx * off, y1 + uy * 20 + ny * off
        ex, ey = x2 - ux * 34 + nx * off, y2 - uy * 20 + ny * off
        out.append(f'<line x1="{sx:.1f}" y1="{sy:.1f}" x2="{ex:.1f}" y2="{ey:.1f}" stroke="#333" marker-end="url(#ah)"/>')
        mx, my = (sx + ex) / 2 + nx * 12, (sy + ey) / 2 + ny * 12
        lab = labels.get(k)
        if lab:
            out.append(f'<text x="{mx:.1f}" y="{my + 4:.1f}" text-anchor="middle" font-weight="bold" font-size="13">{lab}</text>')
    out.append("</svg>")
    return "".join(out)


