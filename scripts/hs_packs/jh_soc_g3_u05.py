def dhondt(votes, seats):
    """ドント式。votes=[得票...]，seats=定数。各党の議席数と，当選に使われた商の一覧を返す。"""
    qs = []
    for i, v in enumerate(votes):
        for d in range(1, seats + 1):
            qs.append((Fraction(v, d), i, d))
    qs.sort(key=lambda x: (-x[0], x[1]))
    win = qs[:seats]
    alloc = [0] * len(votes)
    for _, i, _ in win:
        alloc[i] += 1
    return alloc, qs


def dhondt_ok(votes, seats):
    """当選・落選の境目で商が同じにならない（くじ引きにならない）かを確かめる。"""
    _, qs = dhondt(votes, seats)
    return qs[seats - 1][0] != qs[seats][0]


def hare(votes, seats):
    """得票の割合に比例させて最大剰余で配分する（ドント式との比較用の誤答）。"""
    tot = sum(votes)
    raw = [Fraction(v * seats, tot) for v in votes]
    out = [int(x) for x in raw]
    order = sorted(range(len(votes)), key=lambda i: raw[i] - int(raw[i]), reverse=True)
    k = 0
    while sum(out) < seats:
        out[order[k]] += 1
        k += 1
    return out


