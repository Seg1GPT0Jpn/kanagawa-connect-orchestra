def code(lines):
    return "\n".join(f"({i + 1}) {l}" for i, l in enumerate(lines))


def arr(xs):
    return "[" + ", ".join(map(str, xs)) + "]"


def bin_s(n, width=0):
    s = format(n, "b")
    return s.zfill(width) if width else s


def weights_expr(s):
    k = len(s)
    return "+".join(f"{d}*2**{k - 1 - i}" for i, d in enumerate(s))


def weights_tex(s):
    k = len(s)
    return "+".join(f"{d}\\times2^{{{k - 1 - i}}}" for i, d in enumerate(s))


def med(xs):
    xs = sorted(xs)
    n = len(xs)
    return xs[n // 2] if n % 2 else (xs[n // 2 - 1] + xs[n // 2]) / 2


def quart(xs):
    xs = sorted(xs)
    n = len(xs)
    return med(xs[: n // 2]), med(xs), med(xs[(n + 1) // 2:])


def fmt(v):
    return str(int(v)) if float(v).is_integer() else f"{v:g}"


def py(v):
    return str(int(v)) if float(v).is_integer() else f"Rational({int(round(v * 2))},2)"


