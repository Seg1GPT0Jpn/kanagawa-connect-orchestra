def sum_prog(r):
    s0 = r.choice([0, 0, 1, 2, 5, 10])
    a = r.randint(1, 3)
    c = r.choice([1, 2, 3])
    b = a + c * r.randint(3, 5)
    f = r.choice(["i", "i × 2", "i × i", "i + 1"])
    fv = {"i": lambda i: i, "i × 2": lambda i: 2 * i, "i × i": lambda i: i * i, "i + 1": lambda i: i + 1}[f]
    fp = {"i": "{}", "i × 2": "2*{}", "i × i": "{}**2", "i + 1": "({}+1)"}[f]
    var = r.choice(["goukei", "wa", "s"])
    lines = [f"{var} = {s0}", f"i を {a} から {b} まで {c} ずつ増やしながら繰り返す:", f"｜　{var} = {var} + {f}", f"表示する({var})"]
    seq = list(range(a, b + 1, c))
    ans = s0 + sum(fv(i) for i in seq)
    trace, cur = [], s0
    for i in seq:
        cur += fv(i)
        trace.append(f"i = {i}：{var} = {cur}")
    expr = f"{s0}+" + "+".join(fp.format(i) for i in seq)
    return dict(lines=lines, ans=ans, seq=seq, trace=trace, expr=expr, s0=s0, f=f, fv=fv, var=var, a=a, b=b, c=c)


def halving_prog(r):
    n = r.randint(9, 300)
    lines = ["x = " + str(n), "kaisu = 0", "x > 0 の間繰り返す:", "｜　x = （x を 2 で割った商）", "｜　kaisu = kaisu + 1", "表示する(kaisu)"]
    xs, x = [], n
    while x > 0:
        x //= 2
        xs.append(x)
    return dict(lines=lines, ans=len(xs), n=n, xs=xs)


