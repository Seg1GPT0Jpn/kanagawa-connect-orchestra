                ap="生徒が使った定義（並べかえの有無、範囲と四分位範囲）を確認し、正しい定義と比べる。",
                steps=[f"生徒の誤り：{why}", f"並べかえる：{', '.join(map(str, sorted(xs)))}。", ans],
