@gen("basic_check", 4, ["computation", "condition_check"])
def a_base_convert(r):
    mode = r.choice(["b2d", "b2d", "d2b", "h2d", "b2h"])
    if mode == "b2d":
        n = r.randint(37, 250)
        s = bin_s(n)
        return num(f"2進数 ${s}_{{(2)}}$ を10進数で表しなさい。", str(n), f"${weights_tex(s)}={n}$。", d=1,
                   ap="右端の桁から重み $2^0, 2^1, 2^2, \\dots$ を書きこみ、1 の桁の重みだけを足す。",
                   steps=[f"各桁の重みを書く：${weights_tex(s)}$。", "1 の桁の重みを足す。", f"答え：{n}"],
                   alt=[f"10進数 {n} を2で割り続けて余りを下から読み、${s}_{{(2)}}$ に戻ることを確かめる。"],
                   pc=[("各桁の重みを正しく書いている", 1), ("正しい値を求めている", 1)],
                   pit=["右端の桁の重みを 2 から始める。"], chk=(weights_expr(s), str(n)))
    if mode == "d2b":
        n = r.randint(20, 200)
        s = bin_s(n)
