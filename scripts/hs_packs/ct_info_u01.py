@gen("error_correction", 3, ["common_error", "computation"])
def d_stats_err(r):
    n = r.choice([7, 9, 8, 10])
    for _ in range(100):
        xs = [r.randint(10, 60) for _ in range(n)]
        m = med(xs)
        raw = xs[n // 2] if n % 2 else (xs[n // 2 - 1] + xs[n // 2]) / 2
        if raw != m:
            break
    s = ", ".join(map(str, xs))
    mis = r.choice(["unsorted", "iqr"])
    if mis == "unsorted":
        sol = f"中央の位置にある値をそのまま使い、中央値は {fmt(raw)} と答えた。"
