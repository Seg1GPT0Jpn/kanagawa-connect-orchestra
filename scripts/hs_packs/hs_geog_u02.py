def _data_rows(r):
    while True:
        names = r.sample(["国 K", "国 L", "国 M", "国 N", "国 P", "国 Q"], 4)
        gnis = sorted(r.sample([800, 1500, 2500, 4000, 6000, 9000, 15000, 25000, 40000, 50000], 4))
        rows = []
        for i, gni in enumerate(gnis):
            tfr = round(r.uniform(4.8, 5.8) - i * r.uniform(1.1, 1.4), 1)
            imr = max(2, int(r.uniform(55, 75) - i * r.uniform(17, 23)))
            old = max(2, int(3 + i * r.uniform(4, 7)))
            rows.append([names[i], gni, max(1.2, tfr), imr, old])
        r.shuffle(rows)
        if len({x[3] for x in rows}) == 4 and len({x[2] for x in rows}) == 4 and len({x[4] for x in rows}) == 4:
            return rows


