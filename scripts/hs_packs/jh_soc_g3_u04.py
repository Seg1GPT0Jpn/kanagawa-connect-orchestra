def pick3(r, lead, stmts, e, **kw):
    """文a〜fのうち正しいもの3つの組み合わせ（8択，「a，c，e」の形）。stmts=[(文, 正しいか, 説明)]。"""
    assert len(stmts) == 6 and sum(1 for s in stmts if s[1]) == 3, stmts
    body = "\n".join(f"{LAB6[i]}　{s[0]}" for i, s in enumerate(stmts))
    good = tuple(i for i, s in enumerate(stmts) if s[1])
    others = [c for c in itertools.combinations(range(6), 3) if c != good]
    # 正しい文を2つふくむ組み合わせ（まぎらわしい誤答）を多めに入れる
    near = [c for c in others if len(set(c) & set(good)) == 2]
    far = [c for c in others if len(set(c) & set(good)) < 2]
    r.shuffle(near)
    r.shuffle(far)
    picks = sorted(near[:5] + far[:2]) + [good]
    picks = sorted(picks)
    choices, why, ai = [], {}, 0
    for c in picks:
        t = "，".join(LAB6[i] for i in c)
        if c == good:
            ai = len(choices)
        else:
            bad = [i for i in c if not stmts[i][1]]
            why[t] = ("".join(f"{LAB6[i]}は誤り。{stmts[i][2]}" for i in bad), "資料の読み取りや知識の誤り")
        choices.append(t)
    return mc(f"{lead}次の文a〜fのうち，正しいものの組み合わせとして最も適するものを，あとの1〜8の中から一つ選び，その番号を答えなさい。\n{body}",
              choices, e, why=why, keep=True, ai=ai, **kw)


