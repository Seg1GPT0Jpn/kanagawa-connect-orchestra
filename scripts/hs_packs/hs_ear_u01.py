def _quads():
    out = []
    for z in range(3, 13):
        pts = []
        for dx in range(-12, 13):
            for dy in range(-12, 13):
                s2 = dx * dx + dy * dy + z * z
                d = math.isqrt(s2)
                if d * d == s2 and (dx or dy):
                    pts.append((dx, dy, d))
        if len(pts) >= 3:
            out.append((z, pts))
    return out


QUADS = _quads()


