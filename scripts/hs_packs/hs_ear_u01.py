def _triples(maxc=260):
    by = {}
    for x in range(1, maxc):
        for z in range(8, 61):
            c = math.isqrt(x * x + z * z)
            if c * c == x * x + z * z and c <= maxc:
                by.setdefault(z, []).append((x, c))
    return {z: v for z, v in by.items() if len(v) >= 2}


