def pick_verb(r):
    k = r.random()
    if k < 0.35:
        return r.choice(GODAN)
    if k < 0.55:
        return r.choice(KAMI)[0]
    if k < 0.8:
        return r.choice(SHIMO)[0]
    if k < 0.88:
        return "来る"
    return r.choice(["する"] + SAHEN)


@gen("basic_check", 5, ["computation", "condition_check"])
def a_vtype(r):
    w = r.choice(TRAP_GODAN) if r.random() < 0.3 else pick_verb(r)
    ok = VT[w]
    wrongs = r.sample([t for t in TYPES if t != ok], 3)
    why = {t: (f"{TYPE_WHY[t]}。「{w}」は{type_reason(w)}である。", "活用の種類の判定の誤り") for t in wrongs}
    rdg = "（くる）" if w == "来る" else ""
    return mc(f"動詞「{w}」{rdg}の活用の種類として最も適するものを、{CH}", choices(ok, wrongs),
              f"「{w}」は{type_reason(w)}である。", d=1,
              ap="まず「来る」「する（名詞＋する）」かどうかを確かめる。そうでなければ「ない」をつけて、直前の音の段を見る。",
              steps=["「来る」「する」「名詞＋する」に当たるかを確かめる。", f"判定：{type_reason(w)}。", f"答え：{ok}"],
              alt=[f"活用表を書いてみて、活用語尾が五つの段にわたるか、イ段・エ段に「る・れ・ろ」がつく形かで確かめる（{row_label(w)}）。"],
              pc=[("「ない」をつけて判定している", 1), ("活用の種類を正しく選んでいる", 1)],
              pit=["終止形が「～いる」「～える」なら一段活用と決めつける（帰る・切るは五段）。", "「ます」をつけて判定しようとする。"], why=why)


