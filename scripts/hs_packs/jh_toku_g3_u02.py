def MC(stem, right, cands, e, nw=3, **kw):
    """cands=[(誤答の文, 理由, 誤概念)]。重複を除いて nw 個の誤答を使う。"""
    seen, ws = {right}, []
    for t, why, mis in cands:
        if t in seen:
            continue
        seen.add(t)
        ws.append((t, why, mis))
        if len(ws) == nw:
            break
    assert len(ws) == nw, (stem[:40], right, cands)
    return mc(stem, [right] + [w[0] for w in ws], e, why={w[0]: (w[1], w[2]) for w in ws}, **kw)


def robust(g):
    fn = g.fn

    def wrapped(r):
        for _ in range(80):
            try:
                return fn(r)
            except AssertionError:
                r = _random.Random(r.random())
        return fn(r)
    wrapped.__name__ = fn.__name__
    g.fn = wrapped
    return g


def nchar(s):
    """字数（句読点・記号・数字1けたをそれぞれ1字と数える）。"""
    return len(s)


def ceil5(n):
    return int(math.ceil(n / 5) * 5)


def nsent(s):
    """文の数（句点で数える。最後が句点で終わることを前提にする）。"""
    return s.count("。") if s.endswith("。") else -1


