def two_conds(good):
    n = nchar(good)
    lo, hi = ceil5(n) - 15, ceil5(n) + 5
    return lo, hi


def two_viol(c, lo, hi, word="賛成"):
    v = []
    if nsent(c) != 2:
        v.append("ONE")
    if not any(ch.isdigit() for ch in c.replace("資料1", "").replace("資料2", "")):  # 資料番号は数値に数えない
        v.append("NUM")
    if word not in c:
        v.append("WORD")
    if not lo <= nchar(c) <= hi:
        v.append("COUNT")
    return v


