def _f3(mode):
    """孫の代（AA：Aa：aa＝1：2：1）を使った次の代の比を、かけ合わせから求める。"""
    f2 = cross("Aa", "Aa")
    if mode == "self_dom":   # 孫の顕性の個体をそれぞれ自家受粉
        pool = {g: f2[g] for g in ("AA", "Aa")}
        partner = None
    elif mode == "self_all":  # 孫のすべての個体をそれぞれ自家受粉
        pool = dict(f2)
        partner = None
    else:                     # 孫の顕性の個体をそれぞれ aa とかけ合わせる
        pool = {g: f2[g] for g in ("AA", "Aa")}
        partner = "aa"
    tot = sum(pool.values())
    dom = Fraction(0)
    for g, w in pool.items():
        c = cross(g, partner or g)
        dom += Fraction(w, tot) * Fraction(c["AA"] + c["Aa"], 4)
    rec = 1 - dom
    L = (dom.denominator * rec.denominator) // gcd(dom.denominator, rec.denominator)
    a, b = int(dom * L), int(rec * L)
    g_ = gcd(a, b)
    return a // g_, b // g_


