def _cell(x, y, stage, w=72, h=58):
    """体細胞分裂の各時期の細胞（模式図）。"""
    o = [f'<rect x="{x}" y="{y}" width="{w}" height="{h}" fill="#fbfbf3" stroke="#333"/>']
    cx, cy = x + w / 2, y + h / 2
    if stage == 0:  # 核がある（分裂前）
        o.append(f'<circle cx="{cx}" cy="{cy}" r="13" fill="#e8e0f0" stroke="#333"/>')
        o.append(f'<circle cx="{cx + 3}" cy="{cy - 2}" r="3" fill="#888"/>')
    elif stage == 1:  # 染色体が現れる
        for dx, dy, a in ((-10, -6, 30), (6, -9, -20), (-4, 6, 70), (10, 5, 10), (-12, 8, -40), (2, -1, 50)):
            o.append(f'<line x1="{cx + dx - 4}" y1="{cy + dy}" x2="{cx + dx + 4}" y2="{cy + dy}" stroke="#7a2a8a" stroke-width="3" transform="rotate({a} {cx + dx} {cy + dy})"/>')
    elif stage == 2:  # 中央に並ぶ
        for k in range(6):
            yy = cy - 17 + k * 7
            o.append(f'<line x1="{cx - 4}" y1="{yy}" x2="{cx + 4}" y2="{yy}" stroke="#7a2a8a" stroke-width="3"/>')
    elif stage == 3:  # 両端に分かれる
        for side in (-1, 1):
            for k in range(6):
                yy = cy - 15 + k * 6
                xx = cx + side * 24
                o.append(f'<line x1="{xx - 3}" y1="{yy}" x2="{xx + 3}" y2="{yy}" stroke="#7a2a8a" stroke-width="3"/>')
    else:  # 仕切りができて2つの細胞になる
        o.append(f'<line x1="{cx}" y1="{y}" x2="{cx}" y2="{y + h}" stroke="#333" stroke-width="1.5"/>')
        for side in (-1, 1):
            o.append(f'<circle cx="{cx + side * 18}" cy="{cy}" r="9" fill="#e8e0f0" stroke="#333"/>')
    return "".join(o)


