def gametes(g):
    """遺伝子の組み合わせ 'Aa' → 生殖細胞の遺伝子 ['A', 'a']（それぞれ同じ割合でできる）。"""
    return [g[0], g[1]]


def norm(a, b):
    """2つの遺伝子を、顕性（大文字）を先に書いた組み合わせにする。"""
    return "".join(sorted([a, b], key=lambda c: (c.islower(), c)))


def cross(p, q):
    """p×q の子の遺伝子の組み合わせの数（4 マスのかけ合わせの表）。"""
    return Counter(norm(x, y) for x in gametes(p) for y in gametes(q))


def ratio_text(nums):
    g = 0
    for n in nums:
        g = gcd(g, n)
    return "：".join(str(n // g) for n in nums)


def geno_ratio(c):
    """遺伝子の組み合わせの比 'AA：Aa：aa＝1：2：1'（数が 0 のものは書かない）。"""
    keys = [k for k in ("AA", "Aa", "aa") if c.get(k)]
    return "：".join(keys) + "＝" + ratio_text([c[k] for k in keys])


def pheno(c):
    """（顕性の形質の数, 潜性の形質の数）"""
    return c["AA"] + c["Aa"], c["aa"]


def pheno_text(c, dom, rec):
    d, r_ = pheno(c)
    if r_ == 0:
        return f"すべて{dom}"
    if d == 0:
        return f"すべて{rec}"
    return f"{dom}：{rec}＝{ratio_text([d, r_])}"


def punnett(p, q):
    """かけ合わせの表（表の行と列は生殖細胞の遺伝子）。"""
    gp, gq = gametes(p), gametes(q)
    rows = [[gp[i]] + [norm(gp[i], y) for y in gq] for i in range(2)]
    return table(rows, header=[f"{p}＼{q}"] + gq, caption=f"表　{p} と {q} のかけ合わせ")


