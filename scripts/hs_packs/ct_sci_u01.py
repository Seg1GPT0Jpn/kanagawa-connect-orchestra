def _trap(r):
    while True:
        V = r.choice([4, 6, 8, 10, 12])
        t1, t3 = r.choice([2, 3, 4, 5, 6]), r.choice([2, 3, 4, 5, 6, 8])
        t2 = r.choice([2, 3, 4, 5, 6])
        if term(sp.Rational(V, t1)) and term(sp.Rational(V, t3)) and t1 + t2 + t3 <= 16:
            return V, t1, t2, t3


