def vform(a, p, q):
    """a(x-p)^2+q の LaTeX。"""
    head = "" if a == 1 else ("-" if a == -1 else str(a))
    inner = "x" if p == 0 else f"x{'-' if p > 0 else '+'}{abs(p)}"
    sq = f"{inner}^2" if p == 0 else f"({inner})^2"
    tail = "" if q == 0 else (f"+{q}" if q > 0 else f"{q}")
    return f"{head}{sq}{tail}"


def expand_v(a, p, q):
    return a, -2 * a * p, a * p * p + q


def py(a, b, c, var="x"):
    return f"({a})*{var}**2+({b})*{var}+({c})"


def cst(k):
    """定数項の符号つき表記（0 なら空）。"""
    return "" if k == 0 else (f"+{k}" if k > 0 else f"{k}")


def at(expr, v):
    return expr.replace("x", f"({v})")


