def hround(fr, nd):
    """Fraction を小数第 nd 位までに四捨五入した文字列と、sympy 用の検算式を返す。"""
    fr = Fraction(fr)
    m = 10 ** nd
    v = (fr * m * 2 + 1) // 2
    s = f"{v // m}" + (f".{str(v % m).rjust(nd, '0')}" if nd else "")
    return s, f"floor(Rational({fr.numerator}*{m},{fr.denominator})+Rational(1,2))/{m}"


def dhondt(votes, seats):
    """ドント式。(各党の議席, 当選した最小の商 (票, 除数)) を返す。境界で同値なら (None, None)。"""
    q = sorted(((v / d, i, v, d) for i, v in enumerate(votes) for d in range(1, seats + 1)), reverse=True)
    if q[seats - 1][0] == q[seats][0]:
        return None, None
    won = [0] * len(votes)
    for _, i, _, _ in q[:seats]:
        won[i] += 1
    last = q[seats - 1]
    return won, (last[2], last[3])


