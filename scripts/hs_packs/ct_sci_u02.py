QUAKE = [("6.0", "3.0"), ("7.0", "3.5"), ("8.0", "4.0"), ("6.0", "4.0"), ("5.0", "3.0"), ("6.0", "3.5")]


@gen("basic_check", 4, ["computation"])
def quake_basic(r):
    vps, vss = r.choice(QUAKE)
    vp, vs = Q(vps), Q(vss)
    k = vp * vs / (vp - vs)
    kind = r.choice(["D", "T", "P", "S"])
    if kind == "T":
        D = r.choice([42, 56, 84, 105, 120, 168, 210, 240])
        T = D / k
        return numq(f"P 波の速さを {vps} km/s、S 波の速さを {vss} km/s とする。震源距離が {D} km の観測点での初期微動継続時間は何秒か。", T, f"{D}/({P(vp)}*{P(vs)}/({P(vp)}-{P(vs)}))",
                    "$T=\\dfrac{D}{V_\\mathrm{S}}-\\dfrac{D}{V_\\mathrm{P}}$。", "秒", d=2,
                    ap="P 波と S 波が届くまでの時間の差が初期微動継続時間。",
                    steps=[f"S 波：$\\dfrac{{{D}}}{{{vss}}}$ 秒、P 波：$\\dfrac{{{D}}}{{{vps}}}$ 秒。", f"差 $T={sig(T, 2)}$ 秒。"],
                    alt=[f"比例定数 $k=\\dfrac{{{vps}\\times{vss}}}{{{vps}-{vss}}}={fv(k)}\\,\\mathrm{{km/s}}$ を求め、$T=\\dfrac{{D}}{{k}}$ としても同じ。"],
                    pc=[("到着時間の差として考えている", 1), ("値が正しい", 1)], pit=["P 波の到着時間だけを答える。"])
    Ts = r.choice(["4.0", "5.0", "6.0", "8.0", "10.0", "12.0", "15.0", "7.5"])
    T = Q(Ts)
    D = k * T
    if kind == "D":
        return numq(f"ある観測点で、初期微動が {Ts} 秒間続いた後に主要動が始まった。P 波の速さを {vps} km/s、S 波の速さを {vss} km/s とするとき、震源距離は何 km か。", D,
                    f"{P(vp)}*{P(vs)}/({P(vp)}-{P(vs)})*{P(T)}", "$D=\\dfrac{V_\\mathrm{P}V_\\mathrm{S}}{V_\\mathrm{P}-V_\\mathrm{S}}T$。", "km", d=2,
                    ap="初期微動継続時間は P 波と S 波の到着時刻の差。$\\dfrac{D}{V_\\mathrm{S}}-\\dfrac{D}{V_\\mathrm{P}}=T$ を $D$ について解く。",
                    steps=[f"$\\dfrac{{D}}{{{vss}}}-\\dfrac{{D}}{{{vps}}}={Ts}$。", f"$k=\\dfrac{{{vps}\\times{vss}}}{{{vps}-{vss}}}={fv(k)}$。", f"$D={fv(k)}\\times{Ts}={sig(D, 2)}\\,\\mathrm{{km}}$。"],
                    alt=["S 波は P 波より 1 km 進むごとに $\\dfrac{1}{V_\\mathrm{S}}-\\dfrac{1}{V_\\mathrm{P}}$ 秒ずつ遅れる、と考えて割り算で求めてもよい。"],
                    pc=[("PS 時間の式を立てている", 1), ("震源距離が正しい", 1)], pit=["$V_\\mathrm{P}\\times T$ や $V_\\mathrm{S}\\times T$ で計算する。"])
    v, vsx, nm = (vp, vps, "P") if kind == "P" else (vs, vss, "S")
    t = D / v
    return numq(f"P 波の速さを {vps} km/s、S 波の速さを {vss} km/s とする。初期微動継続時間が {Ts} 秒であった観測点に、{nm} 波が届いたのは地震発生の何秒後か。", t,
                f"{P(vp)}*{P(vs)}/({P(vp)}-{P(vs)})*{P(T)}/{P(v)}", f"震源距離を求め、{nm} 波の速さで割る。", "秒", d=2,
                ap=f"まず震源距離 $D=kT$ を求め、{nm} 波がその距離を進む時間 $\\dfrac{{D}}{{V_\\mathrm{{{nm}}}}}$ を求める。",
                steps=[f"$k={fv(k)}\\,\\mathrm{{km/s}}$、$D={fv(k)}\\times{Ts}={sig(D, 3)}\\,\\mathrm{{km}}$。", f"$\\dfrac{{{sig(D, 3)}}}{{{vsx}}}={sig(t, 2)}$ 秒後。"],
                alt=["P 波と S 波の到着時間の比は速さの逆比 $V_\\mathrm{S}:V_\\mathrm{P}$ であることを使い、PS 時間を比で分けても求められる。"],
                pc=[("震源距離を求めている", 1), ("時間が正しい", 1)], pit=["初期微動継続時間をそのまま答える。"])


