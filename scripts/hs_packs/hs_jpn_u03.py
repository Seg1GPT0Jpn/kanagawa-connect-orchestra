def basis(v):
    """活用の種類の判定根拠。"""
    if v["t"] in ("四段", "上二段", "下二段"):
        dan = {"四段": "ア", "上二段": "イ", "下二段": "エ"}[v["t"]]
        s = f"「ず」を付けると「{mizen(v)}ず」となり、直前が{dan}段の音なので{label(v)}である。"
        if v["row"] in SPECIAL_NOTE:
            s += SPECIAL_NOTE[v["row"]]
        return s
    return f"{MEMO[v['t']]}。よって「{v['word']}」は{label(v)}である。"


def wrong_type_reason(v, d):
    """誤った活用の種類 d を選んだときの理由。"""
    if v["t"] not in ("四段", "上二段", "下二段"):
        return f"{MEMO[v['t']]}。「{v['word']}」は{label(v)}である。"
    for t in ("四段", "上二段", "下二段"):
        if d == f"{v['row']}行{t}活用":
            hyp = v["stem"] + ROWS[v["row"]][V[PAT[t][0][0]]]
            return f"{t}活用なら「ず」を付けた形は「{hyp}ず」となるはずだが、実際は「{mizen(v)}ず」である。"
    if d == f"{v['row']}行上一段活用":
        return f"上一段活用なら終止形は「〜{ROWS[v['row']][1]}る」の形になるはずだが、「{v['word']}」はそうではない。上一段活用の動詞は限られている。"
    if d.endswith("下一段活用"):
        return "下一段活用は「蹴る」一語だけである。"
    for t, lab in HENKAKU.items():
        if d == lab:
            return MEMO[t] + "。"
    return f"「{v['word']}」は{v['row']}行の音で活用するので、{d}ではない。"


def type_choices(r, v):
    ans = label(v)
    cand = [f"{v['row']}行{t}活用" for t in ("四段", "上二段", "下二段", "上一段")] + list(HENKAKU.values())
    if v["row"] != "カ":
        cand.append("カ行下一段活用")
    cand = [c for c in dict.fromkeys(cand) if c != ans]
    near = [c for c in cand if c.startswith(f"{v['row']}行")]
    pick = r.sample(near, min(2, len(near)))
    pick += r.sample([c for c in cand if c not in pick], 3 - len(pick))
    return ans, pick


