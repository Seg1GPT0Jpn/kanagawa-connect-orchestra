def follow_for(v, form_i):
    opts = {0: ["ず", "む", "ば"], 1: ["て", "けり", "たり"], 2: ["。", "べし"], 3: ["時", "こと", "人"], 4: ["ども", "ば"], 5: ["。"]}[form_i]
    if v["t"] == "ラ変":
        opts = [o for o in opts if o not in ("たり", "べし")]
    return opts


