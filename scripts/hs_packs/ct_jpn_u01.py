DATA_THEMES = [
    ("二つの高校で行った読書についての調査", "北高校", "南高校", "平日に30分以上読書をする"),
    ("二つの町で行った地域活動についての調査", "東町", "西町", "地域の行事に参加したことがある"),
    ("二つの店舗で行った買い物袋についての調査", "駅前店", "郊外店", "買い物袋を持参した"),
    ("二つの図書館で行った利用者調査", "中央図書館", "分館", "電子書籍を利用したことがある"),
    ("二つの学年で行ったニュースの読み方についての調査", "１年生", "３年生", "毎日ニュースを読む"),
    ("二つの地区で行った防災についての調査", "山側地区", "海側地区", "家庭で避難場所を確認している"),
]


def make_data(r):
    """A は回答者が少なく割合が高い、B は回答者が多く割合が低い（人数は B が多い）。"""
    th = r.choice(DATA_THEMES)
    while True:
        nA = r.choice([200, 300, 400])
        nB = r.choice([600, 800, 900, 1000, 1200])
        pA = r.choice([45, 50, 55, 60, 65, 70, 75, 80])
        pB = r.choice([20, 25, 30, 35, 40])
        cA, cB = nA * pA // 100, nB * pB // 100
        if pA > pB and cA < cB and pA - pB >= 15:
            return dict(theme=th[0], A=th[1], B=th[2], item=th[3], nA=nA, nB=nB, pA=pA, pB=pB, cA=cA, cB=cB)


def dtable(D):
    return table([[D["A"], f"{D['nA']}人", f"{D['pA']}％"], [D["B"], f"{D['nB']}人", f"{D['pB']}％"]],
                 header=["", "回答者数", f"「{D['item']}」と答えた割合"], caption=f"【資料】{D['theme']}（架空の調査）")


def dline(D):
    return f"【資料】（架空の調査）{D['A']}：回答者{D['nA']}人・「{D['item']}」{D['pA']}％／{D['B']}：回答者{D['nB']}人・同{D['pB']}％"




def combined(D):
    tot = D["cA"] + D["cB"]
    n = D["nA"] + D["nB"]
    return (200 * tot + n) // (2 * n)  # 四捨五入した整数％


