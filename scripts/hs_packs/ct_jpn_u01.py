GROUPS = [
    ("高校の文芸部", True), ("中学校の科学部", True), ("高校の吹奏楽部の有志", True), ("高校生の地域ボランティア団体", True),
    ("地域の子ども会（小学生）", True), ("市民の合唱サークル", False), ("自治会の防災委員会", False), ("大学の卒業生の会", False),
    ("社会人の読書会", False), ("写真愛好会", False),
]
PURPOSES = ["定期練習", "打ち合わせ", "発表会の準備", "勉強会", "作品の講評会", "年間計画の話し合い"]


def make_case(r):
    name, student = r.choice(GROUPS)
    m = r.randint(6, 34)
    city = r.randint(1, m)
    lead = r.randint(1, 2) if student else 0
    total = m + lead
    room = next(x for x in ROOMS if x[1] >= total)
    h = r.randint(2, 4)
    mult = 1 if 2 * city >= m else 2
    fee = room[2] * h * mult // (2 if student else 1)
    return dict(name=name, student=student, m=m, city=city, lead=lead, total=total, room=room, h=h, mult=mult, fee=fee, purpose=r.choice(PURPOSES))


def case_text(c):
    s = f"{c['name']}（構成員{c['m']}人、うち市内在住・在学・在勤{c['city']}人）"
    if c["student"]:
        s += f"が、成人の引率者{c['lead']}人とともに"
    else:
        s += "が"
    return s


