def prog_tax(income, brackets):
    """超過累進税率による税額（万円）。brackets=[(上限 or None, 税率％), ...]。"""
    tax = Fraction(0)
    lo = 0
    for hi, rate in brackets:
        top = income if hi is None else min(income, hi)
        if top > lo:
            tax += Fraction((top - lo) * rate, 100)
        if hi is None or income <= hi:
            break
        lo = hi
    return tax


def yen(x):
    """整数なら「1,234」，そうでなければ小数第1位まで。"""
    x = Fraction(x)
    return f"{int(x):,}" if x.denominator == 1 else dec(float(x), 1)


