def _bracket_txt(br):
    parts, lo = [], 0
    for hi, rate in br:
        if hi is None:
            parts.append(f"{lo}万円をこえる部分に{rate}％")
        elif lo == 0:
            parts.append(f"{hi}万円以下の部分に{rate}％")
        else:
            parts.append(f"{lo}万円をこえ{hi}万円以下の部分に{rate}％")
        lo = hi
    return "，".join(parts)


