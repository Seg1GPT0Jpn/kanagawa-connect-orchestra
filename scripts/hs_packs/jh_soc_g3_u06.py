def _term_item(r, bank, topic, pit, ap1, ap2):
    k = r.randrange(len(bank))
    term, d_ = bank[k]
    others = [t for i, t in enumerate(bank) if i != k]
    r.shuffle(others)
    if r.random() < 0.5:
        wr = [(t[0], f"{t[0]}は「{t[1]}」である。", f"{topic}に関する用語の取り違え") for t in others]
        lead = r.choice([f"Kさんは，{topic}について調べ，用語カードを作成した。", f"次の説明は，{topic}にかかわる語について述べたものである。"])
        return mc4(f"{lead}次の説明に当てはまる語として，{ASK4}\n［説明］{d_}", term, wr, f"{term}：{d_}。", d=1,
                   ap=ap1, steps=["説明文の中心となる内容を確かめる。", "その内容を表す用語を選ぶ。", f"答え：{term}"],
                   alt=["選択肢の用語の意味を一つずつ確かめ，説明と合わないものを消す。"],
                   pc=[("正しい用語を選んでいる", 2)], pit=[pit])
    wr = [(t[1], f"これは「{t[0]}」の説明である。", f"{topic}に関する用語の取り違え") for t in others]
    return mc4(f"{topic}にかかわる「{term}」の説明として，{ASK4}", d_, wr, f"{term}：{d_}。", d=1,
               ap=ap2, steps=[f"「{term}」の意味を思い出す。", "説明文と照らし合わせる。", f"答え：{d_}"],
               alt=["ほかの説明がどの用語のものかを特定して消去する。"],
               pc=[("正しい説明を選んでいる", 2)], pit=[pit])


