def plain(s):
    """傍線の記法 [[mark:①:語句]] を外した本文。"""
    return re.sub(r"\[\[mark:[^:\]]*:([^\]]*)\]\]", r"\1", s)


def choices(correct, wrongs):
    """正答を先頭に、誤答は順序を正規化して並べる（同じ組合せが別問題として数えられないように）。"""
    return [correct] + sorted(wrongs)


