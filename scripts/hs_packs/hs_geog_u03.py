def _hz_rows(r):
    names = ["地点ア", "地点イ", "地点ウ", "地点エ", "地点オ"]
    while True:
        rows = []
        for nm in names:
            depth = r.choice([0, 0.3, 0.8, 1.5, 2.5, 3.5, 4.5])
            sed = r.choice(["内", "外", "外"])
            dist = 100 * r.randint(3, 20)
            rows.append([nm, depth, sed, dist])
        if len({x[3] for x in rows}) == 5 and any(x[1] >= 3 for x in rows) and any(x[2] == "内" for x in rows):
            return rows


