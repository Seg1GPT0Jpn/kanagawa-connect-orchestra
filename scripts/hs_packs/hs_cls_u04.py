# 返り点は内部では漢文用の記号（㆑㆒㆓）で持ち、本文の漢数字（一刻・二月 など）と区別する。
CONTENT_NUM = ("一刻", "一杯", "一層", "一日", "二月花")
MARK = {"㆑": "レ", "㆒": "一", "㆓": "二"}


def conv(line):
    out = []
    for i, ch in enumerate(line):
        if ch == "レ":
            out.append("㆑")
        elif ch in "一二" and not any(line.startswith(c, i) for c in CONTENT_NUM):
            out.append("㆒" if ch == "一" else "㆓")
        else:
            out.append(ch)
    return "".join(out)


def disp(line):
    return "".join(MARK.get(ch, ch) for ch in line)


def K(title, author, dyn, kun, kaki, rhyme, taiku, gloss, theme, wtheme):
    return dict(title=title, author=author, dyn=dyn, kun=[conv(x) for x in kun], kaki=kaki, rhyme=rhyme, taiku=taiku, gloss=gloss, theme=theme, wtheme=wtheme)


