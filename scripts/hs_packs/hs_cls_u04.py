def kb_tokens(marked):
    out = []
    for ch in marked:
        if ch in MARK:
            c, m = out[-1]
            out[-1] = (c, m + MARK[ch])
        else:
            out.append((ch, ""))
    return out


def kb_order(marked):
    """返り点（レ点・一二点）にしたがって読む順に並べた字のリスト。"""
    toks = kb_tokens(marked)
    out, stack = [], []

    def resolve_re():
        while stack and stack[-1][1] == "レ":
            out.append(stack.pop()[0])

    for c, m in toks:
        if m in ("レ", "二"):
            stack.append((c, m))
            continue
        out.append(c)
        resolve_re()
        if m == "一":
            while stack:
                cc, mm = stack.pop()
                out.append(cc)
                if mm == "二":
                    break
            resolve_re()
    while stack:
        out.append(stack.pop()[0])
    return out


