@kgen("thinking_writing", 3, ["application", "condition_check"])
def c_timeline(r):
    for _ in range(500):
        rows = sorted(r.sample(EV2, 4))
        ys = [y for y, _ in rows]
        if min(b - a for a, b in zip(ys, ys[1:])) < 4:
            continue
        rest = [e for e in EV2 if e not in rows and all(abs(e[0] - y) >= 2 for y in ys)]
        if len(rest) >= 2:
            break
    marks = "①②③④"
    tbl = table([[marks[i], f"{y}年", SHORT[y]] for i, (y, _) in enumerate(rows)], header=["", "年", "できごと"], caption="表")

    def span(kk):
        if kk == 0:
            return "表中の①より前"
        if kk == 4:
            return "表中の④より後"
        return f"表中の{marks[kk - 1]}と{marks[kk]}の間"

    def pos_stmt(e, truth):
        y, _ = e
        k = sum(1 for yy in ys if yy < y)
        if truth:
            return (f"「{SHORT[y]}」のは，{span(k)}である。", True, "")
        alt_k = r.choice([x for x in range(5) if x != k])
        return (f"「{SHORT[y]}」のは，{span(alt_k)}である。", False, f"「{SHORT[y]}」のは{y}年で，{span(k)}である。")

