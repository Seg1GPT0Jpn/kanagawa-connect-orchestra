def pyramid_svg(labels):
    """生物の数量ピラミッド（下から 生産者 → 草食 → 肉食）。labels は下から順の名前。"""
    o = ['<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 300 170" width="300" height="170" font-family="serif" font-size="12">']
    widths = [240, 160, 80]
    for i, (w, lab) in enumerate(zip(widths, labels)):
        y = 120 - i * 50
        x = 150 - w / 2
        o.append(f'<rect x="{x}" y="{y}" width="{w}" height="44" fill="{["#dff0d8", "#fcf3cf", "#f9d6d5"][i]}" stroke="#333"/>')
        o.append(f'<text x="{150 - len(lab) * 6}" y="{y + 27}">{lab}</text>')
    o.append("</svg>")
    return "".join(o)


def balance_svg(stage):
    """数量ピラミッドの変化（つり合い → 草食動物が減る → …）。stage は (下, 中, 上) の幅の倍率。"""
    o = ['<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 160 120" width="160" height="120" font-family="serif" font-size="10">']
    base = [120, 80, 40]
    for i, (b, k) in enumerate(zip(base, stage)):
        w = b * k
        y = 82 - i * 34
        o.append(f'<rect x="{80 - w / 2:.1f}" y="{y}" width="{w:.1f}" height="30" fill="{["#dff0d8", "#fcf3cf", "#f9d6d5"][i]}" stroke="#333"/>')
    o.append("</svg>")
    return "".join(o)


