def score_table(r, k, need_split=False):
    """3 案 × k 人の満足度（架空）。need_split=True なら合計最大の案と最小値最大の案が異なり、どちらも一意。"""
    while True:
        rows = [[r.randint(0, 10) for _ in range(k)] for _ in OPTS]
        sums = [sum(x) for x in rows]
        mins = [min(x) for x in rows]
        if len(set(sums)) < 3 or sums.count(max(sums)) > 1 or mins.count(max(mins)) > 1:
            continue
        iu, im = sums.index(max(sums)), mins.index(max(mins))
        if need_split and iu == im:
            continue
        return rows, sums, mins, iu, im


def score_tbl(rows, people, scene):
    return table([[o] + [str(v) for v in row] for o, row in zip(OPTS, rows)], header=["案"] + people,
                 caption=f"{scene}の各案に対する満足度（架空の資料、0〜10）")


