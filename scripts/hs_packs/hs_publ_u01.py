def mcw(stem, right, wrongs, e, **kw):
    """wrongs = [(誤答, 理由, 誤概念)]。誤答は並びを正規化し、why を自動で付ける。"""
    ws = sorted(wrongs, key=lambda w: w[0])
    return mc(stem, [right] + [w[0] for w in ws], e, why={w[0]: (w[1], w[2]) for w in ws}, **kw)


