FUZOKU = {"が", "は", "を", "に", "で", "と", "の", "て", "た", "ので", "から", "う"}
REL = {"sv": "主・述の関係", "mod": "修飾・被修飾の関係", "par": "並立の関係", "aux": "補助の関係", "conj": "接続の関係", "ind": "独立の関係"}
