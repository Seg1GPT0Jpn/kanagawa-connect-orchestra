def wrong_divisions(s, r):
    out = {}
    w = "／".join("／".join(t) + p for t, p in zip(s.toks, s.punct)) + "。"
    if w != s.slash():
        out["word"] = w
    aux = sorted(s.aux_first())
    if aux:
        i = aux[0]
        kind = "merge_aux"
    else:
        i = r.randrange(s.n - 1)
        kind = "merge"
    parts = [s.bp(k) for k in range(s.n)]
    m = parts[:i] + [s.b(i) + s.bp(i + 1)] + parts[i + 2:]
    out[kind] = "／".join(m) + "。"
    cand = [k for k in range(s.n - 1) if len(s.toks[k]) >= 2 and not s.punct[k]]
    if cand:
        k = r.choice(cand)
        parts = [list(t) for t in s.toks]
        last = parts[k].pop()
        parts[k + 1] = [last] + parts[k + 1]
        out["shift"] = "／".join("".join(t) + p for t, p in zip(parts, s.punct)) + "。"
    return out


