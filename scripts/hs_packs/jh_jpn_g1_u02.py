def statement(r, s=None):
    """(文, 正誤, 誤りの理由)"""
    s = s or r.choice(SENTS)
    kind = r.choice(["count", "rel", "words"])
    if kind == "count":
        n = s.n + (0 if r.random() < 0.5 else r.choice([-1, 1]))
        return (f"「{s.text()}」は{n}つの文節に区切ることができる。", n == s.n, f"正しくは{s.n}文節（{s.slash()}）。")
    if kind == "words":
        w = s.words() + (0 if r.random() < 0.5 else r.choice([-1, 1]))
        return (f"「{s.text()}」は{w}つの単語からできている。", w == s.words(), f"正しくは{s.words()}単語。")
    if not s.pairs():
        return statement(r, s)
    i, j, rl = r.choice(s.pairs())
    claim = rl if r.random() < 0.5 else r.choice([x for x in ("sv", "mod", "par", "aux") if x != rl])
    return (f"「{s.text()}」の{bs(s, i)}と{bs(s, j)}は、{REL[claim]}にある。", claim == rl, f"正しくは{REL[rl]}。")


