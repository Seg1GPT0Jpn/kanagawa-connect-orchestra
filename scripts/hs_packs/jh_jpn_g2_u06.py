# 返り点の処理
# ----------------------------------------------------------------------
MARKS = {"㆑": "レ", "㆒": "一", "㆓": "二", "㆔": "三", "㆖": "上", "㆗": "中", "㆘": "下"}
OKIJI = {"而", "於"}
NEXT = {"一": "二", "二": "三", "上": "中", "中": "下"}
DEFER = {"レ", "二", "三", "中", "下"}


def parse(kun, okiji=True):
    """訓読文を [(字, 返り点)] に分ける。置き字は返り点 '置'。"""
    toks = []
    for ch in kun:
        if ch in MARKS:
            c, m = toks[-1]
            toks[-1] = (c, MARKS[ch])
        else:
            toks.append((ch, "置" if okiji and ch in OKIJI else ""))
    return toks


def read_order(toks, ignore=()):
    """返り点のきまりにしたがって、読む字の位置を順に返す（置き字は読まない）。ignore に入れた返り点は無いものとして扱う。"""
    marks = ["" if m in ignore else m for _, m in toks]
    done, out = set(), []

    def read_at(i):
        out.append(i)
        done.add(i)
        j = i - 1
        while j >= 0 and marks[j] == "置":
            j -= 1
        if j >= 0 and marks[j] == "レ" and j not in done:
            read_at(j)
        nx = NEXT.get(marks[i])
        if nx:
            if nx == "中" and not any(marks[k] == "中" and k not in done for k in range(i)):
                nx = "下"
            for k in range(i - 1, -1, -1):
                if marks[k] == nx and k not in done:
                    read_at(k)
                    break

    for i in range(len(toks)):
        if i in done or marks[i] == "置" or marks[i] in DEFER:
            continue
        read_at(i)
    return out


def order_str(toks, idx):
    return "→".join(toks[i][0] for i in idx)


def show(toks):
    rev = {v: k for k, v in MARKS.items()}
    return "".join(c + (rev[m] if m in rev else "") for c, m in toks)


