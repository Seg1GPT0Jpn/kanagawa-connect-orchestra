def wrong_orders(toks):
    """よくある誤りの読み方：(読む順, 誤りの説明)。"""
    n = len(toks)
    ok = read_order(toks)
    cands = [
        ([i for i in range(n) if toks[i][1] != "置"], "返り点を無視して、上の字から順に読んでいる。"),
        (read_order(toks, ignore=("レ",)), "レ点を無視している。"),
        (read_order(toks, ignore=("一", "二", "三")), "一二点を無視している。"),
        (read_order(toks, ignore=("上", "中", "下")), "上下点を無視している。"),
        (list(reversed([i for i in range(n) if toks[i][1] != "置"])), "返り点のない字まで後回しにして、下から順に読んでいる。"),
    ]
    out, seen = [], {tuple(ok)}
    for o, rs in cands:
        if tuple(o) not in seen and len(o) == len(ok):
            seen.add(tuple(o))
            out.append((o, rs))
    return out


