class T:
    def __init__(self, raw):
        self.toks = []
        for x in raw.split():
            if x == "、":
                self.toks.append(("、", None, None))
                continue
            p = x.split("/")
            self.toks.append((p[0], p[1], p[2] if len(p) > 2 else p[0]))

    def words(self):
        return [k for k, t in enumerate(self.toks) if t[1]]

    def text(self, mark=None):
        return "".join(f"[[u:{t[0]}]]" if k == mark else t[0] for k, t in enumerate(self.toks)) + "。"

    def surf(self, k):
        return self.toks[k][0]

    def pos(self, k):
        return self.toks[k][1]

    def unique(self, k):
        return sum(1 for t in self.toks if t[0] == self.toks[k][0]) == 1

    def count(self, pred):
        return sum(1 for k in self.words() if pred(self.pos(k)))


TS = [T(x) for x in RAW]
for _t in TS:
    for _k in _t.words():
        assert _t.pos(_k) in POS10, _t.toks[_k]


