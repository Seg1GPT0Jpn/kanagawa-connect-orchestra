def statement(r, t=None):
    """(文, 正誤, 誤りの理由)"""
    if t is None:
        kind = r.choice(["rule", "rule", "word"])
    else:
        kind = r.choice(["word", "word", "count"])
    if kind == "rule":
        p = r.choice(POS10)
        if r.random() < 0.5:
            return (f"{p}は、{POS_DEF[p]}品詞である。", True, "")
        q = r.choice([x for x in CONFUSE[p]])
        return (f"{p}は、{POS_DEF[q]}品詞である。", False, f"それは{q}の説明。{p}は{POS_DEF[p]}。")
    if kind == "count" and t is not None:
        kd = r.choice(["自立語", "付属語"])
        pred = is_jiritsu if kd == "自立語" else (lambda p: not is_jiritsu(p))
        n = t.count(pred)
        m = n if r.random() < 0.5 else n + r.choice([-1, 1])
        return (f"この文には{kd}が{m}つある。", m == n, f"正しくは{n}つ。")
    t2 = t or r.choice(TS)
    k = r.choice([k for k in t2.words() if t2.unique(k)])
    p = t2.pos(k)
    claim = p if r.random() < 0.5 else r.choice(CONFUSE[p])
    head = "" if t is not None else f"「{t2.text()}」の"
    return (f"{head}「{t2.surf(k)}」は{claim}である。", claim == p, f"「{t2.surf(k)}」は{p}。")


