def make_pyramid(r, kind):
    """17 階級の人口構成比（%）。合計 100。"""
    if kind == "富士山型（ピラミッド型）":
        q = r.uniform(0.80, 0.86)
        w = [q ** k for k in range(17)]
    elif kind == "釣鐘型":
        w = [1.0 + r.uniform(-0.03, 0.03) for _ in range(10)] + [0.95, 0.88, 0.8, 0.7, 0.55, 0.4, 0.45]
    elif kind == "つぼ型":
        top = r.uniform(1.6, 1.9)
        w = [1.0, 1.05, 1.1, 1.2, 1.35, 1.5, 1.6, 1.7, top, top, top - 0.05, top - 0.1, top - 0.15, top - 0.3, top - 0.5, top - 0.8, top - 0.6]
    elif kind == "星型":
        b = r.uniform(1.6, 2.0)
        w = [0.9, 0.85, 0.8, 0.9, b, b * 1.05, b, b * 0.85, 0.95, 0.85, 0.8, 0.7, 0.6, 0.5, 0.4, 0.3, 0.3]
    else:
        d = r.uniform(0.35, 0.5)
        w = [0.9, 0.95, 1.0, 0.8, d, d, d * 1.1, d * 1.3, 0.9, 1.0, 1.05, 1.1, 1.1, 1.0, 0.9, 0.75, 0.8]
    w = [x * (1 + r.uniform(-0.03, 0.03)) for x in w]
    s = sum(w)
    pct = [round(100 * x / s, 1) for x in w]
    pct[0] = round(pct[0] + 100 - sum(pct), 1)
    return pct


def pyr_kind(p):
    """型の判定（架空データの検算用）。"""
    young = sum(p[0:3]) / 3
    adult = sum(p[4:8]) / 4
    around = (sum(p[0:3]) + sum(p[9:12])) / 6
    if adult >= 1.3 * around:
        return "星型"
    if adult <= 0.75 * around:
        return "ひょうたん型"
    if young >= 1.3 * adult and all(p[k] >= p[k + 1] - 0.3 for k in range(15)):
        return "富士山型（ピラミッド型）"
    if young <= 0.8 * adult:
        return "つぼ型"
    if 0.9 <= young / adult <= 1.12:
        return "釣鐘型"
    return None


def pyramid(r, kind):
    for _ in range(100):
        p = make_pyramid(r, kind)
        if pyr_kind(p) == kind:
            return p
    raise RuntimeError(kind)


def groups3(p):
    y = round(sum(p[0:3]), 1)
    o = round(sum(p[13:]), 1)
    w = round(100 - y - o, 1)
    return y, w, o


def pyr_body(p, name, dx=0):
    cx, top, bh = 150 + dx, 20, 11
    mx = max(p) / 2
    sc = 110 / mx
    out = [f'<text x="{cx}" y="12" text-anchor="middle" font-weight="bold">{name}</text>']
    for k in range(17):
        y = top + (16 - k) * bh
        half = p[k] / 2
        out.append(f'<rect x="{cx - 14 - half * sc:.1f}" y="{y}" width="{half * sc:.1f}" height="{bh - 1}" fill="#7fa7d1" stroke="#335" stroke-width="0.4"/>')
        out.append(f'<rect x="{cx + 14:.1f}" y="{y}" width="{half * sc:.1f}" height="{bh - 1}" fill="#e8a0a0" stroke="#533" stroke-width="0.4"/>')
        if k % 2 == 0 or k == 16:
            out.append(f'<text x="{cx}" y="{y + 8}" font-size="7" text-anchor="middle">{AGES[k] if k < 16 else "80〜"}</text>')
    yb = top + 17 * bh + 10
    out.append(f'<text x="{cx - 70}" y="{yb}" font-size="8" text-anchor="middle">男</text><text x="{cx + 70}" y="{yb}" font-size="8" text-anchor="middle">女</text>')
    return out


