@kgen("error_correction", 5, ["common_error", "computation"])
def d_calc(r):
    kind = r.choice(["aging", "majority", "twothirds", "share"])
    if kind == "aging":
        while True:
            y0 = r.choice(range(5, 21)) * 1000
            w = r.choice(range(30, 61, 5)) * 1000
            o = r.choice(range(8, 31)) * 1000
            tot = y0 + w + o
            if (o * 100) % tot == 0 and (o * 1000) % w != 0:
                break
        p = o * 100 // tot
        sol = f"架空の町の人口は，0〜14歳が{y0}人，15〜64歳が{w}人，65歳以上が{o}人。高齢化率は{o}÷{w}×100≒{_pct(o * 100 / w)}（％）である。"
        step = "65歳以上の人口を15〜64歳の人口でわった部分"
        right = f"高齢化率は総人口に対する割合なので，{o}÷（{y0}＋{w}＋{o}）×100＝{p}（％）となる。"
        wr = [(f"高齢化率は{o}÷{y0}×100で求める。", "0〜14歳の人口でわるのは誤り。総人口でわる。", "割合のわる数の誤り"),
              (f"高齢化率は（{y0}＋{o}）÷{tot}×100で求める。", "0〜14歳の人口は高齢者ではない。", "年齢区分の取り違え"),
              ("Kさんの計算は正しい。", f"総人口でわるので，正しくは{p}％。", "割合のわる数の誤り")]
        title = "高齢化率を計算した。"
        tempt = "高齢者を支える世代との比べ方と，高齢化率の求め方を混同するため。"
        typ = "formula"
        extra = dict(chk=(f"Rational({o}*100,{y0}+{w}+{o})", str(p), None, "intermediate"))
        fix = f"{o}÷{tot}×100＝{p}（％）"
    elif kind == "majority":
        n = r.choice([n for n in range(21, 41) if n % 2 == 1])
        need = n // 2 + 1
        sol = f"{n}人の学級で多数決をとるとき，過半数は{n}÷2＝{n / 2:g}なので，{n // 2}人以上の賛成があれば可決される。"
        step = f"過半数を{n // 2}人以上とした部分"
        right = f"過半数は半数をこえる数なので，{n / 2:g}人をこえる{need}人以上の賛成が必要である。"
        wr = [(f"過半数は全員の3分の2以上なので，{-(-2 * n // 3)}人以上が必要である。", "3分の2以上は過半数とは別の基準である。", "基準の取り違え"),
              (f"過半数は全員なので，{n}人の賛成が必要である。", "全員の賛成は全会一致である。", "決め方の取り違え"),
              ("Kさんの解答は正しい。", f"{n // 2}人では半数をこえていない。", "過半数の意味の誤解")]
        title = "多数決で可決されるために必要な人数を考えた。"
        tempt = "「半分」と「半分をこえる」のちがいを確かめずに，割った数の整数部分をそのまま使ったため。"
        typ = "condition"
        extra = dict(chk=(f"floor({n}/2)+1", str(need), None, "intermediate"))
        fix = f"{need}人以上"
    elif kind == "twothirds":
        n = r.choice([n for n in range(24, 46) if n % 3 != 0])
        need = -(-2 * n // 3)
        sol = f"{n}人で，3分の2以上の賛成が必要なきまりを決める。{n}×2÷3＝{_pct(2 * n / 3)}なので，{2 * n // 3}人以上の賛成があればよい。"
        step = f"必要な人数を{2 * n // 3}人以上とした部分"
        right = f"{_pct(2 * n / 3)}人以上が必要なので，人数としては切り上げて{need}人以上の賛成が必要である。"
        wr = [(f"3分の2以上は過半数と同じなので，{n // 2 + 1}人以上でよい。", "3分の2以上は過半数より多くの賛成を必要とする基準である。", "基準の取り違え"),
              (f"3分の2以上なので，{n}÷3＝{_pct(n / 3)}より，{n // 3 + 1}人以上でよい。", "これは3分の1の人数である。", "計算の誤り"),
              ("Kさんの解答は正しい。", f"{2 * n // 3}人では3分の2に届かない。", "端数の処理の誤り")]
        title = "3分の2以上の賛成が必要なときの人数を考えた。"
        tempt = "小数を切り捨てると，基準に届かなくなることに気づかなかったため。"
        typ = "calculation"
        extra = dict(chk=(f"ceiling(2*{n}/3)", str(need), None, "intermediate"))
        fix = f"{need}人以上"
    else:
        while True:
            tot = r.choice(range(200, 1001, 50))
            part = r.choice(range(20, tot // 2, 10))
            if (part * 100) % tot == 0:
                break
        pct = part * 100 // tot
        sol = f"架空の市の外国人住民へのアンケートで，回答者{tot}人のうち{part}人が「案内表示を増やしてほしい」と答えた。その割合は{tot}÷{part}×100{'＝' if (tot * 1000) % part == 0 else '≒'}{_pct(tot * 100 / part)}（％）である。"
        step = "全体を部分でわった部分"
        right = f"割合は部分÷全体×100なので，{part}÷{tot}×100＝{pct}（％）となる。"
        wr = [(f"割合は{tot}－{part}＝{tot - part}（％）である。", "ひき算では割合は求められない。", "差と割合の混同"),
              (f"割合は{part}÷{tot}＝{part / tot:g}（％）である。", "百分率にするには100をかける。", "百分率の計算の誤り"),
              ("Kさんの計算は正しい。", "割合が100％をこえることはない。わる順が逆である。", "割合の計算の誤り")]
        title = "アンケートの結果の割合を計算した。"
        tempt = "わる数とわられる数を逆にしてしまうため。"
        typ = "formula"
        extra = dict(chk=(f"Rational({part}*100,{tot})", str(pct), None, "intermediate"))
        fix = f"{part}÷{tot}×100＝{pct}（％）"
    return mc4(f"Kさんは，{title}\n［Kさんの解答］{sol}\nKさんの解答の誤りを説明したものとして{ASK4}",
               right, wr, right, d=3,
               ap="解答が使った式の意味（何を何でわるのか）や，基準（過半数・3分の2以上）の意味を確かめる。",
               steps=["解答が使った式や基準を確かめる。", f"誤りの箇所：{step}。", f"正しくは：{fix}"],
               alt=["求めた答えを元の条件に当てはめて，基準を満たしているか（割合が100％をこえていないか）を確かめる。"],
               pc=[("誤りの箇所を指摘している", 2), ("正しい計算・人数を示している", 4)],
               pit=["「Kさんの計算は正しい」という選択肢にまどわされる。"],
               err=dict(sol=sol, step=step, type=typ, tempt=tempt, fix=fix), **extra)


