def longest_dark(L, brk):
    D = 24 - L
    if brk is None:
        return D
    return max(brk, D - brk)


def sched_text(L, brk):
    D = 24 - L
    return f"明期 {L} 時間・暗期 {D} 時間" + (f"（暗期の開始から {brk} 時間後に短時間の光中断）" if brk is not None else "")


