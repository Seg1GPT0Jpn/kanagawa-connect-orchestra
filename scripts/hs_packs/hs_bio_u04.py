def fpy(x):
    x = Fraction(x)
    return str(x.numerator) if x.denominator == 1 else f"Rational({x.numerator},{x.denominator})"


def _ap(x):
    if x < 1:
        return -7.0
    if x < 2:
        return -7.0 + 11.0 * (x - 1)
    if x < 3:
        return 4.0 - 12.0 * (x - 2)
    if x < 4:
        return -8.0 + 1.0 * (x - 3)
    return -7.0


