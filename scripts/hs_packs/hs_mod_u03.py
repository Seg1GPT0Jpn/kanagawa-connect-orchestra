def calc(q, num, den, mul, unit, wrongs):
    """割合・増減率・倍率の計算問題。値は num/den*mul（mul=100 なら％）。"""
    v = Fraction(num, den) * mul
    s = f"{float(v):g}{unit}"
    expr = f"Rational({num},{den})*{mul}"
    return dict(q=q, expr=expr, val=frs(v), ans=s, wrongs=wrongs)


