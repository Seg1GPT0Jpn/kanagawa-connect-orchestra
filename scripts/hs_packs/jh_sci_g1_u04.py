def _stack(seq_up, H=20):
    """凝灰岩の層の上端を 0 とした相対深さでの層の並び。seq_up は凝灰岩より下の層を下から上の順に並べたもの。"""
    below = list(reversed(seq_up))  # 凝灰岩の直下から下へ
    layers = [(-40, -9, "砂岩"), (-9, -4, "泥岩"), (-4, 0, "砂岩"), (0, 1, "凝灰岩")]
    y = 1
    for i, kind in enumerate(below):
        th = 3 if i < len(below) - 1 else 40
        layers.append((y, y + th, kind))
        y += th
    return layers


def _col(stack, dk):
    return [(top + dk, bot + dk, k) for top, bot, k in stack]


