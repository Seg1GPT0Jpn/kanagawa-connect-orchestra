def column_svg(cols, H=20, unit=9):
    """柱状図。cols=[(見出し, [(上端の深さ, 下端の深さ, 岩石名), ...])]。深さは m。"""
    W = 70 * len(cols) + 150
    Hp = H * unit + 50
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {Hp}" width="{W}" height="{Hp}" font-family="serif" font-size="11">']
    for d in range(0, H + 1, 5):
        y = 25 + d * unit
        out.append(f'<text x="2" y="{y + 4}">{d}</text><line x1="22" y1="{y}" x2="28" y2="{y}" stroke="#000"/>')
    out.append(f'<text x="0" y="14">深さ〔m〕</text><line x1="28" y1="25" x2="28" y2="{25 + H * unit}" stroke="#000"/>')
    for c, (lab, layers) in enumerate(cols):
        x = 50 + c * 70
        out.append(f'<text x="{x + 6}" y="18">{lab}</text>')
        for top, bot, kind in layers:
            top, bot = max(0, top), min(H, bot)
            if bot <= top:
                continue
            y0, y1 = 25 + top * unit, 25 + bot * unit
            out.append(f'<rect x="{x}" y="{y0}" width="34" height="{y1 - y0}" fill="{LAYER_FILL[kind]}" stroke="#000"/>')
            if kind == "れき岩":
                yy = y0 + 4
                while yy < y1 - 2:
                    out.append(f'<circle cx="{x + 9}" cy="{yy}" r="2.4" fill="none" stroke="#000"/><circle cx="{x + 24}" cy="{yy + 3}" r="2.4" fill="none" stroke="#000"/>')
                    yy += 8
            elif kind == "砂岩":
                yy = y0 + 3
                while yy < y1 - 1:
                    for xx in (6, 14, 22, 30):
                        out.append(f'<circle cx="{x + xx}" cy="{yy}" r="0.8" fill="#000"/>')
                    yy += 5
            elif kind == "泥岩":
                yy = y0 + 4
                while yy < y1 - 1:
                    out.append(f'<line x1="{x + 4}" y1="{yy}" x2="{x + 30}" y2="{yy}" stroke="#666" stroke-width="0.6"/>')
                    yy += 5
            elif kind == "凝灰岩":
                yy = y0 + 4
                while yy < y1 - 1:
                    for xx in (6, 16, 26):
                        out.append(f'<path d="M{x + xx},{yy - 2} L{x + xx + 2},{yy + 2} L{x + xx + 4},{yy - 2}" fill="none" stroke="#000" stroke-width="0.6"/>')
                    yy += 6
        out.append(f'<rect x="{x}" y="25" width="34" height="{H * unit}" fill="none" stroke="#000"/>')
    lx = 60 + len(cols) * 70
    kinds = []
    for _, layers in cols:
        for _, _, k in layers:
            if k not in kinds:
                kinds.append(k)
    for i, k in enumerate(kinds):
        y = 30 + i * 22
        out.append(f'<rect x="{lx}" y="{y}" width="18" height="14" fill="{LAYER_FILL[k]}" stroke="#000"/><text x="{lx + 24}" y="{y + 11}">{k}</text>')
    out.append("</svg>")
    return "".join(out)


def quake_svg(vp, vs, tmax, dmax, pts):
    """震源からの距離と、P波・S波が届くまでの時間の関係のグラフ。pts=[(時間, 距離, ラベル)]。"""
    W, H = 300, 200
    ox, oy = 50, 220
    sx, sy = W / tmax, H / dmax
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W + 90} {H + 60}" width="{W + 90}" height="{H + 60}" font-family="serif" font-size="11">']
    tstep = 5 if tmax <= 40 else 10
    dstep = max(10, dmax // 6 // 10 * 10)
    for t in range(0, tmax + 1, tstep):
        x = ox + t * sx
        out.append(f'<line x1="{x:.1f}" y1="{oy}" x2="{x:.1f}" y2="{oy - H}" stroke="#ddd"/><text x="{x - 5:.1f}" y="{oy + 14}">{t}</text>')
    for d in range(0, dmax + 1, dstep):
        y = oy - d * sy
        out.append(f'<line x1="{ox}" y1="{y:.1f}" x2="{ox + W}" y2="{y:.1f}" stroke="#ddd"/><text x="{ox - 30}" y="{y + 4:.1f}">{d}</text>')
    out.append(f'<line x1="{ox}" y1="{oy}" x2="{ox + W}" y2="{oy}" stroke="#000"/><line x1="{ox}" y1="{oy}" x2="{ox}" y2="{oy - H}" stroke="#000"/>')
    for v, lab in ((vp, "P波"), (vs, "S波")):
        t_end = min(tmax, dmax / v)
        x2, y2 = ox + t_end * sx, oy - v * t_end * sy
        out.append(f'<line x1="{ox}" y1="{oy}" x2="{x2:.1f}" y2="{y2:.1f}" stroke="#000" stroke-width="1.6"/><text x="{x2 + 3:.1f}" y="{y2 + 4:.1f}">{lab}</text>')
    for t, d, lab in pts:
        out.append(f'<circle cx="{ox + t * sx:.1f}" cy="{oy - d * sy:.1f}" r="2.6" fill="#000"/>')
        if lab:
            out.append(f'<text x="{ox + t * sx + 4:.1f}" y="{oy - d * sy - 4:.1f}">{lab}</text>')
    out.append(f'<text x="{ox + W / 2 - 70}" y="{oy + 32}">地震が発生してからの時間〔秒〕</text>')
    out.append(f'<text x="2" y="{oy - H - 8}">震源からの距離〔km〕</text></svg>')
    return "".join(out)


