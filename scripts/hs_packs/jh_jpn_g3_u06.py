@gen("error_correction", 3, ["common_error", "computation"])
def err_data(r):
    while True:
        t, v1, v2 = make_data(r)
        g1, g2 = GROUPS[0][0], GROUPS[1][0]
        n1, n2 = GROUPS[0][1], GROUPS[1][1]
        cats = t["cats"]
        opts = []
        for i, c in enumerate(cats):
            a, b = v1[i], v2[i]
            if a > b and n2 * b > n1 * a:
                opts.append(("COUNT", f"「{c}」と答えた人の人数は、{g2}より{g1}のほうが多い。",
                             f"割合は{g1}が{a}％、{g2}が{b}％で{g1}のほうが高いが、人数は{g1}が{n1 * a // 100}人、{g2}が{n2 * b // 100}人で、{g2}のほうが多い。"))
            if b > a:
                opts.append(("REVERSE", f"「{c}」と答えた人の割合は、{g1}から{g2}にかけて減っている。", f"「{c}」は{g1}が{a}％、{g2}が{b}％で、増えている。"))
        mx = max(range(4), key=lambda i: v2[i])
        if v2[mx] < 50:
            opts.append(("HALF", f"{g2}では、最も多い「{cats[mx]}」と答えた人が半数を超えている。", f"「{cats[mx]}」は{v2[mx]}％で、最も多いが半数（50％）は超えていない。"))
        if opts:
            break
    typ, kt, rs = r.choice(opts)
    T_ = {"COUNT": "調査した人数がちがうのに、割合の大小だけで人数を比べている。",
          "REVERSE": "二つの調査の数値を比べるときに、増減の向きを逆に読んでいる。",
          "HALF": "最も多い項目であることと、半数を超えていることを混同している。",
          "OTHER": "表の別の項目の数値を読んでいる。"}
