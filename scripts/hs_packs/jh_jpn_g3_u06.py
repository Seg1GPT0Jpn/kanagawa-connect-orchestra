@gen("basic_check", 4, ["condition_check", "common_error"])
def style_unify(r):
    sents, k, base = r.choice(STYLE)
    lab = "abcd"
    body = "\n".join(f"{lab[i]}　{s}" for i, s in enumerate(sents))
    other = "敬体（です・ます）" if base == "常体" else "常体（だ・である）"
    basej = "常体（だ・である）" if base == "常体" else "敬体（です・ます）"
    ok = f"{lab[k]}　{sents[k]}"
    wrongs = [(f"{lab[i]}　{s}", f"{lab[i]} は、ほかの多くの文と同じ{basej}で書かれている。", "文体の判断の誤り") for i, s in enumerate(sents) if i != k]
