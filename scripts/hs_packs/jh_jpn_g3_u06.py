def _shift(r, v1):
    """前回の結果から、各項目を3〜15ポイント程度動かした今回の結果（合計100）。"""
    for _ in range(50):
        d = [r.choice([-1, 1]) * r.randint(3, 15) for _ in range(3)]
        last = -sum(d)
        if not 3 <= abs(last) <= 15:
            continue
        v2 = [a + b for a, b in zip(v1, d + [last])]
        if min(v2) >= 5 and max(v2) <= 62 and len(set(v2)) == 4:
            return v2
    return None


def _split(r):
    while True:
        a = sorted(r.sample(range(5, 96), 3))
        v = [a[0], a[1] - a[0], a[2] - a[1], 100 - a[2]]
        if min(v) >= 5 and max(v) <= 62 and len(set(v)) == 4:
            return v


