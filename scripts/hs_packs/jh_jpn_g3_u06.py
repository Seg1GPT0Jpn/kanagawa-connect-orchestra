def pick_stmts(r, pool, n_true, n_false):
    tr = [s for s in pool if s[1]]
    fa = [s for s in pool if not s[1]]
    r.shuffle(tr)
    r.shuffle(fa)
    out_t, out_f, used = [], [], set()
    for s in tr:
        if len(out_t) < n_true and (s[3] not in used or len(used) >= 5):
            out_t.append(s)
            used.add(s[3])
    for s in fa:
        if len(out_f) < n_false and (s[3] not in used or len(used) >= 5):
            out_f.append(s)
            used.add(s[3])
    for s in fa:
        if len(out_f) < n_false and s not in out_f:
            out_f.append(s)
    return out_t, out_f


