def violations(c, text):
    """条件違反の種類のリスト（プログラムで判定）。"""
    v = []
    mid = inner(c, text)
    if mid is None:
        v.append("START_END")
        mid = text[len(c["start"]):] if text.startswith(c["start"]) else text
        mid = mid[:len(mid) - len(c["end"])] if mid.endswith(c["end"]) else mid.rstrip("。")
    if not (c["lo"] <= len(mid) <= c["hi"]):
        v.append("COUNT")
    if not all(w in mid for w in c["words"]):
        v.append("WORDS")
    if "。" in mid:
        v.append("ONE")
    return v


