KNAME = {"Af": "熱帯雨林気候", "Am": "熱帯モンスーン気候", "Aw": "サバナ気候", "BW": "砂漠気候", "BS": "ステップ気候",
         "Cs": "地中海性気候", "Cw": "温暖冬季少雨気候", "Cfa": "温暖湿潤気候", "Cfb": "西岸海洋性気候",
         "Df": "亜寒帯湿潤気候", "Dw": "亜寒帯冬季少雨気候", "ET": "ツンドラ気候", "EF": "氷雪気候"}
GEN_KINDS = ["Af", "Aw", "BW", "BS", "Cs", "Cw", "Cfa", "Cfb", "Df", "Dw", "ET", "EF"]
SOUTH_OK = {"Aw", "BW", "BS", "Cs", "Cw", "Cfa", "Cfb"}
BASE = [-1.0, -0.866, -0.5, 0.0, 0.5, 0.866, 1.0, 0.866, 0.5, 0.0, -0.5, -0.866]
NORTH_SUMMER = [3, 4, 5, 6, 7, 8]
SOUTH_SUMMER = [9, 10, 11, 0, 1, 2]


def summer_idx(t):
    n = sum(t[i] for i in NORTH_SUMMER)
    s = sum(t[i] for i in SOUTH_SUMMER)
    return NORTH_SUMMER if n >= s else SOUTH_SUMMER


def pattern(t, p):
    """降水の季節配分：'s'（夏に乾燥）・'w'（冬に乾燥）・'f'（年中湿潤）。"""
    su = summer_idx(t)
    wi = [i for i in range(12) if i not in su]
    if min(p[i] for i in su) < 30 and max(p[i] for i in wi) >= 3 * min(p[i] for i in su):
        return "s"
    if max(p[i] for i in su) >= 10 * min(p[i] for i in wi):
        return "w"
    return "f"


def dry_limit(tm, pat):
    """乾燥限界 r（mm）。tm は年平均気温（℃）。"""
    return 20 * tm if pat == "s" else (20 * (tm + 14) if pat == "w" else 20 * (tm + 7))


def classify(t, p):
    hot, cold, P = max(t), min(t), sum(p)
    tm = sum(t) / 12
    pat = pattern(t, p)
    if hot < 10:
        return "ET" if hot >= 0 else "EF"
    r = dry_limit(tm, pat)
    if P < r:
        return "BW" if P < r / 2 else "BS"
    if cold >= 18:
        if min(p) >= 60:
            return "Af"
        return "Am" if min(p) >= 100 - P / 25 else "Aw"
    if cold >= -3:
        if pat == "s":
            return "Cs"
        if pat == "w":
            return "Cw"
        return "Cfa" if hot >= 22 else "Cfb"
    if pat == "w":
        return "Dw"
    return "Df" if pat == "f" else "Ds"


def _wave(r, mean, amp, south):
    b = BASE[6:] + BASE[:6] if south else BASE
    return [round(mean + amp * x, 1) for x in b]


def _rain(r, lo, hi, k, south, reverse=False, noise=0.12):
    b = BASE[6:] + BASE[:6] if south else BASE
    out = []
    for x in b:
        s = (x + 1) / 2
        if reverse:
            s = 1 - s
        v = lo + (hi - lo) * s ** k
        v *= 1 + r.uniform(-noise, noise)
        out.append(max(0, int(round(v))))
    return out


def make_climate(r, kind, south=False):
    U = r.uniform
    if kind == "Af":
        return _wave(r, U(26, 27.5), U(0.4, 1.2), south), _rain(r, U(130, 200), U(220, 320), 1, south)
    if kind == "Aw":
        return _wave(r, U(25, 28), U(1.5, 3.5), south), _rain(r, U(0, 6), U(220, 320), 1.5, south)
    if kind == "BW":
        return _wave(r, U(19, 25), U(6, 11), south), _rain(r, 0, U(5, 25), 1, south, noise=0.3)
    if kind == "BS":
        return _wave(r, U(12, 20), U(8, 13), south), _rain(r, U(3, 10), U(30, 60), 1, south)
    if kind == "Cs":
        return _wave(r, U(15, 18), U(5, 8), south), _rain(r, U(0, 8), U(80, 140), 1.2, south, reverse=True)
    if kind == "Cw":
        return _wave(r, U(19, 23), U(4, 7), south), _rain(r, U(10, 22), U(280, 420), 1.5, south)
    if kind == "Cfa":
        return _wave(r, U(14, 17), U(10, 12.5), south), _rain(r, U(45, 80), U(150, 240), 1, south)
    if kind == "Cfb":
        return _wave(r, U(9, 12), U(5, 7), south), _rain(r, U(50, 70), U(65, 95), 1, south, reverse=r.random() < 0.5)
    if kind == "Df":
        return _wave(r, U(1, 6), U(13, 17), south), _rain(r, U(30, 45), U(70, 100), 1, south)
    if kind == "Dw":
        return _wave(r, U(-4, 1), U(19, 24), south), _rain(r, U(1, 4), U(110, 160), 2, south)
    if kind == "ET":
        return _wave(r, U(-14, -8), U(8, 13), south), _rain(r, U(5, 15), U(30, 60), 1, south)
    return _wave(r, U(-32, -22), U(6, 12), south), _rain(r, 2, 15, 1, south, noise=0.3)


def robust(t, p, kind):
    """気温・降水量を少しずらしても判定が変わらないか。"""
    if classify(t, p) != kind:
        return False
    for dt in (-0.8, 0.8):
        for mode in ("x0.88", "x1.12", "+5", "-5"):
            if mode.startswith("x"):
                q = [v * float(mode[1:]) for v in p]
            else:
                q = [max(0, v + int(mode)) for v in p]
            if classify([v + dt for v in t], q) != kind:
                return False
    return True


def climate(r, kind, south=False):
    for _ in range(400):
        t, p = make_climate(r, kind, south)
        if robust(t, p, kind):
            return t, p
    raise RuntimeError(kind)


def stats(t, p):
    tm = round(sum(t) / 12, 1)
    return dict(hot=max(t), cold=min(t), rng=round(max(t) - min(t), 1), P=sum(p), tm=tm, pat=pattern(t, p))


def climo_svg(t, p, name):
    """雨温図（折れ線：月平均気温、棒：月降水量）。"""
    W, H, ox, oy, gw, gh = 280, 220, 40, 28, 196, 160
    tmin, tmax = -40, 40
    pmax = 500 if max(p) > 400 else 400
    X = lambda m: ox + (m + 0.5) * gw / 12  # noqa: E731
    YT = lambda v: oy + (tmax - v) * gh / (tmax - tmin)  # noqa: E731
    YP = lambda v: oy + gh - v * gh / pmax  # noqa: E731
    out = [svg_open(W, H), f'<text x="{W / 2}" y="12" text-anchor="middle" font-weight="bold">{name}</text>',
           f'<rect x="{ox}" y="{oy}" width="{gw}" height="{gh}" fill="#fff" stroke="#000" stroke-width="0.8"/>']
    for v in range(tmin, tmax + 1, 10):
        y = YT(v)
        out.append(f'<line x1="{ox}" y1="{y:.1f}" x2="{ox + gw}" y2="{y:.1f}" stroke="#ddd" stroke-width="0.5"/>')
        out.append(f'<text x="{ox - 3}" y="{y + 3:.1f}" font-size="8" text-anchor="end">{v}</text>')
    for v in range(0, pmax + 1, 100):
        out.append(f'<text x="{ox + gw + 3}" y="{YP(v) + 3:.1f}" font-size="8">{v}</text>')
    out.append(f'<line x1="{ox}" y1="{YT(0):.1f}" x2="{ox + gw}" y2="{YT(0):.1f}" stroke="#999" stroke-width="0.8"/>')
    bw = gw / 12 * 0.6
    for m in range(12):
        if p[m] > 0:
            out.append(f'<rect x="{X(m) - bw / 2:.1f}" y="{YP(p[m]):.1f}" width="{bw:.1f}" height="{p[m] * gh / pmax:.1f}" fill="#7fa7d1" stroke="#335" stroke-width="0.4"/>')
        out.append(f'<text x="{X(m):.1f}" y="{oy + gh + 11}" font-size="8" text-anchor="middle">{m + 1}</text>')
    pts = " ".join(f"{X(m):.1f},{YT(t[m]):.1f}" for m in range(12))
    out.append(f'<polyline points="{pts}" fill="none" stroke="#c0392b" stroke-width="1.8"/>')
    for m in range(12):
        out.append(f'<circle cx="{X(m):.1f}" cy="{YT(t[m]):.1f}" r="1.8" fill="#c0392b"/>')
    out.append(f'<text x="{ox - 30}" y="{oy - 6}" font-size="8">気温（℃）</text>')
    out.append(f'<text x="{ox + gw - 24}" y="{oy - 6}" font-size="8">降水量（mm）</text>')
    out.append(f'<text x="{ox + gw / 2}" y="{oy + gh + 23}" font-size="8" text-anchor="middle">（月）</text>')
    st = stats(t, p)
    out.append(f'<text x="{ox + 4}" y="{oy + 11}" font-size="8">年平均気温 {st["tm"]}℃　年降水量 {st["P"]:,}mm</text>')
    out.append("</svg>")
    return "".join(out)


