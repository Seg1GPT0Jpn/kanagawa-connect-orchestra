def mc4(stem, right, wrongs, e, **kw):
    """正答と誤答候補 [(文, 理由, 誤概念)] から、重複を除いて 4 択を作る。"""
    ch, why = [right], {}
    for w, reason, mis in wrongs:
        if w in ch:
            continue
        ch.append(w)
        why[w] = (reason, mis)
        if len(ch) == 4:
            break
    assert len(ch) == 4, (stem, ch)
    return mc(stem, ch, e, why=why, **kw)


def combo(stem, heads, opts, correct, bad, e, **kw):
    """組み合わせ選択（「X：…　Y：…」）。bad[n] は見出し n の誤った候補 → (理由, 誤概念)。"""
    choices, why, ai = [], {}, 0
    for idx in itertools.product(*[range(len(o)) for o in opts]):
        text = "　".join(f"{h}：{o[k]}" for h, o, k in zip(heads, opts, idx))
        if tuple(idx) == tuple(correct):
            ai = len(choices)
        else:
            rs = [bad[n][opts[n][k]] for n, k in enumerate(idx) if k != correct[n]]
            why[text] = ("".join(x[0] for x in rs), rs[0][1])
        choices.append(text)
    n = len(choices)
    return mc(f"{stem}の組み合わせとして最も適するものを次の1～{n}の中から一つ選び、その番号を答えなさい。", choices, e,
              why=why, keep=True, ai=ai, **kw)


def seigo(stem, stmts, e, **kw):
    """X・Y の正誤の組み合わせ（4択）。stmts=[(見出し, 文, 正しいか, 説明)]。"""
    heads = [s[0] for s in stmts]
    body = "\n".join(f"{h}：{t}" for h, t, _, _ in stmts)
    correct = [0 if s[2] else 1 for s in stmts]
    bad = [{("誤" if ok else "正"): (f"{h}は{'正しい' if ok else '誤り'}。{ex}", "記述の正誤の判断の誤り")} for h, _, ok, ex in stmts]
    return combo(f"{stem}\n{body}\n{'・'.join(heads)}の正誤", heads, [["正", "誤"]] * len(stmts), correct, bad, e, **kw)


def pick2(stem, stmts, e, **kw):
    """a〜d のうち適するもの2つの組み合わせ（6択）。stmts=[(文, 正しいか, 説明)]。"""
    lab = "abcd"
    assert len(stmts) == 4 and sum(1 for s in stmts if s[1]) == 2, stmts
    body = "\n".join(f"{lab[i]}　{s[0]}" for i, s in enumerate(stmts))
    choices, why, ai = [], {}, 0
    for i, j in itertools.combinations(range(4), 2):
        t = f"{lab[i]}と{lab[j]}"
        if stmts[i][1] and stmts[j][1]:
            ai = len(choices)
        else:
            why[t] = ("".join(f"{lab[k]}は適さない。{stmts[k][2]}" for k in (i, j) if not stmts[k][1]), "条件の当てはめの誤り")
        choices.append(t)
    return mc(f"{stem}最も適するものをあとの1～6の中から一つ選び、その番号を答えなさい。\n{body}", choices, e,
              why=why, keep=True, ai=ai, **kw)


def dec(x, nd=2):
    s = f"{x:.{nd}f}".rstrip("0").rstrip(".")
    return s


def rq(x):
    """数値 → 'Rational(p,q)'（検算式用）"""
    f = Fraction(str(x)) if not isinstance(x, Fraction) else x
    return f"Rational({f.numerator},{f.denominator})"


def fx(x):
    """Fraction → 小数表記（割り切れないときは「約」をつけて小数第2位まで）"""
    f = Fraction(x)
    d = f.denominator
    for p in (2, 5):
        while d % p == 0:
            d //= p
    if d != 1:
        return "約" + dec(float(f), 2)
    return dec(float(f), 4)


