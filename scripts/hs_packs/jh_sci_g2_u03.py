def iv_svg(lines, vmax=6, imax=0.6):
    """電圧（横軸）と電流（縦軸）のグラフ。lines=[(抵抗Ω, ラベル)]。"""
    ox, oy, w, h = 50, 170, 240, 150
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 320 210" width="320" height="210" font-family="serif" font-size="10">']
    for k in range(vmax + 1):
        x = ox + w * k / vmax
        out.append(f'<line x1="{x:.1f}" y1="{oy}" x2="{x:.1f}" y2="{oy - h}" stroke="#ddd"/>')
        out.append(f'<text x="{x - 3:.1f}" y="{oy + 13}">{k}</text>')
    steps = 6
    for k in range(steps + 1):
        y = oy - h * k / steps
        out.append(f'<line x1="{ox}" y1="{y:.1f}" x2="{ox + w}" y2="{y:.1f}" stroke="#ddd"/>')
        out.append(f'<text x="{ox - 26}" y="{y + 3:.1f}">{dec(imax * k / steps, 2)}</text>')
    out.append(f'<line x1="{ox}" y1="{oy}" x2="{ox + w + 8}" y2="{oy}" stroke="#000"/><line x1="{ox}" y1="{oy}" x2="{ox}" y2="{oy - h - 8}" stroke="#000"/>')
    out.append(f'<text x="{ox + w - 30}" y="{oy + 30}">電圧〔V〕</text><text x="4" y="{oy - h - 12}">電流〔A〕</text>')
    for R, lab in lines:
        vend = min(vmax, imax * R)
        x2, y2 = ox + w * vend / vmax, oy - h * (vend / R) / imax
        out.append(f'<line x1="{ox}" y1="{oy}" x2="{x2:.1f}" y2="{y2:.1f}" stroke="#1f4e79" stroke-width="1.8"/>')
        out.append(f'<text x="{x2 + 3:.1f}" y="{y2 + 3:.1f}" fill="#1f4e79">{lab}</text>')
    out.append("</svg>")
    return "".join(out)


