@gen("thinking_writing", 2, ["application", "computation"])
def c_pairs(r):
    groups = koto_groups()
    g = r.choice([g for g, ks in groups.items() if len(ks) >= 2])
    hits = r.sample(groups[g], 2)
    rest = r.sample([k for k, _, gg in KOTO if gg not in banned_groups(g)], 4)
    words = hits + rest
    r.shuffle(words)
    lab = {w: PAIRS[i] for i, w in enumerate(words)}
    inv = {v: k for k, v in lab.items()}
    ok = "と".join(sorted(lab[w] for w in hits))
    allp = [f"{PAIRS[i]}と{PAIRS[j]}" for i in range(6) for j in range(i + 1, 6)]
    wrongp = r.sample([p for p in allp if p != ok], 7)

    def why_p(p):
        bad = [inv[c] for c in p.split("と") if inv[c] not in hits]
        return ("、".join(f"{lab[w]}の「{w}」は「{KOTO_M[w]}」という意味" for w in bad) + "なので、条件に当てはまらない。", "ことわざの意味の取り違え")
    listing = "\n".join(f"{lab[w]}　{w}" for w in words)
    return mc(f"次のa〜fのことわざのうち、「{KOTO_M[hits[0]]}」という意味をもつものを二つ選んだときの組み合わせとして最も適するものを、あとの1〜8の中から一つ選び、その番号を答えなさい。\n{listing}",
              [ok] + wrongp, f"「{KOTO_M[hits[0]]}」という意味のことわざは、「{hits[0]}」と「{hits[1]}」である。", d=3,
              ap="六つのことわざの意味をすべて書き出してから、条件に合うものを二つ選ぶ。",
              steps=["a〜fの意味を確かめる：" + "、".join(f"{lab[w]} {w}" for w in words) + "。", f"条件に合うのは {ok}。"],
              alt=["当てはまらないことわざを先に消していき、残った二つが同じ意味かどうかを確かめる。"],
              pc=[("六つのことわざの意味を確かめている", 4), ("正しい組み合わせを選んでいる", 4)],
              pit=["一つ見つけた段階で、残りを確かめずに選ぶ。"], why={p: why_p(p) for p in wrongp})


