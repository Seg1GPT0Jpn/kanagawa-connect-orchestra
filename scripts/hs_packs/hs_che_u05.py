def glycine_fig(pk1=2.3, pk2=9.7):
    k1, k2 = 10 ** -pk1, 10 ** -pk2

    def frac(which):
        def f(ph):
            h = 10 ** -ph
            den = 1 + k1 / h + k1 * k2 / h ** 2
            v = {"c": 1 / den, "z": (k1 / h) / den, "a": (k1 * k2 / h ** 2) / den}[which]
            return 8 * v
        return f
    svg = plane(xr=(0, 14), yr=(-0.8, 9), unit=22, grid=False, ticks=False,
                curves=[(frac("c"), ""), (frac("z"), ""), (frac("a"), "")],
                labels=[(0.3, 8.4, "陽イオン"), (5.0, 8.4, "双性イオン"), (11.2, 8.4, "陰イオン")] 
                + [(x - 0.2, -0.6, str(x)) for x in range(2, 14, 2)],
                points=[(round((pk1 + pk2) / 2, 2), 8 * (1 / (1 + 10 ** (-(pk2 - pk1) / 2) * 2)), "等電点")], xl="pH", yl="割合")
    return figure(f"グリシンの陽イオン・双性イオン・陰イオンの割合と pH の関係（概形）。pH {pk1} 付近で陽イオンと双性イオン、pH {pk2} 付近で双性イオンと陰イオンが等量になり、等電点 pH {round((pk1 + pk2) / 2, 1)} では双性イオンがほとんどを占める。",
                  svg=svg, caption="アミノ酸（グリシン）の電離平衡と pH（概形）")


