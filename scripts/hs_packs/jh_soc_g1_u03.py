def fake_countries(r):
    """架空の国A〜Dの人口（万人）・面積（万km²）・国内総生産（億ドル）。人口密度と1人あたりGDPが整数になるように作る。"""
    for _ in range(500):
        rows = []
        for lab in "ABCD":
            area = r.choice([5, 8, 10, 20, 25, 40, 50, 80, 100, 200])
            dens = r.choice([10, 20, 25, 40, 50, 80, 100, 150, 200, 300])
            pop = area * dens
            per = r.choice([500, 1000, 2000, 4000, 5000, 8000, 10000, 20000, 40000])  # ドル
            gdp = pop * per // 10000
            if gdp * 10000 != pop * per or gdp == 0:
                break
            rows.append(dict(lab=lab, pop=pop, area=area, gdp=gdp, dens=dens, per=per))
        if len(rows) == 4 and len({x["dens"] for x in rows}) == 4 and len({x["per"] for x in rows}) == 4 and len({x["pop"] for x in rows}) == 4 \
                and len({x["gdp"] for x in rows}) == 4 and len({x["area"] for x in rows}) == 4:
            return rows
    raise RuntimeError("fake_countries")


