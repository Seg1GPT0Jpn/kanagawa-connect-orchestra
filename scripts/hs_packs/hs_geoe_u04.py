def fact_q(r, region, lead):
    cs = REGIONS[region]
    right = r.choice(list(cs))
    fact = r.choice(cs[right])
    pool = [c for c in cs if c != right]
    if len(pool) < 3:
        pool += [c for c in ALLC if c not in cs and c != right]
    others = r.sample(pool, 3)
    wr = [(o, f"この説明は{right}に当てはまる。{o}は、{r.choice(ALLC[o][1])}国である。", "国の特色の混同") for o in others]
    return mcw(f"{lead}次の説明に当てはまる国として最も適当なものを選びなさい。\n「{fact}」", right, wr,
               f"{right}は、{fact}国である。", d=1,
               ap="説明の中の手がかり（宗教・言語・政策の名称・地名・産物）を、系統地理で学んだ知識と結びつける。",
               steps=["説明から、宗教・言語・政策・産業などの手がかりを抜き出す。", f"手がかりに合うのは{right}。"],
               alt=["地図帳でそれぞれの国の位置を確かめ、気候や地形と説明が矛盾しないかを確かめる。"],
               pc=[("手がかりを地域の特色と結びつけている", 1), ("正答", 1)], pit=["近隣の国どうしの特色を取り違える。"])


