@gen("standard_practice", 3, ["concept", "application"])
def b_combo(r):
    picks = r.sample(COMBO, 3)
    labels = ["①", "②", "③"]
    letters = ["A", "B", "C"]
    order = list(range(3))
    r.shuffle(order)
    desc_txt = "\n".join(f"{letters[k]}　{picks[order[k]][1]}" for k in range(3))
    reg_txt = "　".join(f"{labels[k]} {picks[k][0]}" for k in range(3))
    right_map = {k: letters[order.index(k)] for k in range(3)}
    right = "　".join(f"{labels[k]}－{right_map[k]}" for k in range(3))
    import itertools
    perms = [p_ for p_ in itertools.permutations(letters) if list(p_) != [right_map[k] for k in range(3)]]
    ws = r.sample(perms, 3)
    wr = []
    for p_ in ws:
        txt = "　".join(f"{labels[k]}－{p_[k]}" for k in range(3))
        bad = [k for k in range(3) if p_[k] != right_map[k]]
        wr.append((txt, f"{picks[bad[0]][0]}の特色は「{picks[bad[0]][1]}」で、{right_map[bad[0]]} にあたる。", "地域と特色の対応の誤り"))
    return mcw(f"次の地域①〜③と、その地域の特色を述べた文 A〜C の組み合わせとして最も適当なものを選びなさい。\n{reg_txt}\n{desc_txt}", right, wr,
               "正しい組み合わせは " + right + "。" + "".join(f"{picks[k][0]}は「{picks[k][1]}」。" for k in range(3)), d=3, p=4,
               ap="確実にわかる組み合わせを1つ決め、残りを絞りこむ。",
               steps=[f"{picks[k][0]} → {right_map[k]}。" for k in range(3)],
               alt=["文 A〜C のキーワード（輸出加工区・原油・一次産品・統合・大土地所有）から、先に地域を特定する。"],
               pc=[("2つ以上の対応を正しく判断している", 2), ("正答", 2)], pit=["1つの対応だけで判断し、残りを確かめない。"])


