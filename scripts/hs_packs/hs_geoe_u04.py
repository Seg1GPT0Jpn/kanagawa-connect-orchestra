@gen("basic_check", 4, ["computation", "condition_check"])
def a_calc(r):
    mode = r.choice(["share", "balance", "percap", "density"])
    cty = r.choice(["A国", "B国", "C国", "D国", "E国"])
    if mode == "share":
        tot = r.choice([20, 40, 50, 80, 100, 200])
        pct = r.choice([15, 25, 35, 40, 45, 60, 65, 75, 80])
        val = tot * pct / 100
        item = r.choice(["原油", "銅", "カカオ豆", "鉄鉱石", "コーヒー豆", "茶"])
        return num(f"{cty}の輸出総額は {tot} 億ドルで、そのうち{item}の輸出額は {g(val)} 億ドルである（架空の資料）。輸出総額に占める{item}の割合は何 % か。",
                   str(pct), f"{g(val)}÷{tot}×100＝{pct} %。", d=1, unit="%",
                   ap="割合＝部分÷全体×100。",
                   steps=[f"{g(val)}÷{tot}＝{pct / 100:g}。", f"×100 で {pct} %。"],
                   alt=[f"{tot} 億ドルの {pct} % が {g(val)} 億ドルになるか、逆算して確かめる。"],
                   pc=[("式を正しく立てている", 1), ("正しい値", 1)], pit=["全体と部分を逆にして割る。"],
                   chk=(f"{val}/{tot}*100", str(pct)))
    if mode == "balance":
        ex = r.choice([120, 250, 380, 450, 600, 720])
        im = r.choice([100, 200, 300, 500, 650, 800])
        while im == ex:
            im = r.choice([100, 200, 300, 500, 650, 800])
        bal = ex - im
        return num(f"{cty}の1年間の輸出額は {ex} 億ドル、輸入額は {im} 億ドルである（架空の資料）。貿易収支は何億ドルか（赤字の場合は負の数で答えなさい）。",
                   str(bal), f"貿易収支＝輸出額－輸入額＝{ex}－{im}＝{bal} 億ドル（{'黒字' if bal > 0 else '赤字'}）。", d=1, unit="億ドル",
                   ap="貿易収支＝輸出額－輸入額。正なら黒字、負なら赤字。",
                   steps=[f"{ex}－{im}＝{bal}。"],
                   alt=["輸出の方が多ければ黒字になるという見当と、符号が合っているかを確かめる。"],
                   pc=[("式を正しく立てている", 1), ("正しい値", 1)], pit=["輸入額－輸出額と逆にする。"],
                   chk=(f"{ex}-{im}", str(bal)))
    if mode == "percap":
        pop = r.choice([5, 8, 10, 20, 25, 40, 50])
        pc_ = r.choice([2000, 4000, 5000, 10000, 20000, 40000, 50000])
        gni = pop * pc_ / 10000
        return num(f"{cty}の人口は {pop} 百万人（{pop * 100} 万人）、国民総所得（GNI）は {g(gni * 100)} 億ドルである（架空の資料）。1人あたりの国民総所得は何ドルか。",
                   f"{pc_:,}", f"{g(gni * 100)} 億ドル÷{pop * 100} 万人＝{g(gni * 100 * 10 ** 8)}÷{pop * 10 ** 6:,}＝{pc_:,} ドル。", d=2, unit="ドル",
                   ap="単位をそろえてから、GNI を人口で割る（1 億＝10⁸、1 百万＝10⁶）。",
                   steps=[f"GNI：{g(gni * 100)} 億ドル＝{g(gni * 100 * 10 ** 8)} ドル。", f"人口：{pop * 10 ** 6:,} 人。", f"割って {pc_:,} ドル。"],
                   alt=[f"「億÷万＝万」なので {g(gni * 100)}÷{pop * 100}＝{g(gni * 100 / (pop * 100))} 万ドル と考えてもよい。"],
                   pc=[("単位をそろえている", 1), ("正しい値", 1)], pit=["億と万の単位をそろえずに割る。"],
                   chk=(f"{gni * 100}*10**8/({pop}*10**6)", str(pc_)))
    area = r.choice([10, 20, 25, 40, 50, 80, 100])
    dens = r.choice([5, 20, 50, 100, 150, 200, 300])
    pop = area * dens
    return num(f"{cty}の面積は {area} 万 km²、人口は {pop:,} 万人である（架空の資料）。人口密度は 1 km² あたり何人か。",
               str(dens), f"{pop:,}÷{area}＝{dens} 人/km²（万どうしで割るので単位はそのまま）。", d=1, unit="人/km²",
               ap="人口密度＝人口÷面積。万人÷万 km² は、人÷km² と同じ。",
               steps=[f"{pop:,}÷{area}＝{dens}。"],
               alt=[f"{dens}×{area}＝{pop:,} で人口に戻るか確かめる。"],
               pc=[("式を正しく立てている", 1), ("正しい値", 1)], pit=["面積÷人口と逆にする。"],
               chk=(f"{pop}/{area}", str(dens)))


