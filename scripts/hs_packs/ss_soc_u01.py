def dec(fr, places=1):
    """Fraction を小数で表す（有限小数のときはそのまま）。"""
    fr = Fr(fr)
    if fr.denominator == 1:
        return str(fr.numerator)
    for k in range(1, 4):
        v = fr * 10 ** k
        if v.denominator == 1:
            neg = v < 0
            s = str(abs(v.numerator)).rjust(k + 1, "0")
            return ("-" if neg else "") + s[:-k] + "." + s[-k:]
    raise ValueError(fr)


def oku(n):
    """億単位の整数を「4兆8000億」のように表す。"""
    if n < 10000:
        return f"{n}億"
    q, m = divmod(n, 10000)
    return f"{q}兆{m}億" if m else f"{q}兆"


def pyfr(fr):
    fr = Fr(fr)
    return str(fr.numerator) if fr.denominator == 1 else f"Rational({fr.numerator},{fr.denominator})"


