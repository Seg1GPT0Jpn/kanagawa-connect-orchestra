@kgen("error_correction", 5, ["common_error", "written_reasoning"])
def d_order(r):
    ev = pick_events(r, 3, gap=3)
    shown = ev[:]
    r.shuffle(shown)
    correct = sorted(range(3), key=lambda i: shown[i][0])
    perms = [list(p) for p in itertools.permutations(range(3)) if list(p) != correct]
    kw_ = r.choice(perms)
    ks = "→".join(ROMAN[i] for i in kw_)
    cs = "→".join(ROMAN[i] for i in correct)
    body = "\n".join(f"{ROMAN[i]}　{shown[i][1]}" for i in range(3))
    yrs = "，".join(f"{ROMAN[i]}は{shown[i][0]}年" for i in range(3))
    right = f"正しい順は{cs}である。"
    wr = []
    for p in perms:
        if p == kw_:
            continue
        ps_ = "→".join(ROMAN[i] for i in p)
        wr.append((f"正しい順は{ps_}である。", f"{yrs}なので，古い順に並べると{cs}になる。", "年代の前後関係の取り違え"))
    r.shuffle(wr)
    wr.append(("Kさんの並べ方は正しい。", f"Kさんの{ks}は古い順になっていない。正しくは{cs}。", "年代の前後関係の取り違え"))
    return mc4(f"Kさんは，次のⅠ～Ⅲのできごとを年代の古い順に並べ，「{ks}」と答えた。\n{body}\nKさんの答えについて，正しく直したものとして，{ASK4}",
               right, wr, f"{yrs}なので，{right}", d=3,
               ap="それぞれのできごとの年代を確かめてから並べ直す。年代を忘れたときは因果の流れで判断する。",
               steps=[f"年代を確かめる：{yrs}。", "古い順に並べる。", f"正しくは{cs}。"],
               alt=["2つずつ前後関係を確かめ（ⅠとⅡ，ⅡとⅢ…），矛盾がないか確認する。"],
               pc=[("年代を正しく確かめている", 2), ("正しい順に直している", 4)],
               pit=["見た目の印象や，同じ人物が登場することから順番を決めてしまう。"],
               err=dict(sol=f"Ⅰ～Ⅲを古い順に並べると{ks}", step="年代の前後を確かめずに並べた部分", type="logic",
                        tempt="因果関係や年代を確かめず，印象で並べたため。", fix=cs),
               chk=(f"{shown[correct[2]][0]}-{shown[correct[0]][0]}", str(shown[correct[2]][0] - shown[correct[0]][0]), None, "intermediate"))


