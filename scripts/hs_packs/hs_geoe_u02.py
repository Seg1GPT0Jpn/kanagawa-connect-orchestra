def rent(c, d):
    """c = (名称, 収量 t/ha, 価格 万円/t, 生産費 万円/t, 輸送費 万円/(t・km))。地代（万円/ha）。"""
    _, Y, p, cost, f = c
    return Y * (p - cost) - Y * f * d


def rent_expr(c, d):
    _, Y, p, cost, f = c
    return f"{Y}*({p}-{cost})-{Y}*{f}*{d}"


def rent_svg(crops, dmax):
    """付け値地代曲線（距離と地代の直線）。"""
    W, H, ox, oy, gw, gh = 300, 210, 46, 16, 230, 160
    top = max(rent(c, 0) for c in crops)
    top = ((top + 49) // 50) * 50
    X = lambda d: ox + d * gw / dmax  # noqa: E731
    Y = lambda v: oy + gh - v * gh / top  # noqa: E731
    cols = ["#c0392b", "#1f77b4", "#2e7d32"]
    dash = ["", ' stroke-dasharray="5,3"', ' stroke-dasharray="2,2"']
    out = [svg_open(W, H), f'<rect x="{ox}" y="{oy}" width="{gw}" height="{gh}" fill="#fff" stroke="#000" stroke-width="0.8"/>']
    step = 50 if top <= 300 else 100
    for v in range(0, top + 1, step):
        out.append(f'<line x1="{ox}" y1="{Y(v):.1f}" x2="{ox + gw}" y2="{Y(v):.1f}" stroke="#ddd" stroke-width="0.5"/>')
        out.append(f'<text x="{ox - 3}" y="{Y(v) + 3:.1f}" font-size="8" text-anchor="end">{v}</text>')
    dstep = 10 if dmax <= 60 else 20
    for d in range(0, dmax + 1, dstep):
        out.append(f'<text x="{X(d):.1f}" y="{oy + gh + 11}" font-size="8" text-anchor="middle">{d}</text>')
    for i, c in enumerate(crops):
        d0 = min(dmax, rent(c, 0) / (c[1] * c[4]))
        out.append(f'<line x1="{X(0):.1f}" y1="{Y(rent(c, 0)):.1f}" x2="{X(d0):.1f}" y2="{Y(rent(c, d0)):.1f}" stroke="{cols[i]}" stroke-width="1.8"{dash[i]}/>')
        out.append(f'<text x="{X(0) + 4:.1f}" y="{Y(rent(c, 0)) - 3:.1f}" font-size="8" fill="{cols[i]}">{c[0]}</text>')
    out.append(f'<text x="{ox - 40}" y="{oy - 4}" font-size="8">地代（万円/ha）</text>')
    out.append(f'<text x="{ox + gw / 2}" y="{oy + gh + 23}" font-size="8" text-anchor="middle">市場からの距離（km）</text>')
    out.append("</svg>")
    return "".join(out)


def rent_fig(crops, dmax):
    alt = "市場からの距離と、作物ごとの地代の関係を表す直線のグラフ。" + "。".join(
        f"{c[0]}：距離 0 km で {g(rent(c, 0))} 万円/ha、1 km 遠くなるごとに {g(c[1] * c[4])} 万円/ha 減る" for c in crops) + "。"
    return figure(alt, rent_svg(crops, dmax), caption="図　距離と地代の関係（架空の資料）")


def thunen_set(r):
    """3つの土地利用。境界の距離が整数になり、近い順に 野菜 → 酪農 → 小麦 となるもの。"""
    while True:
        f = r.choice([1, 2])
        A = ("野菜", r.choice([20, 25, 30]), None, None, f)
        B = ("牧草（酪農）", r.choice([8, 10, 12]), None, None, f)
        C = ("小麦", r.choice([3, 4, 5]), None, None, f)
        mA, mB, mC = r.randint(6, 14), r.randint(6, 14), r.randint(6, 16)
        crops = []
        for (nm, Y, _, _, ff), m in zip((A, B, C), (mA, mB, mC)):
            cost = r.choice([2, 3, 4, 5])
            crops.append((nm, Y, cost + m, cost, ff))
        a, b, c = crops
        d1n = a[1] * (a[2] - a[3]) - b[1] * (b[2] - b[3])
        d1d = f * (a[1] - b[1])
        d2n = b[1] * (b[2] - b[3]) - c[1] * (c[2] - c[3])
        d2d = f * (b[1] - c[1])
        if d1n <= 0 or d2n <= 0 or d1n % d1d or d2n % d2d:
            continue
        d1, d2 = d1n // d1d, d2n // d2d
        d3 = (c[2] - c[3]) // f if (c[2] - c[3]) % f == 0 else None
        if 3 <= d1 < d2 and d3 and d2 + 3 <= d3 <= 80:
            return crops, d1, d2, d3


