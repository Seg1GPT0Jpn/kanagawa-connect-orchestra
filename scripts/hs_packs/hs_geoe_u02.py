def g(x):
    v = round(x, 2)
    return f"{v:g}" if v >= 0 else f"−{-v:g}"


def svg_open(w, h):
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" width="{w}" height="{h}" '
            f'font-family="serif" font-size="11">')


