def err_item(stem, wrong, step, etype, tempt, fix, expl, steps, ap, alt, pit, d=3, **kw):
    return desc(f"{stem}\n［ある生徒の解答］\n{wrong}\n上の解答の誤りを指摘し、正しく直しなさい。", fix, expl,
                [("誤りの箇所と理由を正しく指摘している", 2), ("正しい解答を根拠とともに示している", 3), ("最終的な解答が設問に合った形になっている", 1)], d=d, p=6, lines=6,
                ap=ap, steps=steps, alt=alt, pc=[("誤りの指摘", 2), ("根拠を示した訂正", 3), ("解答の形", 1)], pit=pit,
                err=dict(sol=wrong, step=step, type=etype, tempt=tempt, fix=fix), **kw)


@gen("error_correction", 4, ["common_error", "condition_check"])
def d_trans(r):
    key, ph, hint, a, ws, need, er = r.choice(TRANS)
    wrong, step, etype, tempt = er
    return err_item(f"（{ksrc(key)}）本文中の「{ph}」を現代語訳しなさい。", wrong, step, etype, tempt, a,
                    f"誤りは「{step}」にある。採点要素は、{'／'.join(need)}。",
                    ["傍線部を品詞に分解し、要素に印をつける。", "生徒の訳で、各要素がどう訳されているかを照合する。", "誤っている要素を正しく訳し直し、全体を整える。"],
                    "誤訳の点検は、要素ごとに「本文の語→生徒の訳→正しい訳」を並べて比べる。",
                    ["訂正した訳を古文に戻してみて、本文の語と一つずつ対応するかを確かめる。"],
                    ["現代語の意味で訳す。", "助動詞・助詞の意味を接続や文脈で確かめない。"], d=3, stim=kstim(key))


