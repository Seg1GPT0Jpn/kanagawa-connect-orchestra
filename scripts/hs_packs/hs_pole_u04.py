def hround(fr, nd):
    fr = Fraction(fr)
    m = 10 ** nd
    v = (fr * m * 2 + 1) // 2
    sg = "-" if v < 0 else ""
    v = abs(v)
    s = sg + f"{v // m}" + (f".{str(v % m).rjust(nd, '0')}" if nd else "")
    return s, f"floor(Rational({fr.numerator}*{m},{fr.denominator})+Rational(1,2))/{m}"


def tie(fr, nd):
    return (Fraction(fr) * 10 ** (nd + 1)) % 10 == 5


def dec(fr):
    fr = Fraction(fr)
    if fr.denominator == 1:
        return str(fr.numerator)
    for k in range(1, 4):
        v = fr * 10 ** k
        if v.denominator == 1:
            s = str(abs(v.numerator)).rjust(k + 1, "0")
            return ("-" if fr < 0 else "") + s[:-k] + "." + s[-k:]
    raise ValueError(fr)


def sg(v):
    return f"{v}" if v < 0 else f"+{v}"


