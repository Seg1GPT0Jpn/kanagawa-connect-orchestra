def pick_comp(r):
    """比較生産費の表（Ｘ国の人数 x1, x2、Ｙ国 y1, y2）。Ｘ国は両方で絶対優位、比較優位は財1か財2。"""
    while True:
        x1, x2 = r.choice(range(10, 101, 10)), r.choice(range(10, 101, 10))
        y1, y2 = r.choice(range(20, 161, 10)), r.choice(range(20, 161, 10))
        if not (x1 < y1 and x2 < y2):
            continue
        if Fraction(x1, x2) == Fraction(y1, y2):
            continue
        k = 0 if Fraction(x1, x2) < Fraction(y1, y2) else 1
        xs = (x1 + x2) / (x1 if k == 0 else x2)
        ys = (y1 + y2) / (y2 if k == 0 else y1)
        fx = Fraction(x1 + x2, x1 if k == 0 else x2)
        fy = Fraction(y1 + y2, y2 if k == 0 else y1)
        try:
            dec(fx), dec(fy)
        except ValueError:
            continue
        if xs > 0 and ys > 0:
            return x1, x2, y1, y2, k, fx, fy


