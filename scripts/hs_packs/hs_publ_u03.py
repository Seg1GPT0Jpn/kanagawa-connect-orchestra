def dec(fr):
    """有限小数で表せる Fraction を文字列にする（整数ならそのまま）。"""
    fr = Fraction(fr)
    if fr.denominator == 1:
        return str(fr.numerator)
    for k in range(1, 4):
        v = fr * 10 ** k
        if v.denominator == 1:
            s = str(v.numerator).rjust(k + 1, "0")
            return s[:-k] + "." + s[-k:]
    raise ValueError(fr)


