def meaning_of(form):
    """その敬語がどの動詞の何という敬語か。"""
    out = []
    for v, (a, b) in SPECIAL.items():
        if form in a:
            out.append(f"「{v}」の尊敬語")
        if form in b:
            out.append(f"「{v}」の謙譲語")
    return "・".join(out)


