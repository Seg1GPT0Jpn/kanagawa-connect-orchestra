@gen("basic_check", 5, ["concept", "computation"])
def a_kind(r):
    s, w, k, reason = r.choice(KSENT)
    wrongs = [x for x in KINDS if x != k]
    why = {x: (f"{KIND_WHY[x]}。「{w}」は{reason}ので{k}{'' if k == '敬語は使われていない' else 'である'}。", "敬語の種類の取り違え") for x in wrongs}
    return mc(f"次の文中の――線をつけた部分について説明したものとして最も適するものを、{CH}\n{s}", choices(k, wrongs),
              f"「{w}」は{reason}。よって{k}。", d=1,
              ap="まず「だれの動作か」を確かめ、その人を高めているのか、自分の側をへりくだっているのか、聞き手に丁寧に述べているのかを考える。",
              steps=["文の主語（動作をしている人）を確かめる。", f"「{w}」の働きを考える：{reason}。", f"答え：{k}"],
              alt=["――線部を普通の言い方に戻してみて（いらっしゃる→いる など）、どんな敬意が加わっていたかを確かめる。"],
              pc=[("だれの動作かを確かめている", 1), ("敬語の種類を正しく選んでいる", 1)],
              pit=["「お」がついていれば尊敬語だと考える（お～する は謙譲語）。", "「です・ます」と尊敬語・謙譲語を区別しない。"], why=why)


@gen("basic_check", 5, ["computation", "condition_check"])
def a_special(r):
    v = r.choice([x for x in SPECIAL if SPECIAL[x][0] or SPECIAL[x][1]])
    kinds = [k for k in ("尊敬語", "謙譲語") if forms_of(v, k)]
    k = r.choice(kinds)
    ok = r.choice(forms_of(v, k))
    other = "謙譲語" if k == "尊敬語" else "尊敬語"
    wrongs = list(forms_of(v, other))[:1]
    correct_set = set(forms_of(v, k))
    pool = [f for f in ALL_FORMS if f not in correct_set and f not in wrongs and v not in meaning_of(f).replace("「", " ").replace("」", " ").split()]
    pool = [f for f in pool if f"「{v}」" not in meaning_of(f)]
    wrongs += r.sample(pool, 3 - len(wrongs))
    why = {x: (f"「{x}」は{meaning_of(x)}である。", "特別な動詞の取り違え") for x in wrongs}
    return mc(f"動詞「{v}」の{k}として最も適するものを、{CH}", choices(ok, wrongs),
              f"「{v}」の{k}は「{'」「'.join(forms_of(v, k))}」。", d=1,
              ap=f"{k}は「{'相手の動作を高める' if k == '尊敬語' else '自分の動作をへりくだる'}」言い方。選択肢のそれぞれが、どの動詞の何という敬語かを確かめる。",
              steps=[f"「{v}」の{k}を思い出す。", "選択肢を一つずつ、元の動詞と種類に戻して確かめる：" + "、".join(f"{x}＝{meaning_of(x)}" for x in [ok] + wrongs) + "。", f"答え：{ok}"],
              alt=[f"「{'先生が' if k == '尊敬語' else '私が'}～」という文を作って当てはめ、自然な敬語の文になるかを確かめる。"],
              pc=[("尊敬語・謙譲語の働きを区別している", 1), ("正しい特別な動詞を選んでいる", 1)],
              pit=["尊敬語と謙譲語を逆に覚えている（おっしゃる／申す など）。", "意味の違う動詞の敬語（お目にかける＝見せる）と取り違える。"], why=why)


