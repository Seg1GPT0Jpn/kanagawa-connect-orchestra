def row_points(kind, n, ox):
    pts, segs = {}, set()

    def P(x, y):
        key = f"{round(x, 3)}_{round(y, 3)}"
        pts[key] = (x, y)
        return key

    if kind == "square":
        for i in range(n):
            a, b, c, d = P(ox + i, 0), P(ox + i + 1, 0), P(ox + i + 1, 1), P(ox + i, 1)
            for s in ((a, b), (b, c), (d, c), (a, d)):
                segs.add(tuple(sorted(s)))
    elif kind == "triangle":
        h = 0.87
        for i in range(n):
            m = i // 2
            if i % 2 == 0:
                a, b, c = P(ox + m, 0), P(ox + m + 1, 0), P(ox + m + 0.5, h)
            else:
                a, b, c = P(ox + m + 0.5, h), P(ox + m + 1.5, h), P(ox + m + 1, 0)
            for s in ((a, b), (b, c), (a, c)):
                segs.add(tuple(sorted(s)))
    else:
        r = 0.58
        w = math.sqrt(3) * r
        for i in range(n):
            cx = ox + w / 2 + i * w
            vs = [P(cx + r * math.cos(math.radians(30 + 60 * k)), r + r * math.sin(math.radians(30 + 60 * k))) for k in range(6)]
            for k in range(6):
                segs.add(tuple(sorted((vs[k], vs[(k + 1) % 6]))))
    return pts, segs


def row_figure(kind):
    pts, segs, texts, ox = {}, set(), [], 0.0
    width = {"square": 1.0, "triangle": 0.5, "hexagon": math.sqrt(3) * 0.58}
    for n in (1, 2, 3):
        p, s = row_points(kind, n, ox)
        pts.update(p)
        segs |= s
        span = (n if kind != "triangle" else (n + 1) / 2) * width[kind] if kind != "triangle" else (n + 1) / 2
        texts.append((ox + span / 2 - 0.45, -0.45, f"{n}番目"))
        ox += span + 1.0
    name = {"square": "正方形", "triangle": "正三角形", "hexagon": "正六角形"}[kind]
    return figure(f"同じ長さの棒で{name}を横1列につなげた図。1番目は{name}1個、2番目は2個、3番目は3個。",
                  shape(pts, labels=[], segments=sorted(segs), scale=34, texts=texts))


