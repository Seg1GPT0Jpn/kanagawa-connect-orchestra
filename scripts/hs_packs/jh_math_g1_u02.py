def ft(x):
    x = Fr(x)
    if x.denominator == 1:
        return str(x.numerator)
    s = "-" if x < 0 else ""
    return f"{s}\\dfrac{{{abs(x.numerator)}}}{{{x.denominator}}}"


def M(x):
    return f"${ft(x)}$"


def sn(v):
    return f"(+{v})" if v > 0 else f"({v})"


def lin(a, b, v="x"):
    """ax+b（整数係数）の LaTeX。"""
    return poly(a, b, var=v)


def L(a, b, v="x"):
    return f"${lin(a, b, v)}$"


def lpy(a, b, v="x"):
    return f"({a})*{v}+({b})"


def fracexpr(A, B, D, v="x"):
    """(Ax+B)/D を既約にして LaTeX で返す（D>0）。"""
    if A == 0:
        return ft(Fr(B, D))
    g = math.gcd(math.gcd(abs(A), abs(B)), D)
    A, B, D = A // g, B // g, D // g
    if D == 1:
        return lin(A, B, v)
    if A < 0 and B <= 0:
        return f"-\\dfrac{{{lin(-A, -B, v)}}}{{{D}}}"
    return f"\\dfrac{{{lin(A, B, v)}}}{{{D}}}"


def cm(k):
    """係数1を省いた表記（1(x+2) → (x+2)）。"""
    return "" if k == 1 else str(k)


def pick(correct, cands, k=4):
    ch, why = [correct], {}
    for t, rs, mi in cands:
        if t in ch:
            continue
        ch.append(t)
        why[t] = (rs, mi)
        if len(ch) == k:
            break
    if len(ch) < k:
        raise ValueError("誤答候補が足りません")
    return ch, why


