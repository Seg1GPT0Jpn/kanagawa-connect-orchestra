def hround(fr, nd):
    """Fraction を小数第 nd 位までに四捨五入した文字列と、sympy 用の検算式を返す。"""
    fr = Fraction(fr)
    m = 10 ** nd
    v = (fr * m * 2 + 1) // 2
    sgn = "-" if v < 0 else ""
    v = abs(v)
    s = sgn + f"{v // m}" + (f".{str(v % m).rjust(nd, '0')}" if nd else "")
    return s, f"floor(Rational({fr.numerator}*{m},{fr.denominator})+Rational(1,2))/{m}"


def tie(fr, nd):
    """四捨五入の境界（ちょうど5）にあたるか。"""
    return (Fraction(fr) * 10 ** (nd + 1)) % 10 == 5


def dec(fr):
    fr = Fraction(fr)
    if fr.denominator == 1:
        return str(fr.numerator)
    for k in range(1, 4):
        v = fr * 10 ** k
        if v.denominator == 1:
            s = str(abs(v.numerator)).rjust(k + 1, "0")
            return ("-" if fr < 0 else "") + s[:-k] + "." + s[-k:]
    raise ValueError(fr)


