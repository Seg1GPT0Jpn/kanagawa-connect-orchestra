def prog_tax(income, br):
    tax = Fraction(0)
    lo = 0
    parts = []
    for hi, rate in br:
        top = income if hi is None else min(income, hi)
        if top > lo:
            tax += Fraction((top - lo) * rate, 100)
            parts.append((lo, top, rate))
        if hi is None or income <= hi:
            break
        lo = hi
    return tax, parts


