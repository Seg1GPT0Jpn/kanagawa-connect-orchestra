def pick_events(r, k, gap=5, pool=None):
    pool = pool or EVENTS
    while True:
        ev = sorted(r.sample(pool, k))
        if all(ev[i + 1][0] - ev[i][0] >= gap for i in range(k - 1)):
            return ev


