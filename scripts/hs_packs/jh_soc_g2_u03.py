    out = ['<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 620 90" width="620" height="90" font-family="sans-serif" font-size="10">',
           '<line x1="10" y1="45" x2="610" y2="45" stroke="#333" stroke-width="1.5"/>']
    for i, (yr, lab) in enumerate(pts):
        x = 10 + (yr - x0) / (x1 - x0) * 600
        out.append(f'<line x1="{x:.1f}" y1="40" x2="{x:.1f}" y2="50" stroke="#1f4e79" stroke-width="2"/>')
        ty = 30 if i % 2 == 0 else 68
        out.append(f'<text x="{x:.1f}" y="{ty}" text-anchor="middle">{yr} {lab}</text>')
    out.append("</svg>")
    return "".join(out)


