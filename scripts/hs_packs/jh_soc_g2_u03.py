def mc4(stem, right, wrongs, e, **kw):
    """正答と誤答候補 [(文, 理由, 誤概念)] から重複を除いて4択を作る。"""
    ch, why = [right], {}
    for w, reason, mis in wrongs:
        if w in ch:
            continue
        ch.append(w)
        why[w] = (reason, mis)
        if len(ch) == 4:
            break
    assert len(ch) == 4, (stem, ch)
    return mc(stem, ch, e, why=why, **kw)


def combo(stem, heads, opts, correct, bad, e, **kw):
    """組み合わせ選択（「あ：…　い：…」）。bad[n][誤った候補] → (理由, 誤概念)。"""
    choices, why, ai = [], {}, 0
    for idx in itertools.product(*[range(len(o)) for o in opts]):
        text = "　".join(f"{h}：{o[k]}" for h, o, k in zip(heads, opts, idx))
        if tuple(idx) == tuple(correct):
            ai = len(choices)
        else:
            rs = [bad[n][opts[n][k]] for n, k in enumerate(idx) if k != correct[n]]
            why[text] = ("".join(x[0] for x in rs), rs[0][1])
        choices.append(text)
    n = len(choices)
    return mc(f"{stem}の組み合わせとして最も適するものを，次の1～{n}の中から一つ選び，その番号を答えなさい。", choices, e,
              why=why, keep=True, ai=ai, **kw)


def seigo(stem, stmts, e, **kw):
    """X・Y の正誤の組み合わせ（4択）。stmts=[(見出し, 文, 正しいか, 説明)]。"""
    heads = [s[0] for s in stmts]
    body = "\n".join(f"{h}　{t}" for h, t, _, _ in stmts)
    correct = [0 if s[2] else 1 for s in stmts]
    bad = [{("誤" if ok else "正"): (f"{h}は{'正しい' if ok else '誤り'}。{ex}", "記述の正誤の判断の誤り")} for h, _, ok, ex in stmts]
    return combo(f"{stem}\n{body}\n{'，'.join(heads)}の文の正誤", heads, [["正", "誤"]] * len(stmts), correct, bad, e, **kw)


def pick2(stem, stmts, e, **kw):
    """a〜d のうち正しいもの2つの組み合わせ（6択）。stmts=[(文, 正しいか, 説明)]。"""
    lab = "abcd"
    assert len(stmts) == 4 and sum(1 for s in stmts if s[1]) == 2, stmts
    body = "\n".join(f"{lab[i]}　{s[0]}" for i, s in enumerate(stmts))
    choices, why, ai = [], {}, 0
    for i, j in itertools.combinations(range(4), 2):
        t = f"{lab[i]}と{lab[j]}"
        if stmts[i][1] and stmts[j][1]:
            ai = len(choices)
        else:
            why[t] = ("".join(f"{lab[k]}は誤り。{stmts[k][2]}" for k in (i, j) if not stmts[k][1]), "記述の正誤の判断の誤り")
        choices.append(t)
    return mc(f"{stem}\n{body}", choices, e, why=why, keep=True, ai=ai, **kw)


def perm3(stem, labels, names, correct, reason, e, **kw):
    """3つの記号（X,Y,Z）と3つの名前の対応（6択）。correct[i] は labels[i] に対応する names の番号。"""
    choices, why, ai = [], {}, 0
    for perm in itertools.permutations(range(3)):
        t = "　".join(f"{labels[i]}：{names[perm[i]]}" for i in range(3))
        if list(perm) == list(correct):
            ai = len(choices)
        else:
            why[t] = (reason, "資料の特徴と地域の特色の結びつけの誤り")
        choices.append(t)
    return mc(f"{stem}の組み合わせとして最も適するものを，あとの1～6の中から一つ選び，その番号を答えなさい。", choices, e,
              why=why, keep=True, ai=ai, **kw)


def dec(x, nd=1):
    return f"{x:.{nd}f}".rstrip("0").rstrip(".")


ROMAN = "ⅠⅡⅢ"


def order3(stem, items, correct, rule, e, **kw):
    """Ⅰ〜Ⅲの年代整序（6択）。items は表示順の文、correct は古い順に並べた番号の列。"""
    choices, why, ai = [], {}, 0
    for perm in itertools.permutations(range(3)):
        t = "→".join(ROMAN[i] for i in perm)
        if list(perm) == list(correct):
            ai = len(choices)
        else:
            why[t] = (f"この順は年代の古い順になっていない。{rule}", "年代の前後関係の取り違え")
        choices.append(t)
    body = "\n".join(f"{ROMAN[i]}　{items[i]}" for i in range(3))
    return mc(f"{stem}年代の古い順に並べたものとして最も適するものを，あとの1～6の中から一つ選び，その番号を答えなさい。\n{body}", choices, e,
              why=why, keep=True, ai=ai, **kw)


