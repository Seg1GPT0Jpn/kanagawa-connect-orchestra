def _kp(x):
    if isinstance(x, str):
        return x.replace("、", "，")
    if isinstance(x, list):
        return [_kp(v) for v in x]
    if isinstance(x, tuple):
        return tuple(_kp(v) for v in x)
    if isinstance(x, dict):
        return {(_kp(k) if isinstance(k, str) else k): (v if k == "chk" else _kp(v)) for k, v in x.items()}
    return x


def kgen(level, n, ps, rel=None):
    def deco(fn):
        def wrapped(r):
            return _kp(fn(r))
        wrapped.__name__ = fn.__name__
        return gen(level, n, ps, rel=rel)(wrapped)
    return deco


