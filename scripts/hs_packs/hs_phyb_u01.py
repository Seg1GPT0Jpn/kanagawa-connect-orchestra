def frac_t(a):
    return f"\\dfrac{{{a.p}}}{{{a.q}}}"


def ftex(a):
    a = sp.Rational(a)
    q = a.q
    for f in (2, 5):
        while q % f == 0:
            q //= f
    return dec(a) if q == 1 else frac_t(a)


