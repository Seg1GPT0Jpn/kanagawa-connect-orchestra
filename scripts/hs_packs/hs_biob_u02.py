@gen("error_correction", 3, ["common_error", "computation"])
def err_kidney(r):
    ratio = r.choice([100, 110, 120, 125, 130, 150])
    urine = r.choice([1, 2, 3])
    prim = urine * ratio
    mode = r.choice(["div", "reab"])
    if mode == "div":
        return err_item(f"イヌリンの濃縮率が {ratio}、1分間の尿量が {urine} mL のとき、1分間につくられる原尿の量を求めなさい。（イヌリンは再吸収も分泌もされない）",
                        f"原尿量＝{urine}÷{ratio}＝{urine / ratio:.4g} mL", "尿量を濃縮率で割った部分", "formula",
                        "「濃縮率」という語から割り算を連想し、原尿と尿のどちらが多いかを考えていない。",
                        f"原尿の水の大部分が再吸収されて尿になるので、原尿量＝尿量×濃縮率＝{prim} mL", f"{prim} mL",
                        "イヌリンの量は原尿中と尿中で等しいので、原尿量×血しょう中濃度＝尿量×尿中濃度。", [f"原尿量＝尿量×（尿中濃度÷血しょう中濃度）。", f"＝{urine}×{ratio}＝{prim} mL。"],
                        "原尿は尿よりずっと多い（水が再吸収されるから）ことを先に確認する。", [f"答えの {prim} mL は尿量 {urine} mL より多く、妥当である。"], ["濃縮率で割ってしまう。"],
                        chk=(f"{urine}*{ratio}", str(prim), None, "intermediate"))
    pc_ = r.choice([2, 3])          # 尿素の血しょう中濃度 ×0.1 mg/mL
    uc = r.choice([40, 50, 60])     # 尿中濃度 ×0.1 mg/mL
    filt = prim * pc_ / 10
    excr = urine * uc / 10
