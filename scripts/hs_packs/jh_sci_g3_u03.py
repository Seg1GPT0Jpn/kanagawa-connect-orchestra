def _arrow(x1, y1, x2, y2, color="#c00", w=2.2, dash=None):
    d = f' stroke-dasharray="{dash}"' if dash else ""
    ang = math.atan2(y2 - y1, x2 - x1)
    hx1, hy1 = x2 - 9 * math.cos(ang - 0.4), y2 - 9 * math.sin(ang - 0.4)
    hx2, hy2 = x2 - 9 * math.cos(ang + 0.4), y2 - 9 * math.sin(ang + 0.4)
    return (f'<line x1="{x1:.1f}" y1="{y1:.1f}" x2="{x2:.1f}" y2="{y2:.1f}" stroke="{color}" stroke-width="{w}"{d}/>'
            f'<polygon points="{x2:.1f},{y2:.1f} {hx1:.1f},{hy1:.1f} {hx2:.1f},{hy2:.1f}" fill="{color}"/>')


def force_grid(vecs, n=6, u=20):
    """方眼（1目盛り＝1 N）の中心 O から力の矢印をかく。vecs=[(dx, dy, 名前, 色)]（dy は上向きが正）。"""
    W = 2 * n * u
    o = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W + 20} {W + 20}" width="{W + 20}" height="{W + 20}" font-family="serif" font-size="12">']
    for i in range(2 * n + 1):
        o.append(f'<line x1="{10 + i * u}" y1="10" x2="{10 + i * u}" y2="{10 + W}" stroke="#ddd"/>')
        o.append(f'<line x1="10" y1="{10 + i * u}" x2="{10 + W}" y2="{10 + i * u}" stroke="#ddd"/>')
    cx = cy = 10 + n * u
    o.append(f'<circle cx="{cx}" cy="{cy}" r="3"/><text x="{cx - 14}" y="{cy + 14}">O</text>')
    for dx, dy, name, col in vecs:
        x2, y2 = cx + dx * u, cy - dy * u
        o.append(_arrow(cx, cy, x2, y2, col))
        o.append(f'<text x="{x2 + (6 if dx >= 0 else -22):.0f}" y="{y2 + (-4 if dy >= 0 else 14):.0f}" fill="{col}">{name}</text>')
    o.append("</svg>")
    return "".join(o)


def tape_svg(lens, unit_label):
    """記録テープを 0.1 秒ごとに切って順にはったグラフ。lens は cm。"""
    m = max(lens)
    sc = 150 / max(m, 1)
    n = len(lens)
    W = 60 + n * 34
    o = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} 200" width="{W}" height="200" font-family="serif" font-size="11">',
         '<line x1="40" y1="170" x2="{0}" y2="170" stroke="#000"/>'.format(W - 10), '<line x1="40" y1="170" x2="40" y2="10" stroke="#000"/>']
    step = 2 if m <= 12 else (5 if m <= 30 else 10)
    v = 0
    while v <= m + 1e-9:
        y = 170 - v * sc
        o.append(f'<line x1="36" y1="{y:.1f}" x2="40" y2="{y:.1f}" stroke="#000"/><text x="8" y="{y + 4:.1f}">{v}</text>')
        v += step
    for i, L in enumerate(lens):
        x = 50 + i * 34
        o.append(f'<rect x="{x}" y="{170 - L * sc:.1f}" width="26" height="{L * sc:.1f}" fill="#f3ead2" stroke="#333"/>')
        o.append(f'<text x="{x + 8}" y="186">{"①②③④⑤⑥⑦⑧"[i]}</text>')
    o.append(f'<text x="44" y="12">〔cm〕</text><text x="{W - 90}" y="198">{unit_label}</text>')
    o.append("</svg>")
    return "".join(o)


def track_svg(pts):
    """レールの断面（点 A〜E の高さ）。pts=[(名前, 高さ cm)]。"""
    H = max(h for _, h in pts)
    sc = 120 / H
    xs = [30 + i * 70 for i in range(len(pts))]
    W = xs[-1] + 40
    path = []
    for i, (name, h) in enumerate(pts):
        y = 150 - h * sc
        path.append(f"{xs[i]},{y:.1f}")
    o = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} 180" width="{W}" height="180" font-family="serif" font-size="12">',
         f'<line x1="10" y1="150" x2="{W - 10}" y2="150" stroke="#999" stroke-dasharray="4 3"/>',
         f'<polyline points="{" ".join(path)}" fill="none" stroke="#333" stroke-width="2.5" stroke-linejoin="round"/>']
    for i, (name, h) in enumerate(pts):
        y = 150 - h * sc
        o.append(f'<circle cx="{xs[i]}" cy="{y:.1f}" r="4" fill="#1f4e79"/><text x="{xs[i] - 5}" y="{y - 9:.1f}">{name}</text>')
        o.append(f'<line x1="{xs[i]}" y1="{y + 6:.1f}" x2="{xs[i]}" y2="150" stroke="#bbb" stroke-dasharray="2 2"/><text x="{xs[i] - 12}" y="168">{h}cm</text>')
    o.append("</svg>")
    return "".join(o)


def buoy_svg(W, b, H, xmax=10):
    """ばねばかりの値〔N〕と、物体の底面の水面からの深さ〔cm〕のグラフ。"""
    sx, sy = 26, 120 / W
    o = ['<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 340 190" width="340" height="190" font-family="serif" font-size="11">',
         '<line x1="50" y1="150" x2="320" y2="150" stroke="#000"/><line x1="50" y1="150" x2="50" y2="15" stroke="#000"/>']
    for k in range(0, xmax + 1, 2):
        x = 50 + k * sx
        o.append(f'<line x1="{x}" y1="150" x2="{x}" y2="154" stroke="#000"/><text x="{x - 4}" y="166">{k}</text>')
    steps = [Fraction(W) * i / 4 for i in range(5)]
    for v in steps:
        y = 150 - float(v) * sy
        o.append(f'<line x1="46" y1="{y:.1f}" x2="320" y2="{y:.1f}" stroke="#eee"/><text x="14" y="{y + 4:.1f}">{dec(v, 2)}</text>')
    y0 = 150 - float(W) * sy
    y1 = 150 - float(W - b) * sy
    o.append(f'<polyline points="50,{y0:.1f} {50 + H * sx},{y1:.1f} {50 + xmax * sx},{y1:.1f}" fill="none" stroke="#1f4e79" stroke-width="2"/>')
    o.append('<text x="160" y="184">水面から物体の底面までの深さ〔cm〕</text><text x="54" y="12">ばねばかりの値〔N〕</text></svg>')
    return "".join(o)


