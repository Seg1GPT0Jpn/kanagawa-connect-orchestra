def _feat_stmt(r, P, Q):
    gp, gq = GROUP_OF[P], GROUP_OF[Q]
    pos, neg, s = r.choice(PFEAT)
    fp, fq = gp in s, gq in s
    form = r.choice(["both", "only"])
    if form == "both":
        text = f"{P}も{Q}も{pos}。"
        ok = fp and fq
    else:
        text = f"{P}は{pos}が、{Q}は{neg}。"
        ok = fp and not fq
    ex = f"{P}は{gp}で{pos if fp else neg}。{Q}は{gq}で{pos if fq else neg}。"
    return text, ok, ex


