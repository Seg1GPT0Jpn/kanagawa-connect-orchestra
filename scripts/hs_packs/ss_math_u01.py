def ft(v):
    v = F(v)
    if v.denominator == 1:
        return str(v.numerator)
    return f"{'-' if v < 0 else ''}\\dfrac{{{abs(v.numerator)}}}{{{v.denominator}}}"


def fp(v):
    v = F(v)
    return str(v.numerator) if v.denominator == 1 else f"Rational({v.numerator},{v.denominator})"


def lin2(a, b, u="x", v="y"):
    """ax+by の LaTeX。"""
    out = ""
    for c, s in ((a, u), (b, v)):
        if c == 0:
            continue
        mag = "" if abs(c) == 1 else str(abs(c))
        sign = "-" if c < 0 else ("+" if out else "")
        out += sign + mag + s
    return out or "0"


def plus_sqrt(c, d, m):
    """c+d√m の LaTeX。"""
    if d == 0:
        return str(c)
    mag = "" if abs(d) == 1 else str(abs(d))
    head = "" if c == 0 else str(c)
    sign = "-" if d < 0 else ("+" if head else "")
    return f"{head}{sign}{mag}\\sqrt{{{m}}}"


def pw2(c):
    return f"{c}^2" if c >= 0 else f"({c})^2"


def one_of(xs):
    return f"${jn(xs)}$ のいずれか" if len(xs) > 1 else f"${xs[0]}$"


def residues(e, m):
    return sorted({pow(k, e, m) for k in range(m)})


def jn(xs):
    return ",\\ ".join(str(x) for x in xs)


