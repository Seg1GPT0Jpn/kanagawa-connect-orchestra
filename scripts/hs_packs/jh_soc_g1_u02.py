def _wave(mean, amp, south=False):
    """1〜12月の気温。北半球では7月ごろ最高、1月ごろ最低（南半球は逆）。"""
    base = [-1.0, -0.87, -0.5, 0.0, 0.5, 0.87, 1.0, 0.87, 0.5, 0.0, -0.5, -0.87]
    if south:
        base = base[6:] + base[:6]
    return [round(mean + amp * b) for b in base]


def _summer(south):
    return [5, 6, 7, 8, 9] if not south else [11, 12, 1, 2, 3]


def make_climate(r, kind, south=False):
    """気候の型 kind の、月平均気温（℃）と月降水量（mm）の架空データ。"""
    sm = _summer(south)
    if kind == "熱帯雨林気候":
        t = _wave(r.randint(26, 27), r.choice([0.5, 1]), south)
        p = [r.randint(14, 30) * 10 for _ in range(12)]
    elif kind == "サバナ気候":
        t = _wave(r.randint(25, 27), r.choice([2, 3]), south)
        p = [(r.randint(18, 32) * 10 if m in sm else r.randint(0, 3) * 5) for m in range(1, 13)]
    elif kind == "砂漠気候":
        t = _wave(r.randint(20, 24), r.randint(8, 11), south)
        p = [r.randint(0, 2) * 5 for _ in range(12)]
    elif kind == "ステップ気候":
        t = _wave(r.randint(8, 12), r.randint(12, 15), south)
        p = [(r.randint(7, 12) * 5 if m in sm else r.randint(2, 4) * 5) for m in range(1, 13)]
    elif kind == "地中海性気候":
        t = _wave(r.randint(15, 18), r.randint(7, 8), south)
        p = [(r.randint(0, 3) * 5 if m in sm else r.randint(14, 24) * 5) for m in range(1, 13)]
    elif kind == "西岸海洋性気候":
        t = _wave(r.randint(10, 12), r.randint(6, 7), south)
        p = [r.randint(10, 15) * 5 for _ in range(12)]
    elif kind == "温暖湿潤気候":
        t = _wave(r.randint(15, 17), r.randint(10, 12), south)
        p = [(r.randint(28, 44) * 5 if m in sm else r.randint(8, 14) * 5) for m in range(1, 13)]
    elif kind == "冷帯（亜寒帯）気候":
        t = _wave(r.randint(0, 3), r.randint(16, 19), south)
        p = [(r.randint(13, 18) * 5 if m in sm else r.randint(6, 9) * 5) for m in range(1, 13)]
    elif kind == "ツンドラ気候":
        t = _wave(r.randint(-12, -9), r.randint(13, 16), south)
        p = [(r.randint(5, 9) * 5 if m in sm else r.randint(1, 4) * 5) for m in range(1, 13)]
    else:  # 氷雪気候
        t = _wave(r.randint(-28, -22), r.randint(8, 12), south)
        p = [r.randint(1, 3) * 5 for _ in range(12)]
    return t, p


