def tape_svg(s, x0, n_marks, total):
    """透明半球の太陽の道すじを写しとった紙テープ。P＝日の出、Q＝日の入り。印は1時間ごと。"""
    sc = 300 / total
    o = ['<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 340 70" width="340" height="70" font-family="serif" font-size="11">',
         '<rect x="15" y="24" width="310" height="16" fill="#f7f1df" stroke="#333"/>']
    o.append('<line x1="20" y1="20" x2="20" y2="44" stroke="#c00" stroke-width="2"/><text x="16" y="16">P</text>')
    o.append(f'<line x1="{20 + total * sc:.1f}" y1="20" x2="{20 + total * sc:.1f}" y2="44" stroke="#c00" stroke-width="2"/><text x="{16 + total * sc:.1f}" y="16">Q</text>')
    for k in range(n_marks):
        x = 20 + (x0 + k * s) * sc
        o.append(f'<circle cx="{x:.1f}" cy="32" r="2.5" fill="#000"/>')
    o.append(f'<text x="18" y="62">P から最初の印まで {dec(x0)} cm、印の間隔はすべて {dec(s)} cm</text></svg>')
    return "".join(o)


