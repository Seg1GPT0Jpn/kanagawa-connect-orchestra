def north_svg(start_letter_angle=90):
    """北の空：北極星 P を中心に、30° ごとの位置 A〜L（A が真上、反時計回りに B, C, …）。"""
    cx, cy, R = 150, 120, 85
    o = ['<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 300 250" width="300" height="250" font-family="serif" font-size="12">',
         f'<circle cx="{cx}" cy="{cy}" r="{R}" fill="none" stroke="#999" stroke-dasharray="3 3"/>',
         f'<circle cx="{cx}" cy="{cy}" r="4" fill="#000"/><text x="{cx + 6}" y="{cy + 16}">北極星</text>',
         f'<line x1="10" y1="235" x2="290" y2="235" stroke="#333"/><text x="140" y="249">北</text><text x="272" y="230">東</text><text x="12" y="230">西</text>']
    for i in range(12):
        a = math.radians(start_letter_angle + 30 * i)
        x, y = cx + R * math.cos(a), cy - R * math.sin(a)
        o.append(f'<circle cx="{x:.1f}" cy="{y:.1f}" r="3" fill="#1f4e79"/>')
        o.append(f'<text x="{cx + (R + 13) * math.cos(a) - 4:.1f}" y="{cy - (R + 13) * math.sin(a) + 4:.1f}">{LET12[i]}</text>')
    o.append("</svg>")
    return "".join(o)


