                   ap="角度を 15° でわって時間に直す。西へ回るのは時間がたったあと。",
                   steps=[f"{ang}°÷15°＝{dec(hrs)}（時間）。", "西へ動くのは後の時刻。", f"{clock(t0)}＋{dec(hrs)} 時間＝{right}。"],
