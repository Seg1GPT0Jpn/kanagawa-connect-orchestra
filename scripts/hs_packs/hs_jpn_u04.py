def att_ok(v, aux):
    w, k = v["word"], v["kind"]
    if aux in ("る・らる", "す・さす"):
        return w in VOICE_OK
    if k == "ラ変" and aux in ("つ", "ぬ", "たり"):
        return False
    if w == "死ぬ" and aux == "つ":
        return False
    if w == "す" and aux == "ぬ":
        return False
    return True


def attach(v, aux):
    """動詞 v に助動詞 aux を付けた形と、その説明。"""
    k = v["kind"]
    if aux in ("る・らる", "す・さす"):
        a_dan = k in ("四段", "ナ変", "ラ変")
        base = ("る" if a_dan else "らる") if aux == "る・らる" else ("す" if a_dan else "さす")
        why = (f"「{base}」は未然形に付く。四段・ナ変・ラ変の未然形（ア段の音）には「{'る' if aux == 'る・らる' else 'す'}」、それ以外の動詞には「{'らる' if aux == 'る・らる' else 'さす'}」が付く")
        return v["f"][0] + base, why, 0
    conn = dict(ATT)[aux]
    if conn == 2:
        if k == "ラ変":
            return v["f"][3] + aux, f"「{aux}」は終止形に付くが、ラ変型の語には連体形に付く", 3
        return v["f"][2] + aux, f"「{aux}」は終止形に付く", 2
    if conn == 1:
        return v["f"][1] + aux, f"「{aux}」は連用形に付く", 1
    return v["f"][0] + aux, f"「{aux}」は未然形に付く", 0


