def build(kind, r):
    """句法の型 kind の練習用の文を一つ作る。"""
    if kind in ("未", "将", "当", "応", "宜", "須", "盍"):
        ch, first, second, mean, form = SD[kind]
        if r.random() < 0.6:
            v, o, og = r.choice(VO)
            kun = f"{ch}レ{v}レ{o}"
            base = f"{o}を{vform(v, form)}"
            obj = f"{og}を"
        else:
            v = r.choice(INTR)
            kun = f"{ch}レ{v}"
            base = vform(v, form)
            obj = ""
        kaki = f"{LEAD[ch]}{base}{second}"
        m = VK[v]
        tl = {"未": f"まだ{obj}{m[5]}。", "将": f"今にも{obj}{m[6]}とする。", "当": f"当然{obj}{m[4]}べきだ。", "応": f"きっと{obj}{m[4]}だろう。",
              "宜": f"{obj}{m[4]}のがよい。", "須": f"ぜひ{obj}{m[4]}必要がある。", "盍": f"どうして{obj}{m[5]}のか（{obj}{m[4]}のがよい）。"}[ch]
        return dict(kind=ch, kuho="再読文字", kun=kun, kaki=kaki, tl=tl, order=None,
                    v=[kaki.replace(LEAD[ch], LEAD_KANA[LEAD[ch]], 1)])
    if kind == "不":
        v, o, og = r.choice(VO)
        m = VK[v]
        return dict(kind=kind, kuho="否定", kun=f"不レ{v}レ{o}", kaki=f"{o}を{m[1]}ず", tl=f"{og}を{m[5]}。", order=[o, v, "不"], v=None)
    if kind == "勿":
        v, o, og = r.choice(VO_KINSHI)
        m = VK[v]
        ch = r.choice(["勿", "莫", "毋"])
        return dict(kind=kind, kuho="禁止", kun=f"{ch}レ{v}レ{o}", kaki=f"{o}を{m[2]}こと{ch}かれ", tl=f"{og}を{m[4]}な。",
                    order=[o, v, ch], v=[f"{o}を{m[2]}こと勿かれ".replace("勿", ch), f"{o}を{m[2]}ことなかれ"])
