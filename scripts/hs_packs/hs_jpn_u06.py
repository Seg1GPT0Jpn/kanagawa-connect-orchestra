def err_item(stem, wrong, step, etype, tempt, fix, expl, steps, ap, alt, pit, d=3, **kw):
    return desc(f"{stem}\n［ある生徒の解答］\n{wrong}\n上の解答の誤りを指摘し、正しく直しなさい。", fix, expl,
                [("誤りの箇所と理由を正しく指摘している", 2), ("正しい手順を示している", 3), ("正しい答えを書いている", 1)], d=d, p=6, lines=5,
                ap=ap, steps=steps, alt=alt, pc=[("誤りの指摘", 2), ("正しい手順", 3), ("正しい答え", 1)], pit=pit,
                err=dict(sol=wrong, step=step, type=etype, tempt=tempt, fix=fix), **kw)


def kaki_error(r):
    """書き下しの典型的な誤りを一つ作る。(訓読文, 誤答, 正答, 誤りの箇所, 誤りの種類, 誤りやすい理由)"""
    mode = r.choice(["drop", "form", "kanji", "shimu", "passive"])
    v, o, og = r.choice(VO)
    m = VK[v]
    if mode == "drop":
        ch = r.choice(["未", "当", "宜", "須"])
        x = SD[ch]
        right = f"{LEAD[ch]}{o}を{vform(v, x[4])}{x[2]}"
        wrong = f"{LEAD[ch]}{o}を{m[0]}"
        return (f"{ch}レ{v}レ{o}", wrong, right, "再読文字の二度目の読み", "notation", "再読文字を一度だけ読んで、返り点にしたがった二度目の読みを忘れやすい")
    if mode == "form":
        ch = r.choice(["当", "応", "宜", "須"])
        right = f"{LEAD[ch]}{o}を{m[0]}べし"
        wrong = f"{LEAD[ch]}{o}を{m[1]}べし"
        return (f"{ch}レ{v}レ{o}", wrong, right, "「べし」の前の動詞の活用形", "condition", "「ず」と同じように未然形に付けてしまい、「べし」が終止形に付くことを確かめない")
    if mode == "kanji":
        right = f"{o}を{m[1]}ず"
        wrong = f"{o}を{m[1]}不"
        return (f"不レ{v}レ{o}", wrong, right, "助動詞にあたる字の書き方", "notation", "訓読文の漢字をすべて漢字のまま書き下し文に残してしまう")
    if mode == "shimu":
        a, ag = r.choice([x for x in AGENTS if x[0] != o])
        right = f"{a}をして{o}を{m[1]}しむ"
        wrong = f"{a}をして{o}を{m[0]}"
        return (f"使三{a}{v}二{o}一", wrong, right, "使役の「使」の読み", "notation", "「使」を動詞の前に置かれた字として読み落とし、文末の「しむ」を書かない")
    v = r.choice(PASSIVE)
    m = VK[v]
    right = m[3]
    wrong = f"{m[0]}を見る"
    return (f"見レ{v}", wrong, right, "受身の「見」の読み", "concept", "「見」をいつも動詞「見る」と読み、受身の助動詞「る・らる」にあたることに気づかない")


