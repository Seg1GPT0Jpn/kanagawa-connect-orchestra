def factorize(n):
    out, p = {}, 2
    while n > 1:
        while n % p == 0:
            out[p] = out.get(p, 0) + 1
            n //= p
        p += 1
    return out


def factor_tex(n, f=None):
    f = f or factorize(n)
    return "\\times".join(f"{p}^{{{e}}}" if e > 1 else str(p) for p, e in sorted(f.items()))


