def sn(v):
    """かっこつきの符号つき整数：(+3), (-3)。"""
    return f"(+{v})" if v > 0 else f"({v})"


def ft(x):
    """Fraction / int → LaTeX。"""
    x = Fr(x)
    if x.denominator == 1:
        return str(x.numerator)
    s = "-" if x < 0 else ""
    return f"{s}\\dfrac{{{abs(x.numerator)}}}{{{x.denominator}}}"


def fpy(x):
    x = Fr(x)
    return str(x.numerator) if x.denominator == 1 else f"Rational({x.numerator},{x.denominator})"


def M(x):
    return f"${ft(x)}$"


def pick(correct, cands, k=4):
    """正答と誤答候補 [(text, reason, misconception)] から重複のない k 個の選択肢と why を作る。"""
    ch, why = [correct], {}
    for t, rs, mi in cands:
        if t in ch:
            continue
        ch.append(t)
        why[t] = (rs, mi)
        if len(ch) == k:
            break
    if len(ch) < k:
        raise ValueError("誤答候補が足りません")
    return ch, why


def near(v, used=()):
    """数値の誤答候補を補う（計算の数え違い）。"""
    out = []
    for d in (1, -1, 2, -2, 3, -3, 10, -10):
        w = v + d
        out.append((M(w), f"途中の加減で数を {abs(d)} だけ数え違えている。答えの見当（符号と大きさ）を確かめれば防げる。", "計算の数え違い"))
    return out


