@gen("basic_check", 5, ["computation"])
def a_addsub(r):
    k = r.choice([3, 3, 4])
    while True:
        vals = [r.choice([v for v in range(-12, 13) if v != 0]) for _ in range(k)]
        ops = ["+"] + [r.choice(["+", "-"]) for _ in range(k - 1)]
        if any(o == "-" and v < 0 for o, v in zip(ops, vals)) and any(v > 0 for v in vals):
            break
    style = r.choice(["paren", "paren", "plain"])
    if style == "paren":
        expr = sn(vals[0]) + "".join(f"{o}{sn(v)}" for o, v in zip(ops[1:], vals[1:]))
    else:
        expr = str(vals[0]) + "".join(f"{o}{sn(v) if v < 0 else v}" for o, v in zip(ops[1:], vals[1:]))
    s = [1 if o == "+" else -1 for o in ops]
    ans = sum(si * v for si, v in zip(s, vals))
    w1 = sum((-abs(v) if (o == "-" and v < 0) else si * v) for o, si, v in zip(ops, s, vals))
    w3 = sum(si * v for si, v in zip(s[1:], vals[1:])) - vals[0]
    terms = [si * v for si, v in zip(s, vals)]
    pos, neg = sum(t for t in terms if t > 0), sum(t for t in terms if t < 0)
    py = "".join(f"{o}({v})" for o, v in zip(ops, vals)).lstrip("+")
    cands = [(M(w1), "「$-(-a)$」を「$-a$」のままにしている。負の数をひくことは、その絶対値をたすことと同じである。", "負の数の減法で符号を変えていない"),
             (M(-ans), "答えの符号が逆になっている。正の項の和と負の項の和の、絶対値の大きいほうの符号をつける。", "和の符号の決め方の誤り"),
             (M(w3), "最初の数の符号を逆にしている。最初の項の符号もそのまま使う。", "先頭の項の符号の読み違い")] + near(ans)
    ch, why = pick(M(ans), cands)
    return mc(f"次の計算をした結果{MCQ}\n${expr}$", ch,
              f"ひく数の符号を変えて加法に直すと、正の項の和は ${pos}$、負の項の和は ${neg}$。よって ${pos}+({neg})={ans}$。", d=1,
              ap="減法をすべて加法に直し、正の項どうし・負の項どうしをまとめてから計算する。",
              steps=["減法は、ひく数の符号を変えて加法に直す。",
                     "加法だけの式にしたら、" + "、".join(f"${t}$" for t in terms) + " の和を求める。",
                     f"正の項の和 ${pos}$、負の項の和 ${neg}$ をたして ${ans}$。"],
              alt=["かっこを省いて項を並べた式（例：$-7+3$）に直し、左から順にたしていっても同じ答えになる。数直線上で右・左に動かして確かめてもよい。"],
              pc=[("減法を加法に直している", 1), ("正しい答えを選んでいる", 1)],
              pit=["$-(-a)$ を $-a$ としてしまう。", "答えの符号を、最初の項の符号と同じにしてしまう。"],
              why=why, chk=(py, str(ans)))


