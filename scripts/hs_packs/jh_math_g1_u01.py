    expr = f"-{p}^2+{q}\\times(-{rr})-(-{s})"
    P = p * p
    ans = -P - q * rr + s
    where = r.choice([0, 1, 2, 3])
    if where == 0:      # -p^2 を +p^2
        l1 = f"={P}+{q}\\times(-{rr})-(-{s})"
        l2 = f"={P}+(-{q * rr})+{s}"
        l3 = f"={P}-{q * rr}+{s}"
        l4 = f"={P - q * rr + s}"
        typ, tempt = "sign", f"$-{p}^2$ の指数が $-{p}$ 全体にかかると思い、$(-{p})^2$ と同じように計算した。"
        reason = f"①の行で $-{p}^2$ を $+{P}$ としている。$-{p}^2=-({p}\\times{p})=-{P}$。"
    elif where == 1:    # -(-s) を -s
        l1 = f"=-{P}+{q}\\times(-{rr})-(-{s})"
        l2 = f"=-{P}+(-{q * rr})-{s}"
        l3 = f"=-{P}-{q * rr}-{s}"
        l4 = f"={-P - q * rr - s}"
        typ, tempt = "sign", f"乗法の計算に気をとられ、$-(-{s})$ のかっこをはずすときに符号を変え忘れた。"
        reason = f"②の行で $-(-{s})$ を $-{s}$ としている。負の数をひくことは、その絶対値をたすことと同じで $+{s}$。"
    elif where == 2:    # +(-qr) を +qr
        l1 = f"=-{P}+{q}\\times(-{rr})-(-{s})"
        l2 = f"=-{P}+(-{q * rr})+{s}"
        l3 = f"=-{P}+{q * rr}+{s}"
        l4 = f"={-P + q * rr + s}"
