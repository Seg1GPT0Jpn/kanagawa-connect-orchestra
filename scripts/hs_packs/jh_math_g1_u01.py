    form = r.choice(["div_mul", "mul_div"])
    while True:
        b = r.choice([2, 3, 4, 5, 6, 8]) * r.choice([1, -1])
        c = r.choice([2, 3, 4, 5, 6, 7]) * r.choice([1, -1])
        q = r.choice([2, 3, 4, 5, 6, 7, 8, 9]) * r.choice([1, -1])
        if b < 0 or c < 0 or q < 0:
            break
    if form == "div_mul":
        A = b * q
        expr = f"{A if A > 0 else sn(A)}\\div{sn(b) if b < 0 else b}\\times{sn(c) if c < 0 else c}"
        ans = q * c
        wrong_order = Fr(A, b * c)
        py = f"({A})/({b})*({c})"
        w_ord_txt = "乗法・除法は左から順に計算する。$b\\times c$ を先に計算してはいけない。"
        w_mul = A * b * c
        w_mul_txt = "除法を乗法にしている。わる数は逆数にしてかける。"
    else:
        A = q
        expr = f"{A if A > 0 else sn(A)}\\times{sn(c) if c < 0 else c}\\div{sn(b) if b < 0 else b}"
