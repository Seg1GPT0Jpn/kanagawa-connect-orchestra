    return mc(f"Kさんは，${expr}$ を次のように計算した。\n{sol}\nKさんの計算で，誤りが最初に生じた行として最も適するものを，次の1〜4の中から1つ選び，その番号を答えなさい。",
              opts, f"{reason}正しく計算すると ${expr}=-{P}-{q * rr}+{s}={ans}$。", d=3, keep=True, ai=where,
              ap="1行ずつ、前の行と値が等しいかを確かめる。累乗・負の数の減法・かっこのはずし方は誤りやすい場所。",
              steps=[f"①：$-{p}^2=-{P}$ になっているか。", f"②：${q}\\times(-{rr})=-{q * rr}$、$-(-{s})=+{s}$ になっているか。",
                     f"③：$+(-{q * rr})=-{q * rr}$ になっているか。", f"④：$-{P}-{q * rr}+{s}={ans}$ になっているか。"],
              alt=["自分で最初から計算して答え " + f"${ans}$" + " を出し、Kさんの各行の値と比べて、最初にずれた行を探す。"],
              pc=[("誤りの行を正しく指摘している", 3), ("誤りの理由（規則）を説明できる", 2), ("正しい答えを求めている", 1)],
              pit=["誤りを引き継いだ後ろの行を「誤り」と判断してしまう。", "最後の答えだけを見て、途中の誤りを探さない。"],
              why=why, err=dict(sol=sol, step=right, type=typ, tempt=tempt, fix=f"${expr}=-{P}+(-{q * rr})+{s}=-{P}-{q * rr}+{s}={ans}$"),
              chk=(f"-{p}**2+{q}*(-{rr})-(-{s})", str(ans), None, "intermediate"))


