def _titled(fn):
    """本文を使う問題の問題文の頭に、どの文章についての問いかを示す（問ごとに複数の文章が混ざるため）。"""
    def wrap(r):
        it = fn(r)
        st = it.get("stim") or {}
        sid = st.get("id", "")
        if sid.startswith("RONSETSU-"):
            it["s"] = f"文章『{PK[sid[9:]]['title']}』について、" + it["s"]
        elif sid.startswith("HIKAKU-"):
            c = next(x for x in CMP if x["key"] == sid[7:])
            it["s"] = f"「{c['theme']}」についての文章Ⅰ・Ⅱについて、" + it["s"]
        return it
    return wrap


for _g in GENERATORS:
    _g.fn = _titled(_g.fn)
