def Q(s):
    """表示用の文字列 '2.0' → 厳密な有理数。"""
    return sp.Rational(s)


def dec(x):
    """有限小数で表せる値を小数の文字列にする。"""
    x = sp.Rational(x)
    d = Decimal(int(x.p)) / Decimal(int(x.q))
    s = format(d.normalize(), "f")
    return s


def sig(x, n=2):
    """有効数字 n 桁に四捨五入した表記。桁が大きいときは a×10^k の LaTeX を返す。"""
    x = sp.nsimplify(x)
    if x == 0:
        return "0"
    d = Decimal(str(sp.N(x, 40)))
    e = d.adjusted()
    r = d.quantize(Decimal(1).scaleb(e - n + 1), rounding=ROUND_HALF_UP)
    if r.adjusted() != e:
        e = r.adjusted()
        r = d.quantize(Decimal(1).scaleb(e - n + 1), rounding=ROUND_HALF_UP)
    if e >= n:
        return f"{format(r.scaleb(-e), 'f')}\\times10^{{{e}}}"
    return format(r, "f")


def is_exact(s, x):
    try:
        return "times" not in s and sp.Rational(s) == sp.nsimplify(x)
    except (TypeError, ValueError):
        return False


def numq(stem, x, expr, e, unit, n=2, **kw):
    """数値の答えの問題。x は厳密値、expr はそれを求める式（検算用）。"""
    s = sig(x, n)
    exact = is_exact(s, x)
    if not exact and "有効数字" not in stem:
        stem += f"有効数字{n}桁で答えなさい。"
    ans = s if "times" not in s else f"${s}$"
    chk = (expr, str(sp.nsimplify(x))) if exact else (expr, str(sp.nsimplify(x)), None, "intermediate")
    return num(stem, ans, e, unit=unit, chk=chk, **kw)


def t(x, n=2):
    """解説中に書く値（有効数字 n 桁）。"""
    s = sig(x, n)
    return s


