def Q(s, q=None):
    return sp.Rational(s) if q is None else sp.Rational(s, q)


def term(x):
    q = sp.Rational(x).q
    while q % 2 == 0:
        q //= 2
    while q % 5 == 0:
        q //= 5
    return q == 1


def dec(x):
    x = sp.Rational(x)
    d = Decimal(int(x.p)) / Decimal(int(x.q))
    return format(d.normalize(), "f")


def sig(x, n=2):
    x = sp.nsimplify(x)
    if x == 0:
        return "0"
    d = Decimal(str(sp.N(x, 40)))
    e = d.adjusted()
    r = d.quantize(Decimal(1).scaleb(e - n + 1), rounding=ROUND_HALF_UP)
    if r.adjusted() != e:
        e = r.adjusted()
        r = d.quantize(Decimal(1).scaleb(e - n + 1), rounding=ROUND_HALF_UP)
    if e >= n + 1 or e < -3:
        return f"{format(r.scaleb(-e), 'f')}\\times10^{{{e}}}"
    return format(r, "f")


def fv(x, n=2):
    """表示用の値：有限小数（4桁以内）ならそのまま、そうでなければ有効数字 n 桁。"""
    x = sp.Rational(sp.nsimplify(x))
    if term(x) and len(dec(x).replace(".", "").replace("-", "").lstrip("0")) <= 4:
        return pad(dec(x))
    return sig(x, n)


def pad(s):
    """有効数字が1桁しかない表示（4、0.5 など）を2桁（4.0、0.50）にそろえる。"""
    digits = s.replace("-", "").replace(".", "").lstrip("0")
    if len(digits) != 1 or s.strip("-") == "0":
        return s
    if "." in s:
        return s + "0"
    return s + ".0" if len(s.strip("-")) == 1 else s


def is_exact(s, x):
    try:
        return "times" not in s and sp.Rational(s) == sp.nsimplify(x)
    except (TypeError, ValueError):
        return False


def P(x):
    return f"({sp.nsimplify(x)})"


def numq(stem, x, expr, e, unit, n=2, **kw):
    """数値の答え。x は厳密値、expr はそれを求める式（検算用）。"""
    s = sig(x, n)
    exact = is_exact(s, x)
    if not exact and "有効数字" not in stem:
        stem += f"答えは有効数字{n}桁で求めなさい。"
    ans = s if "times" not in s else f"${s}$"
    xs = str(sp.nsimplify(x))
    chk = (expr, xs) if exact else (expr, xs, None, "intermediate")
    return num(stem, ans, e, unit=unit, chk=chk, **kw)


def mcv(stem, right, wrongs, e, **kw):
    """正答と誤答候補 [(文, 理由, 誤概念)] から、重複を除いて 4 択を作る。"""
    ch, why = [right], {}
    for w, reason, mis in wrongs:
        if w in ch:
            continue
        ch.append(w)
        why[w] = (reason, mis)
        if len(ch) == 4:
            break
    assert len(ch) == 4, (stem, ch)
    return mc(stem, ch, e, why=why, **kw)


