def unit_tex(d):
    parts = []
    for name, p in zip(("kg", "m", "s"), d):
        if p == 0:
            continue
        ps = "" if p == 1 else (f"^{{{p.numerator}}}" if p.denominator == 1 else f"^{{{p.numerator}/{p.denominator}}}")
        parts.append(f"\\mathrm{{{name}}}{ps}")
    return "$" + "\\,".join(parts) + "$" if parts else "なし（無次元）"


