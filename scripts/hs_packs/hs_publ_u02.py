def dhondt(votes, seats):
    """ドント式。(各党の議席, 当選した最小の商 (票, 除数)) を返す。境界で同値なら None。"""
    q = sorted(((v / d, i, v, d) for i, v in enumerate(votes) for d in range(1, seats + 1)), reverse=True)
    if q[seats - 1][0] == q[seats][0]:
        return None, None
    won = [0] * len(votes)
    for _, i, _, _ in q[:seats]:
        won[i] += 1
    last = q[seats - 1]
    return won, (last[2], last[3])


def divisor_alloc(votes, seats, divs):
    q = sorted(((v / d, i) for i, v in enumerate(votes) for d in divs[:seats]), reverse=True)
    if q[seats - 1][0] == q[seats][0]:
        return None
    won = [0] * len(votes)
    for _, i in q[:seats]:
        won[i] += 1
    return won


