def cut_frags(L, sites, circular):
    sites = sorted(sites)
    if circular:
        return [sites[i + 1] - sites[i] for i in range(len(sites) - 1)] + [L - sites[-1] + sites[0]]
    pts = [0] + sites + [L]
    return [pts[i + 1] - pts[i] for i in range(len(pts) - 1)]


def kb(x):
    return f"{x / 10:.1f}"


