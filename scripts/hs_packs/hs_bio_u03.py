def ms_ratio(n):
    """メセルソンとスタールの実験：14N に移して n 世代後の 中間：軽い の比（n≥1）。"""
    mid, light = 2, 2 ** n - 2
    g = gcd(mid, light) if light else mid
    return mid // g, light // g


