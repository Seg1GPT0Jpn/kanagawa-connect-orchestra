def mut_case(r):
    """(元の mRNA, 変異 mRNA, 種類) を返す。"""
    while True:
        body = [r.choice(SENSE) for _ in range(4)]
        mrna = ["AUG"] + body + [r.choice(["UAA", "UAG", "UGA"])]
        kind = r.choice(["syn", "mis", "non", "fs"])
        i = r.randint(1, 4)
        c = mrna[i]
        if kind == "fs":
            seq = "".join(mrna)
            pos = 3 * i + r.randint(0, 2)
            new = seq[:pos] + seq[pos + 1:] if r.random() < 0.5 else seq[:pos] + r.choice("UCAG") + seq[pos:]
            return "".join(mrna), new, "fs", i
        opts = []
        for p in range(3):
            for b in "UCAG":
                if b == c[p]:
                    continue
                nc = c[:p] + b + c[p + 1:]
                a0, a1 = CODE[c], CODE[nc]
                k = "non" if a1 == "*" else ("syn" if a1 == a0 else "mis")
                if k == kind:
                    opts.append(nc)
        if opts:
            nc = r.choice(opts)
            new = mrna[:i] + [nc] + mrna[i + 1:]
            return "".join(mrna), "".join(new), kind, i


