def pstim(keys, labels=None, mark=None):
    """作品を囲みの資料にする。keys が複数のときは a〜 などのラベルをつける。"""
    keys = [keys] if isinstance(keys, str) else list(keys)
    lines, gl, srcs = [], [], []
    for i, k in enumerate(keys):
        p = P[k]
        t = p["t"]
        if mark and i == 0:
            assert mark in t, (k, mark)
            t = t.replace(mark, f"[[u:{mark}]]", 1)
        head = f"{labels[i]}　" if labels else ""
        tail = f"　　{p['a']}" + (f"（『{p['c']}』）" if p["c"] else "")
        lines.append(head + t + tail)
        for g in p["g"]:
            if g not in gl:
                gl.append(g)
        srcs.append(f"『{p['c']}』" if p["c"] else p["a"])
    content = "\n".join(lines)
    sid = "POEM-" + str(zlib.crc32(content.encode()) % 10 ** 8)
    return stim(sid, content, "poem", source=None, glossary=gl or None, cp=PD)


def src_of(keys):
    keys = [keys] if isinstance(keys, str) else list(keys)
    out = []
    for k in keys:
        s = f"『{P[k]['c']}』" if P[k]["c"] else f"{P[k]['a']}の作品"
        if s not in out:
            out.append(s)
    return "・".join(out)


