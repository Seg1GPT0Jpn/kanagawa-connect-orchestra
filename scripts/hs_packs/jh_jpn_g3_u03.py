    kigo, sea, _, decoy = HAIKU[k]
    ok = f"季語：{kigo}　季節：{sea}"
    trap = next((x for x in KIGO_TRAP if x[0] == k), None)
    s1 = trap[1] if trap else r.choice([s for s in SEASONS if s != sea])
    wr = [(f"季語：{kigo}　季節：{s1}", f"季語は「{kigo}」で正しいが、季節は{sea}である。" + (trap[3] if trap else ""), "季語の季節の取り違え")]
