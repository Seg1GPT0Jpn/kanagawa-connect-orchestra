def wind_patterns_svg():
    """北半球の地上付近の風の吹き方の4パターン（P：時計回りに吹き出す、Q：反時計回りに吹きこむ、R：時計回りに吹きこむ、S：反時計回りに吹き出す）。"""
    pats = [("P", -1, 1), ("Q", 1, -1), ("R", -1, -1), ("S", 1, 1)]   # (ラベル, 回転 +1=反時計回り, 半径方向 +1=外向き)
    out = ['<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 440 130" width="440" height="130" font-family="serif" font-size="12">',
           '<defs><marker id="w" markerWidth="8" markerHeight="8" refX="6" refY="3" orient="auto"><path d="M0,0 L6,3 L0,6 z" fill="#1f4e79"/></marker></defs>']
    for k, (lab, rot, rad) in enumerate(pats):
        cx, cy = 55 + 110 * k, 60
        out.append(f'<circle cx="{cx}" cy="{cy}" r="32" fill="none" stroke="#999" stroke-dasharray="3 3"/><circle cx="{cx}" cy="{cy}" r="2" fill="#000"/>')
        for j in range(4):
            th = math.pi / 4 + j * math.pi / 2
            px, py = 32 * math.cos(th), 32 * math.sin(th)
            dx = rot * -math.sin(th) + rad * math.cos(th)
            dy = rot * math.cos(th) + rad * math.sin(th)
            n = math.hypot(dx, dy)
            dx, dy = dx / n * 11, dy / n * 11
            out.append(f'<line x1="{cx + px - dx:.1f}" y1="{cy - (py - dy):.1f}" x2="{cx + px + dx:.1f}" y2="{cy - (py + dy):.1f}" stroke="#1f4e79" stroke-width="1.6" marker-end="url(#w)"/>')
        out.append(f'<text x="{cx - 4}" y="{cy + 54}">{lab}</text>')
    out.append("</svg>")
    return "".join(out)


