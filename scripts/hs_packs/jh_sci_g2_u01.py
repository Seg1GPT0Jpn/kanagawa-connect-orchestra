def mol_svg(nh, no):
    """水素分子 nh 個と酸素分子 no 個のモデル図（○：水素原子、●：酸素原子）。"""
    W = 40 * (nh + no) + 40
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} 90" width="{W}" height="90" font-family="serif" font-size="11">']
    x = 20
    for _ in range(nh):
        out.append(f'<circle cx="{x}" cy="40" r="8" fill="#fff" stroke="#000"/><circle cx="{x + 14}" cy="40" r="8" fill="#fff" stroke="#000"/>')
        x += 40
    for _ in range(no):
        out.append(f'<circle cx="{x}" cy="40" r="11" fill="#777" stroke="#000"/><circle cx="{x + 18}" cy="40" r="11" fill="#777" stroke="#000"/>')
        x += 46
