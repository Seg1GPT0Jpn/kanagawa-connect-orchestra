def _titled(fn):
    """本文を使う問題の問題文の頭に、どの本文についての問いかを示す（問ごとに複数の本文が混ざるため）。"""
    def wrap(r):
        it = fn(r)
        sid = (it.get("stim") or {}).get("id", "")
        if sid.startswith("OKU-"):
            it["s"] = f"{_PART[sid.split('-')[1]]}の古文について、" + it["s"]
        elif sid.startswith("RONGO-"):
            kd = RGK[sid.split("-")[1]][0].split("「", 1)[1]
            it["s"] = f"『論語』の一節「{kd[:10]}…」について、" + it["s"]
        return it
    return wrap


for _g in GENERATORS:
    _g.fn = _titled(_g.fn)
