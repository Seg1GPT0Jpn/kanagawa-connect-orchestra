def mcq(stem, ok, wrongs, e, **kw):
    """wrongs=[(誤答の文, 理由, 誤概念)]。"""
    why = {w: (rs, mi) for w, rs, mi in wrongs}
    return mc(stem, [ok] + [w for w, _, _ in wrongs], e, why=why, **kw)


