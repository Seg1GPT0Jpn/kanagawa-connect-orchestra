@gen("thinking_writing", 4, ["application", "condition_check"])
def c_timeline(r):
    for _ in range(500):
        rows = sorted(r.sample(EVENTS, 4))
        ys = [y for y, _ in rows]
        if min(b - a for a, b in zip(ys, ys[1:])) < 10:
            continue
        rest = [e for e in EVENTS if e not in rows and all(abs(e[0] - y) >= 5 for y in ys)]
        if len(rest) >= 2:
            break
    marks = "①②③④"
    tbl = table([[marks[i], _yr(y), SHORT[y]] for i, (y, _) in enumerate(rows)], header=["", "年", "できごと"], caption="表")

    def pos_stmt(e, truth):
        y, _ = e
        k = sum(1 for yy in ys if yy < y)  # 0..4
        def span(kk):
            if kk == 0:
                return "表中の①より前"
            if kk == 4:
                return "表中の④より後"
            return f"表中の{marks[kk - 1]}と{marks[kk]}の間"
        if truth:
            return (f"「{SHORT[y]}」のは、{span(k)}である。", True, "")
        alt_k = r.choice([x for x in range(5) if x != k])
        return (f"「{SHORT[y]}」のは、{span(alt_k)}である。", False, f"「{SHORT[y]}」のは{_yr(y)}で、{span(k)}である。")

    def gap_stmt(truth):
        i, j = sorted(r.sample(range(4), 2))
        g = ys[j] - ys[i]
        n = (g // 10) * 10
        if n == 0:
            n = 5
        if truth:
            return (f"表中の{marks[i]}から{marks[j]}までには、{n}年以上の年月がたっている。", True, "")
        n2 = n + r.choice([30, 50, 100])
        return (f"表中の{marks[i]}から{marks[j]}までには、{n2}年以上の年月がたっている。", False, f"{marks[i]}は{_yr(ys[i])}、{marks[j]}は{_yr(ys[j])}で、その差は{g}年である。")

    ex_ = r.sample(rest, 2)
    st = [pos_stmt(ex_[0], True), pos_stmt(ex_[1], False)] if r.random() < 0.5 else [pos_stmt(ex_[0], False), pos_stmt(ex_[1], True)]
    st += [gap_stmt(True), gap_stmt(False)]
    r.shuffle(st)
    e = "表の年は " + "、".join(f"{marks[i]}{_yr(y)}" for i, y in enumerate(ys)) + "。" + "".join(s[2] for s in st if not s[1])
    return pick2("Kさんは、古代のおもなできごとを、次の表にまとめた。表と、表にないできごとの時期について述べた", st, e, d=4, tbl=tbl,
                 ap="表のできごとの年を確かめ、表にないできごとの年を思い出して、表のどこに入るかを考える。年数の差は引き算で確かめる。",
                 steps=["表の①～④の年を確かめる。", "表にないできごとの年を思い出し、表の中の位置を決める。", "年数の差の文は、引き算で確かめる。", "正しい文2つの組み合わせを選ぶ。"],
                 alt=["表の右に、表にないできごとを書きこんだ年表をつくってから、文を1つずつ判断する。"],
                 pc=[("表にないできごとの時期を正しく判断している", 3), ("年数の差を正しく計算している", 3), ("正しい組み合わせを選んでいる", 2)],
                 pit=["「以上」の意味を読み落とし、年数の差の判断を誤る。", "表の番号と年の対応を取り違える。"],
                 chk=(f"{ys[3]}-{ys[0]}", str(ys[3] - ys[0]), None, "intermediate"))


