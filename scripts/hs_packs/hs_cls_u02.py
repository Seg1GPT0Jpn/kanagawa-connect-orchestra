KAISHAKU = ["KOMACHI", "KARA", "YUKIHIRA", "KOSHIKIBU", "HITOMARO", "MUNEYUKI", "ISE", "KONU", "BETTO", "YASUHIDE", "TATSUTA", "SANEKATA", "KANESUKE"]


def shuji_of(k):
    out = []
    for kk, word, right, _, dbl in KAKE:
        if kk == k:
            out.append(f"掛詞「{word}」（{right}）")
    for kk, jo, target, how, _ in JO:
        if kk == k:
            out.append(f"序詞「{jo}」（{how}で「{target}」を導く）")
    for kk, center, right, _, _ in ENGO:
        if kk == k:
            out.append(f"縁語（{center}：{right}）")
    return out


