def tree_case(r):
    names = r.sample(["ア", "イ", "ウ", "エ"], 4)
    h1 = r.randint(2, 8)
    h2 = h1 + r.randint(2, 8)
    h3 = h2 + r.randint(2, 8)
    a, b, c, d = names
    shape = r.choice(["ladder", "balanced"])
    D = {}
    def setd(x, y, v):
        D[(x, y)] = D[(y, x)] = v
    if shape == "ladder":
        setd(a, b, 2 * h1)
        setd(a, c, 2 * h2); setd(b, c, 2 * h2)
        for x in (a, b, c):
            setd(x, d, 2 * h3)
        first, pair = d, (a, b)
    else:
        setd(a, b, 2 * h1); setd(c, d, 2 * h2)
        for x in (a, b):
            for y in (c, d):
                setd(x, y, 2 * h3)
        first, pair = None, (a, b)
    return names, D, shape, first, pair


