def mcw(stem, right, wrongs, e, **kw):
    """wrongs = [(誤答, 理由, 誤概念)]。why を自動で付ける。"""
    return mc(stem, [right] + [w[0] for w in wrongs], e, why={w[0]: (w[1], w[2]) for w in wrongs}, **kw)


