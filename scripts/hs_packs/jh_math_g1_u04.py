def _norm(s):
    return re.sub(r"\s+", "", unicodedata.normalize("NFKC", s))


def MC(stem, right, cands, e, k=3, **kw):
    """正答 right と誤答候補 [(文, 理由, 誤概念)] から、重複を除いて k 個の誤答を選ぶ。"""
    seen, ws = {_norm(right)}, []
    for t, why, mis in cands:
        if _norm(t) in seen:
            continue
        seen.add(_norm(t))
        ws.append((t, why, mis))
        if len(ws) == k:
            break
    assert len(ws) == k, (stem, right, cands)
    return mc(stem, [right] + [w[0] for w in ws], e, why={w[0]: (w[1], w[2]) for w in ws}, **kw)


def ftex(v):
    v = Fr(v)
    if v.denominator == 1:
        return str(v.numerator)
    s = "-" if v < 0 else ""
    return f"{s}\\dfrac{{{abs(v.numerator)}}}{{{v.denominator}}}"


def fpy(v):
    v = Fr(v)
    return str(v.numerator) if v.denominator == 1 else f"Rational({v.numerator},{v.denominator})"


def MARK(stem, v, e, expr, **kw):
    """あいう方式（0〜9 のマーク）で答える数値問題。v は 0 以上の整数か既約分数。"""
    v = Fr(v)
    assert v >= 0
    if v.denominator == 1:
        n = int(v)
        return num(stem, str(n), e, mark=("int", n), chk=(expr, str(n), None, "answer"), **kw)
    p, q = v.numerator, v.denominator
    return num(stem, f"${ftex(v)}$", e, mark=("frac", p, q), chk=(expr, f"Rational({p},{q})", None, "answer"), **kw)


def lin(a):
    """y=ax の表記。"""
    a = Fr(a)
    if a == 1:
        return "$y=x$"
    if a == -1:
        return "$y=-x$"
    return f"$y={ftex(a)}x$"


def inv(a):
    """y=a/x の表記。"""
    a = Fr(a)
    s = "-" if a < 0 else ""
    return f"$y={s}\\dfrac{{{ftex(abs(a))}}}{{x}}$" if a.denominator == 1 else f"$y={ftex(a)}\\div x$"


def red(p, q):
    """分数 p/q と、約分できるときはその結果。"""
    v = Fr(p, q)
    head = f"\\dfrac{{{p}}}{{{q}}}"
    return head if (v.numerator == p and v.denominator == q) else f"{head}={ftex(v)}"


def pt(x, y):
    return f"$({ftex(x)},\\,{ftex(y)})$"


def rng_pm(r, lo, hi):
    return r.choice([-1, 1]) * r.randint(lo, hi)


