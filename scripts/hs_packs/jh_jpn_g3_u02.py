def mcq(stem, ok, wrongs, e, **kw):
    """wrongs = [(誤答, 理由, 誤概念)]"""
    why = {w: (rs, mi) for w, rs, mi in wrongs}
    return mc(stem, choices(ok, [w for w, _, _ in wrongs]), e, why=why, **kw)


