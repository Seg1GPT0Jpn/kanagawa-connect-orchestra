def _f(v):
    return f"{v:.1f}".rstrip("0").rstrip(".")


def sector_svg(deg, label_r="", label_a=""):
    """中心角 deg のおうぎ形の SVG。"""
    R, cx, cy = 70, 90, 95
    a0 = math.radians(90 - deg / 2)
    a1 = math.radians(90 + deg / 2)
    x0, y0 = cx + R * math.cos(a0), cy - R * math.sin(a0)
    x1, y1 = cx + R * math.cos(a1), cy - R * math.sin(a1)
    large = 1 if deg > 180 else 0
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 180 180" width="180" height="180" font-family="serif" font-size="12">'
            f'<path d="M{cx},{cy} L{_f(x0)},{_f(y0)} A{R},{R} 0 {large} 0 {_f(x1)},{_f(y1)} Z" fill="#e6eef7" stroke="#000" stroke-width="1.2"/>'
            f'<text x="{cx - 4}" y="{cy + 16}">O</text><text x="{_f((cx + x0) / 2 + 4)}" y="{_f((cy + y0) / 2 + 12)}">{label_r}</text>'
            f'<text x="{cx - 10}" y="{cy - 14}">{label_a}</text></svg>')


