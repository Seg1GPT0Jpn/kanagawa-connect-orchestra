def choices(correct, wrongs):
    """正答を先頭に、誤答は順序を正規化して並べる（同じ組み合わせが別の問題として数えられないように）。"""
    return [correct] + sorted(wrongs)


def mcq(stem, correct, wy, e, **kw):
    """wy = {誤答の選択肢の文: (理由, 誤概念)}。選択肢は正答＋wy のキー。"""
    kw.pop("why", None)
    return mc(stem, choices(correct, list(wy)), e, why=wy, **kw)


