def poly_pairs():
    out = []
    for word, senses in POLY.items():
        for i, (g1, e1) in enumerate(senses):
            for j, (g2, e2) in enumerate(senses):
                if i == j:
                    continue
                body = f"{g1}という意味で、Ｂは{g2}"
                if 25 <= len(body) <= 35:
                    out.append((word, i, j))
    return out


