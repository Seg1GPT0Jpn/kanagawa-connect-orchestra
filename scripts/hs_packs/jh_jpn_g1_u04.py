def pair_item(stem, stmts, e, **kw):
    """stmts=[(文, 正誤, 理由)] 6文（正しいものは2つ）。"""
    lab = "abcdef"
    body = "\n".join(f"{lab[i]}　{s[0]}" for i, s in enumerate(stmts))
    right = [lab[i] for i, s in enumerate(stmts) if s[1]]
    ok = f"{right[0]}と{right[1]}"
    pairs = [f"{a}と{b}" for a, b in itertools.combinations(lab, 2)]
    return ok, pairs, body, {lab[i]: s for i, s in enumerate(stmts)}


