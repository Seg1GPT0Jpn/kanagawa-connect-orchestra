XY_CHOICES = ["X：正　Y：正", "X：正　Y：誤", "X：誤　Y：正", "X：誤　Y：誤"]


def xy_item(stem, x, y, e, **kw):
    """x, y = (文, 正誤, 理由)。"""
    ok = f"X：{'正' if x[1] else '誤'}　Y：{'正' if y[1] else '誤'}"
    why = {}
    for c in XY_CHOICES:
        if c == ok:
            continue
        bad = []
        if (c[2] == "正") != x[1]:
            bad.append(f"X は{'正しい' if x[1] else '誤り'}。{x[2]}")
        if (c[6] == "正") != y[1]:
            bad.append(f"Y は{'正しい' if y[1] else '誤り'}。{y[2]}")
        why[c] = ("　".join(bad), "本文の内容との照合の誤り")
    return mc(stem + f"\nX　{x[0]}\nY　{y[0]}", XY_CHOICES, e, ai=XY_CHOICES.index(ok), keep=True, why=why, **kw)


