def rules_text(code):
    return "、さらに".join(RULE[c] for c in code.split("+"))


def kana_why(hist, modern, code, w):
    base = hist.split("（")[0]
    if w == base:
        return (f"もとの歴史的仮名遣いのままで、きまりを当てはめていない。{rules_text(code)}ので「{modern}」。", "きまりの当てはめ忘れ")
    if w[0] != base[0] and base[0] in "はひふへほ":
        return (f"語頭の「{base[0]}」は直さない。語頭以外だけを直すので「{modern}」。", "語頭のハ行まで直す誤り")
    if code == "H" and w in ("ゆう",):
        return ("発音は「ユー」に近いが、現代仮名遣いでは「いう」と書く。", "発音どおりに書く誤り")
    if "+" in code:
        return (f"二つのきまり（{'・'.join(RULE_SHORT[c] for c in code.split('+'))}）の両方を正しく当てはめていない。正しくは「{modern}」。", "きまりの一部だけの当てはめ")
    return (f"きまりの当てはめ方が誤っている。{rules_text(code)}ので「{modern}」。", "きまりの当てはめ誤り")


