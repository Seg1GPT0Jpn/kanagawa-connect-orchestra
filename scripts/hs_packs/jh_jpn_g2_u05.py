def ktext(key):
    work, src, body, notes = TEXTS[key]
    gl = "　".join(f"{a}＝{b}" for a, b in notes)
    return f"{body}\n（「{work}」から。）\n（注）{gl}"


def kstem(key, q):
    return f"次の古文を読んで、あとの問いに答えなさい。\n{ktext(key)}\n{q}"


