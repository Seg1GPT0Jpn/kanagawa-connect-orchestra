# 暖かさの指数の区分（降水量が十分な場合）
WI_ZONES = [(0, 15, "ツンドラ"), (15, 45, "針葉樹林"), (45, 85, "夏緑樹林"), (85, 180, "照葉樹林"), (180, 240, "亜熱帯多雨林"), (240, 10 ** 6, "熱帯多雨林")]
SHAPE = [-1, -0.9, -0.5, 0, 0.5, 0.85, 1, 1, 0.7, 0.2, -0.3, -0.75]


def wi_of(ts):
    return sum(t - 5 for t in ts if t > 5)


def zone(wi):
    for lo, hi, name in WI_ZONES:
        if lo <= wi < hi:
            return name


def make_temps(r):
    """境界から離れた暖かさの指数をもつ、架空の月平均気温（整数）。"""
    while True:
        M = r.randint(-2, 26)
        A = r.randint(3, 13) if M > 20 else r.randint(8, 15)
        ts = [round(M + A * s) for s in SHAPE]
        w = wi_of(ts)
        if all(abs(w - b) >= 3 for b in (15, 45, 85, 180, 240)):
            return ts, w


