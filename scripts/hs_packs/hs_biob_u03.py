def mcw(stem, right, wrongs, e, **kw):
    """wrongs = [(誤答, 理由, 誤概念)]。"""
    return mc(stem, [right] + [w[0] for w in wrongs], e, why={w[0]: (w[1], w[2]) for w in wrongs}, **kw)


def err_item(stem, wrong, step, etype, tempt, fix, ans, expl, steps, ap, alt, pit, chk=None, d=3):
    return desc(f"{stem}\n［ある生徒の解答］\n{wrong}\n上の解答の誤りを指摘し、正しく直しなさい。", ans, expl,
                [("誤りの箇所と理由を正しく指摘している", 2), ("正しい考え方・途中の過程を示している", 3), ("最終的な答えが正しい", 1)], d=d, p=6, lines=6,
                ap=ap, steps=steps, alt=alt, pc=[("誤りの指摘", 2), ("正しい過程", 3), ("正しい答え", 1)], pit=pit,
                err=dict(sol=wrong, step=step, type=etype, tempt=tempt, fix=fix), chk=chk)


def fs(x):
    """Fraction を小数表記の文字列に（有限小数のみ）。"""
    x = Fraction(x)
    if x.denominator == 1:
        return str(x.numerator)
    return f"{float(x):.6f}".rstrip("0").rstrip(".")


def fpy(x):
    x = Fraction(x)
    return str(x.numerator) if x.denominator == 1 else f"Rational({x.numerator},{x.denominator})"


