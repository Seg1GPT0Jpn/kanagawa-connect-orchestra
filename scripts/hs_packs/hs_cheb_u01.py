SHELL_NAMES = ["K", "L", "M", "N"]


def shells(n):
    """電子 n 個（n ≦ 20）の電子配置 [K, L, M, N]。"""
    out = []
    for cap in (2, 8, 8, 2):
        k = min(n, cap)
        out.append(k)
        n -= k
    while out and out[-1] == 0:
        out.pop()
    return out


def shell_text(cfg):
    return "、".join(f"{SHELL_NAMES[i]} 殻 {c} 個" for i, c in enumerate(cfg))


def valence(sym):
    g = EL[sym][2]
    return 0 if g == 18 else (g if g <= 2 else g - 10)


def chg(q):
    if q == 0:
        return ""
    s = "+" if q > 0 else "-"
    return s if abs(q) == 1 else f"{abs(q)}{s}"


def ion(sym, q=0):
    c = chg(q)
    return f"\\mathrm{{{sym}}}^{{{c}}}" if c else f"\\mathrm{{{sym}}}"


def nuclide(sym, A, q=0):
    Z = EL[sym][1]
    c = chg(q)
    return f"{{}}^{{{A}}}_{{{Z}}}\\mathrm{{{sym}}}" + (f"^{{{c}}}" if c else "")


def sig(x, n=2):
    """有効数字 n 桁の表記（大きい数は a×10^k）。"""
    x = sp.nsimplify(x)
    d = Decimal(str(sp.N(x, 40)))
    e = d.adjusted()
    r = d.quantize(Decimal(1).scaleb(e - n + 1), rounding=ROUND_HALF_UP)
    if r.adjusted() != e:
        e = r.adjusted()
        r = d.quantize(Decimal(1).scaleb(e - n + 1), rounding=ROUND_HALF_UP)
    if e >= n or e < -3:
        return f"{format(r.scaleb(-e), 'f')}\\times10^{{{e}}}"
    return format(r, "f")


