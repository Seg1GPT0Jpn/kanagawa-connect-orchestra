def part(s, cnt, poly):
    if cnt == 1:
        return s
    return f"({s})_{cnt}" if poly else f"{s}_{cnt}"


def formula(cat, an):
    import math
    cs, _, cq, cp = cat
    as_, _, aq, ap_ = an
    l = math.lcm(cq, -aq)
    m, n = l // cq, l // -aq
    return f"\\mathrm{{{part(cs, m, cp)}{part(as_, n, ap_)}}}", m, n


