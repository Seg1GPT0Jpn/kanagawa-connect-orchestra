def empirical(f):
    p = parse(f)
    g = sp.gcd(sp.gcd(p["C"], p["H"]), p.get("O", 0))
    return "".join(f"{e}{p[e] // g if p[e] // g > 1 else ''}" for e in ("C", "H", "O") if p.get(e)), g


