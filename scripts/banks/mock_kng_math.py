def svg_boxplots(summaries, correct_note=None):
    """箱ひげ図4つを 2×2 に並べる。summaries=[(最小,Q1,中央,Q3,最大), ...]（目もり 10〜30 人）。"""
    W, H = 440, 210
    cw, ch = 210, 100
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}" font-family="serif" font-size="10">']
    for k, (mn, q1, md, q3, mx) in enumerate(summaries):
        ox = 10 + (k % 2) * (cw + 10)
        oy = 6 + (k // 2) * (ch + 4)
        x0, x1 = ox + 18, ox + cw - 12
        X = lambda v: x0 + (v - 10) * (x1 - x0) / 20  # noqa: E731
        out.append(f'<text x="{ox}" y="{oy + 12}" font-weight="bold">{k + 1}.</text>')
        ay = oy + 72
        out.append(f'<line x1="{x0}" y1="{ay}" x2="{x1}" y2="{ay}" stroke="#000" stroke-width="0.8"/>')
        for v in range(10, 31):
            t = 4 if v % 5 == 0 else 2
            out.append(f'<line x1="{_f(X(v))}" y1="{ay}" x2="{_f(X(v))}" y2="{ay + t}" stroke="#000" stroke-width="0.6"/>')
            if v % 5 == 0:
                out.append(f'<text x="{_f(X(v) - 5)}" y="{ay + 14}" font-size="9">{v}</text>')
        out.append(f'<text x="{x1 - 4}" y="{ay + 25}" font-size="9">(人)</text>')
        by, bh = oy + 30, 22
        cy = by + bh / 2
        out.append(f'<line x1="{_f(X(mn))}" y1="{cy}" x2="{_f(X(q1))}" y2="{cy}" stroke="#000" stroke-width="1"/>')
        out.append(f'<line x1="{_f(X(q3))}" y1="{cy}" x2="{_f(X(mx))}" y2="{cy}" stroke="#000" stroke-width="1"/>')
        for v in (mn, mx):
            out.append(f'<line x1="{_f(X(v))}" y1="{by + 5}" x2="{_f(X(v))}" y2="{by + bh - 5}" stroke="#000" stroke-width="1"/>')
        out.append(f'<rect x="{_f(X(q1))}" y="{by}" width="{_f(X(q3) - X(q1))}" height="{bh}" fill="#fff" stroke="#000" stroke-width="1"/>')
        out.append(f'<line x1="{_f(X(md))}" y1="{by}" x2="{_f(X(md))}" y2="{by + bh}" stroke="#000" stroke-width="1.2"/>')
    out.append("</svg>")
    return "".join(out)


