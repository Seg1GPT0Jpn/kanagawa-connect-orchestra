def mk(*letters):
    """あいう 方式の設問の決まり文句。"""
    ls = "".join(f"「{l}」" for l in letters)
    return f"次の［　］の中の{ls}にあてはまる数字をそれぞれ0〜9の中から1つずつ選び，その数字を答えなさい。"


def _f(v):
    return f"{v:.1f}".rstrip("0").rstrip(".")


