def svg_pyramid(path=False):
    """正四角錐 OABCD（図1：中点 N，M／図2：AP+PM の経路）。"""
    P = {"O": (130, 18), "A": (60, 190), "B": (170, 200), "C": (225, 150), "D": (115, 140)}
    mid = lambda p, q: ((P[p][0] + P[q][0]) / 2, (P[p][1] + P[q][1]) / 2)  # noqa: E731
    N, M = mid("O", "B"), mid("O", "C")
    out = ['<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 260 220" width="260" height="220" font-family="serif" font-size="12">']
    seg = lambda a, b, dash=False, w=1.2: out.append(  # noqa: E731
        f'<line x1="{_f(a[0])}" y1="{_f(a[1])}" x2="{_f(b[0])}" y2="{_f(b[1])}" stroke="#000" stroke-width="{w}"'
        + (' stroke-dasharray="4 3"' if dash else "") + "/>")
    for a, b in (("O", "A"), ("O", "B"), ("O", "C"), ("A", "B"), ("B", "C")):
        seg(P[a], P[b])
    for a, b in (("O", "D"), ("A", "D"), ("D", "C")):
        seg(P[a], P[b], dash=True, w=0.9)
    for name, (x, y), (dx, dy) in (("O", P["O"], (-4, -5)), ("A", P["A"], (-13, 6)), ("B", P["B"], (2, 14)),
                                    ("C", P["C"], (6, 4)), ("D", P["D"], (-14, -2))):
        out.append(f'<text x="{_f(x + dx)}" y="{_f(y + dy)}">{name}</text>')
    if path:
        # P は OB 上で OP:PB = 1:2（展開図での交点：O から 2cm）
        Pp = (P["O"][0] + (P["B"][0] - P["O"][0]) / 3, P["O"][1] + (P["B"][1] - P["O"][1]) / 3)
        out.append(f'<polyline points="{_f(P["A"][0])},{_f(P["A"][1])} {_f(Pp[0])},{_f(Pp[1])} {_f(M[0])},{_f(M[1])}" fill="none" stroke="#000" stroke-width="1.4"/>')
        out.append(f'<circle cx="{_f(Pp[0])}" cy="{_f(Pp[1])}" r="2.2" fill="#000"/><text x="{_f(Pp[0] - 14)}" y="{_f(Pp[1] + 4)}">P</text>')
        out.append(f'<circle cx="{_f(M[0])}" cy="{_f(M[1])}" r="2.2" fill="#000"/><text x="{_f(M[0] + 6)}" y="{_f(M[1])}">M</text>')
    else:
        for name, (x, y), dx in (("N", N, 6), ("M", M, 6)):
            out.append(f'<circle cx="{_f(x)}" cy="{_f(y)}" r="2.2" fill="#000"/><text x="{_f(x + dx)}" y="{_f(y)}">{name}</text>')
    out.append("</svg>")
    return "".join(out)


def _circle_fig():
    """問3(ア) 図1：円Oの周上の A，B，C，D（弧 AB=80°，BC=104°，CD=66°，DA=110°）と点 E，F。"""
    R = 2.5
    pt = lambda d: (round(R * math.cos(math.radians(d)), 3), round(R * math.sin(math.radians(d)), 3))  # noqa: E731
    A, B, Cc, D = pt(200), pt(280), pt(24), pt(90)

    def inter(p1, p2, p3, p4):
        (x1, y1), (x2, y2), (x3, y3), (x4, y4) = p1, p2, p3, p4
        den = (x1 - x2) * (y3 - y4) - (y1 - y2) * (x3 - x4)
        t = ((x1 - x3) * (y3 - y4) - (y1 - y3) * (x3 - x4)) / den
        return (round(x1 + t * (x2 - x1), 3), round(y1 + t * (y2 - y1), 3))

    E = inter(A, Cc, B, D)
    F = inter(B, A, D, (D[0] + Cc[0] - A[0], D[1] + Cc[1] - A[1]))
    return shape({"A": A, "B": B, "C": Cc, "D": D, "E": E, "F": F},
                 segments=[("A", "B"), ("B", "C"), ("C", "D"), ("A", "C"), ("B", "D"), ("F", "A"), ("F", "D")],
                 labels={"A": "A", "B": "B", "C": "C", "D": "D", "E": "E", "F": "F"},
                 circle=((0, 0), R), scale=26)


def _para_fig():
    """問3(エ) 図4：平行四辺形 ABCD，AE:ED=2:1，F は CD の中点，G は BE と AF の交点。"""
    A, B, Cc, D = (1.2, 3.0), (0.0, 0.0), (4.5, 0.0), (5.7, 3.0)
    E = (A[0] + (D[0] - A[0]) * 2 / 3, 3.0)
    F = ((Cc[0] + D[0]) / 2, 1.5)
    # BE: B + t(E-B)、AF: A + s(F-A) の交点（正方形で計算すると t = 3/4）
    G = (round(E[0] * 0.75, 3), round(E[1] * 0.75, 3))
    return shape({"A": A, "B": B, "C": Cc, "D": D, "E": (round(E[0], 3), E[1]), "F": F, "G": G},
                 segments=[("A", "B"), ("B", "C"), ("C", "D"), ("D", "A"), ("B", "E"), ("A", "F")],
                 labels={"A": "A", "B": "B", "C": "C", "D": "D", "E": "E", "F": "F", "G": "G"}, scale=30)


