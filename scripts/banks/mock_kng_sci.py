def S(w, h, body, fs=12):
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" width="{w}" height="{h}" '
            f'font-family="serif" font-size="{fs}">{DEFS}{body}</svg>')


def f2(v):
    return f"{v:.1f}".rstrip("0").rstrip(".")


def L(x1, y1, x2, y2, w=1.2, dash=None, col="#000"):
    d = f' stroke-dasharray="{dash}"' if dash else ""
    return f'<line x1="{f2(x1)}" y1="{f2(y1)}" x2="{f2(x2)}" y2="{f2(y2)}" stroke="{col}" stroke-width="{w}"{d}/>'


def A(x1, y1, x2, y2, w=1.6):
    return (f'<line x1="{f2(x1)}" y1="{f2(y1)}" x2="{f2(x2)}" y2="{f2(y2)}" stroke="#000" stroke-width="{w}" '
            f'marker-end="url(#sciar)"/>')


def T(x, y, s, a="middle", fs=None, b=False, extra=""):
    z = f' font-size="{fs}"' if fs else ""
    bb = ' font-weight="bold"' if b else ""
    return f'<text x="{f2(x)}" y="{f2(y)}" text-anchor="{a}"{z}{bb}{extra}>{s}</text>'


def VT(x, y, s, fs=10):
    """縦書きの軸ラベル（上端を (x, y) にそろえる）。"""
    spans = "".join(f'<tspan x="{f2(x)}" dy="{f2(fs * 1.08) if i else 0}">{ch}</tspan>' for i, ch in enumerate(s))
    return f'<text y="{f2(y + fs)}" font-size="{fs}" text-anchor="middle">{spans}</text>'


def R(x, y, w, h, fill="none", sw=1.2, rx=0, dash=None):
    d = f' stroke-dasharray="{dash}"' if dash else ""
    return (f'<rect x="{f2(x)}" y="{f2(y)}" width="{f2(w)}" height="{f2(h)}" rx="{rx}" fill="{fill}" '
            f'stroke="#000" stroke-width="{sw}"{d}/>')


def P(d, fill="none", sw=1.2, dash=None):
    dd = f' stroke-dasharray="{dash}"' if dash else ""
    return f'<path d="{d}" fill="{fill}" stroke="#000" stroke-width="{sw}"{dd}/>'


def C(cx, cy, r, fill="none", sw=1.2):
    return f'<circle cx="{f2(cx)}" cy="{f2(cy)}" r="{f2(r)}" fill="{fill}" stroke="#000" stroke-width="{sw}"/>'


def G(x, y, body, rot=None):
    r = f" rotate({rot})" if rot is not None else ""
    return f'<g transform="translate({f2(x)},{f2(y)}){r}">{body}</g>'


def PL(pts, w=1.4, dash=None):
    d = f' stroke-dasharray="{dash}"' if dash else ""
    p = " ".join(f"{f2(x)},{f2(y)}" for x, y in pts)
    return f'<polyline points="{p}" fill="none" stroke="#000" stroke-width="{w}"{d}/>'


def hatch_ground(x1, x2, y, n=None):
    out = [L(x1, y, x2, y, 1.2)]
    step = 10
    x = x1 + 4
    while x < x2:
        out.append(L(x, y, x - 6, y + 6, 0.7))
        x += step
    return "".join(out)


