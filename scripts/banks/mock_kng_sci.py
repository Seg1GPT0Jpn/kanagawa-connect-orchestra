def _crystal(x, y, s):
    return (f'<polygon points="{f2(x)},{f2(y - s)} {f2(x + s)},{f2(y)} {f2(x)},{f2(y + s)} {f2(x - s)},{f2(y)}" '
            f'fill="#fff" stroke="#000" stroke-width="0.9"/>')


def _dish_panel(px, py, kind, n):
    cx, cy = px + 80, py + 52
    out = [C(cx, cy, 46, fill="#f6f6f6")]
    big = [(-22, -14), (16, -20), (-4, 14), (24, 16)]
    small = [(-30 + (k % 8) * 8.5, -24 + (k // 8) * 9.5) for k in range(48)]
    if kind == 1:
        out += [_crystal(cx + dx, cy + dy, 11) for dx, dy in big]
    elif kind == 2:
        out += [_crystal(cx + dx, cy + dy, 2.6) for dx, dy in small]
    elif kind == 3:
        out += [_crystal(cx + dx, cy + dy, 2.6) for dx, dy in small if all(abs(dx - bx) > 13 or abs(dy - by) > 13 for bx, by in big[:2])]
        out += [_crystal(cx + dx, cy + dy, 10) for dx, dy in big[:2]]
    else:
        for k in range(10):
            out.append(L(cx - 4 + k, cy - 2, cx - 36 + k * 8, cy - 38 + (k % 3) * 4, 1))
            out.append(L(cx + k - 4, cy + 2, cx - 30 + k * 7, cy + 38 - (k % 3) * 4, 1))
    out.append(T(px + 18, py + 14, f"{n}．", fs=12))
    return "".join(out)


