def combo(slots, sep="　"):
    """空欄の組み合わせ。slots=[(ラベル, 正しい語, [(誤った語, 理由), ...]), ...]"""
    opts = [[(c, None)] + list(w) for (_, c, w) in slots]
    choices, why = [], {}
    for pick in itertools.product(*opts):
        text = sep.join(f"{lab}：{v}" for (lab, _, _), (v, _) in zip(slots, pick))
        choices.append(text)
        bad = [f"{lab}の「{v}」は誤り（{r}）。" for (lab, _, _), (v, r) in zip(slots, pick) if r]
        if bad:
            why[text] = "".join(bad)
    return choices, why


def seiho(truth, notes, sep="　"):
    """正誤の組み合わせ。truth={'X': True, ...}、notes={'X': 理由}"""
    labs = list(truth)
    choices, why = [], {}
    for pick in itertools.product([True, False], repeat=len(labs)):
        text = sep.join(f"{l}：{'正' if v else '誤'}" for l, v in zip(labs, pick))
        wrong = [l for l, v in zip(labs, pick) if v != truth[l]]
        if not wrong:
            choices.insert(0, text)
        else:
            choices.append(text)
            why[text] = "".join(f"{l}は{'正しい' if truth[l] else '誤り'}（{notes[l]}）。" for l in wrong)
    return choices, why


def perm(correct, years):
    """Ⅰ〜Ⅲの並べかえ。correct=["Ⅱ","Ⅲ","Ⅰ"]、years={"Ⅰ": "1588年", ...}"""
    right = "→".join(correct)
    order_note = "→".join(f"{r}（{years[r]}）" for r in correct)
    choices, why = [right], {}
    for p in itertools.permutations(sorted(correct, key="ⅠⅡⅢ".index)):
        t = "→".join(p)
        if t != right:
            choices.append(t)
            why[t] = f"年代の古い順は {order_note} である。"
    return choices, why


def pick(correct, distractors, facts, sep="，"):
    """文a〜fから正しいものを選ぶ組み合わせ。facts={'a': (正誤, 理由)}"""
    right = sep.join(correct)
    choices, why = [right], {}
    for d in distractors:
        t = sep.join(d)
        choices.append(t)
        bad = [x for x in d if not facts[x][0]]
        miss = [x for x in correct if x not in d]
        msg = "".join(f"{x}は誤り（{facts[x][1]}）。" for x in bad)
        msg += "".join(f"{x}は正しい文である。" for x in miss)
        why[t] = msg
    return choices, why


