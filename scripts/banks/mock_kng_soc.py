def poly(pts, proj, fill="#e6e6e6", stroke="#000", sw=0.9):
    s = " ".join(f"{proj(x, y)[0]:.1f},{proj(x, y)[1]:.1f}" for x, y in pts)
    return f'<polygon points="{s}" fill="{fill}" stroke="{stroke}" stroke-width="{sw}"/>'


